//! The Vivante GC7000 backend of the i.MX8MP, the sibling of [`crate::pvr`].
//!
//! `gl/draw.rs` resolves the current GL context into one
//! [`crate::backend::GlesDraw`] and calls the backend; this one translates it
//! into LOAD_STATE commands and a DRAW_INSTANCED in a command stream it builds
//! in GPU memory, and `flush` submits the stream through the OSAL. The GPU is
//! immediate mode: a frame is one command stream, there is no tiling, no
//! parameter buffer and no firmware.
//!
//! Everything GC7000-specific stays behind this module; the GL core never sees
//! a register. `VIVANTE_NOTES.md` says what is implemented and what only
//! silicon can settle.
//!
//! | module | what it does |
//! | --- | --- |
//! | [`regs`] | the registers and command words this backend writes, in address order |
//! | [`cmd`] | writing commands into a CPU-mapped buffer (LOAD_STATE, stall, draw) |
//! | [`state`] | what the three translation units share: the resolved draw and the frame |
//! | [`backend`] | frames, the render target, the rasteriser and pixel engine, the clear quad |
//! | [`rs_clear`] | a whole-target clear of colour, depth and stencil as the resolve engine's fill: whether a clear takes it, and its words |
//! | [`pe_zs`] | when the pixel engine may skip depth and stencil (PE_DEPTH_CONFIG DISABLE_ZS), clears included |
//! | [`pe_overwrite`] | the PE colour COMPONENTS mask and OVERWRITE bit of a draw |
//! | [`dedup`] | the state groups as the open stream last wrote them: a draw writes only the ones that differ |
//! | [`depth_format`] | the depth surface format, size and clear word per GL depth attachment (not yet used) |
//! | [`early_z`] | the early-depth rule: whether a draw may use it and the PE_DEPTH_CONFIG and RA_EARLY_DEPTH words for it (not yet used) |
//! | [`shader`] | the register wiring of the two stages, the instruction cache, the uniforms |
//! | [`texture`] | texture descriptors and sampler state |
//! | [`kick`] | the descriptor the OSAL's `submit()` takes |
//! | [`internal`] | generated by our compiler: the clear quad's two shaders and the mipmap quad's fragment program |
//! | [`mipmap`] | glGenerateMipmap on the GPU: a 2D RGBA8 chain drawn level by level into the storage |
//! | [`profile`] | the part: the ids, limits and feature bits of its hardware database row |
//! | [`tiled_copy`] | the tiled copies the texture unit samples instead of some linear textures |
//! | [`wide_target`] | the tiled shadow a 64-bit colour target is rendered into |
//! | [`layout`] | the address map of the 4x4-tiled and 64x64 super-tiled layouts: offsets, padding, stride, and whole-buffer linear-to-tiled conversion (not yet used) |
//! | [`ts`] | tile-status buffer sizes, fast-clear words, and the PE_MEM_CONFIG and TS_MEM_CONFIG values Mesa writes (not yet used) |
