//! ETC2 and EAC block decoding on the CPU: the ten OpenGL ES 3.0 compressed
//! formats (ES 3.0.6 3.8.5, table 3.19; the Khronos Data Format
//! Specification's ETC2 and EAC sections), for the formats the GL core
//! decodes at upload instead of storing as blocks
//! ([`crate::gl::texture`]: R11_EAC, SIGNED_R11_EAC, RG11_EAC,
//! SIGNED_RG11_EAC and both punch-through formats).
//!
//! Written from the format's specification; the tests compare every format
//! with the outputs of Mesa 26.2.1's own decoder (`src/mesa/main/
//! texcompress_etc.c`, `_mesa_unpack_etc2_format`), the vectors generated by
//! `tools/etc2/gen_mesa_vectors.py` (see `etc2_vectors.rs`).
//!
//! Texels are indexed `y * 4 + x` in a block. An RGB, RGBA or punch-through
//! block decodes to R, G, B, A bytes (the sRGB twins hold the same bytes:
//! the curve is the sampler's business, not the decoder's). An EAC channel
//! decodes to its 11-bit codeword: 0..=2047 for the unsigned formats,
//! -1023..=1023 for the signed ones; [`unorm11_to_float`] and
//! [`snorm11_to_float`] make the value GL defines from it.

/// The bytes of an 8-byte block (ETC1/ETC2 RGB, punch-through, EAC R11).
pub(crate) const BLOCK8: usize = 8;

const DISTANCES: [i32; 8] = [3, 6, 11, 16, 23, 32, 41, 64];

/// The ETC1 modifier table (ETC2's "opaque" one), by table index, then by
/// the pixel's (msb << 1 | lsb).
const MODIFIERS: [[i32; 4]; 8] = [
    [2, 8, -2, -8],
    [5, 17, -5, -17],
    [9, 29, -9, -29],
    [13, 42, -13, -42],
    [18, 60, -18, -60],
    [24, 80, -24, -80],
    [33, 106, -33, -106],
    [47, 183, -47, -183],
];

/// Punch-through blocks with the opaque bit clear: pixel index 2 is
/// transparent (and has no modifier), 0 is the base colour.
const MODIFIERS_TRANSPARENT: [[i32; 4]; 8] = [
    [0, 8, 0, -8],
    [0, 17, 0, -17],
    [0, 29, 0, -29],
    [0, 42, 0, -42],
    [0, 60, 0, -60],
    [0, 80, 0, -80],
    [0, 106, 0, -106],
    [0, 183, 0, -183],
];

/// EAC's modifier tables (the alpha channel's and R11/RG11's), by table
/// index, then by the 3-bit pixel index.
const EAC_MODIFIERS: [[i32; 8]; 16] = [
    [-3, -6, -9, -15, 2, 5, 8, 14],
    [-3, -7, -10, -13, 2, 6, 9, 12],
    [-2, -5, -8, -13, 1, 4, 7, 12],
    [-2, -4, -6, -13, 1, 3, 5, 12],
    [-3, -6, -8, -12, 2, 5, 7, 11],
    [-3, -7, -9, -11, 2, 6, 8, 10],
    [-4, -7, -8, -11, 3, 6, 7, 10],
    [-3, -5, -8, -11, 2, 4, 7, 10],
    [-2, -6, -8, -10, 1, 5, 7, 9],
    [-2, -5, -8, -10, 1, 4, 7, 9],
    [-2, -4, -8, -10, 1, 3, 7, 9],
    [-2, -5, -7, -10, 1, 4, 6, 9],
    [-3, -4, -7, -10, 2, 3, 6, 9],
    [-1, -2, -3, -10, 0, 1, 2, 9],
    [-4, -6, -8, -9, 3, 5, 7, 8],
    [-3, -5, -7, -9, 2, 4, 6, 8],
];

fn clamp255(v: i32) -> u8 {
    v.clamp(0, 255) as u8
}

fn ext4(v: u32) -> i32 {
    ((v << 4) | v) as i32
}

fn ext5(v: u32) -> i32 {
    ((v << 3) | (v >> 2)) as i32
}

fn ext6(v: u32) -> i32 {
    ((v << 2) | (v >> 4)) as i32
}

fn ext7(v: u32) -> i32 {
    ((v << 1) | (v >> 6)) as i32
}

/// A 5-bit channel plus the signed 3-bit delta in the low bits of `byte`'s
/// pair, as the differential mode adds them: (the sum, which GL's overflow
/// rules test).
fn diff_sum(byte: u8) -> i32 {
    const DELTA: [i32; 8] = [0, 1, 2, 3, -4, -3, -2, -1];
    i32::from(byte >> 3) + DELTA[usize::from(byte & 7)]
}

/// Decode a 64-bit ETC2 colour block to R, G, B, A texels. `punchthrough`
/// selects the RGB8_PUNCHTHROUGH_ALPHA1 interpretation of the bit that is
/// the differential flag in the other formats (the "opaque" bit there):
/// with it clear, pixel index 2 decodes to (0, 0, 0, 0). Any other block
/// has alpha 255.
pub(crate) fn rgb_block(b: &[u8; BLOCK8], punchthrough: bool) -> [[u8; 4]; 16] {
    let mut out = [[0u8; 4]; 16];
    let flag = b[3] & 2 != 0;
    let opaque = !punchthrough || flag;
    let indices = u32::from_be_bytes([b[4], b[5], b[6], b[7]]);
    let index_of = |x: usize, y: usize| -> usize {
        let bit = y + x * 4;
        (((indices >> (16 + bit)) & 1) << 1 | ((indices >> bit) & 1)) as usize
    };

    #[derive(Clone, Copy, PartialEq)]
    enum Mode {
        Individual,
        Differential,
        T,
        H,
        Planar,
    }
    /* the overflow tests apply to the differential mode of the colour
     * formats, and always to the punch-through one */
    let mode = if !flag && !punchthrough {
        Mode::Individual
    } else if !(0..=31).contains(&diff_sum(b[0])) {
        Mode::T
    } else if !(0..=31).contains(&diff_sum(b[1])) {
        Mode::H
    } else if !(0..=31).contains(&diff_sum(b[2])) {
        Mode::Planar
    } else {
        Mode::Differential
    };

    match mode {
        Mode::Individual | Mode::Differential => {
            let mut base = [[0i32; 3]; 2];
            for c in 0..3 {
                let v = b[c];
                if mode == Mode::Individual {
                    base[0][c] = ext4(u32::from(v >> 4));
                    base[1][c] = ext4(u32::from(v & 15));
                } else {
                    base[0][c] = ext5(u32::from(v >> 3));
                    base[1][c] = ext5(diff_sum(v) as u32);
                }
            }
            let tables = if opaque { &MODIFIERS } else { &MODIFIERS_TRANSPARENT };
            let table = [tables[usize::from(b[3] >> 5) & 7], tables[usize::from(b[3] >> 2) & 7]];
            let flipped = b[3] & 1 != 0;
            for y in 0..4 {
                for x in 0..4 {
                    let sub = usize::from(if flipped { y >= 2 } else { x >= 2 });
                    let idx = index_of(x, y);
                    out[y * 4 + x] = if !opaque && idx == 2 {
                        [0; 4]
                    } else {
                        let m = table[sub][idx];
                        [clamp255(base[sub][0] + m), clamp255(base[sub][1] + m), clamp255(base[sub][2] + m), 255]
                    };
                }
            }
        }
        Mode::T | Mode::H => {
            let (c0, c1);
            let dist;
            if mode == Mode::T {
                c0 = [
                    ext4(u32::from(((b[0] >> 1) & 0xc) | (b[0] & 3))),
                    ext4(u32::from(b[1] >> 4)),
                    ext4(u32::from(b[1] & 15)),
                ];
                c1 = [ext4(u32::from(b[2] >> 4)), ext4(u32::from(b[2] & 15)), ext4(u32::from(b[3] >> 4))];
                dist = DISTANCES[usize::from(((b[3] >> 1) & 6) | (b[3] & 1))];
            } else {
                c0 = [
                    ext4(u32::from((b[0] >> 3) & 15)),
                    ext4(u32::from(((b[0] & 7) << 1) | ((b[1] >> 4) & 1))),
                    ext4(u32::from((b[1] & 8) | ((b[1] & 3) << 1) | (b[2] >> 7))),
                ];
                c1 = [
                    ext4(u32::from((b[2] >> 3) & 15)),
                    ext4(u32::from(((b[2] & 7) << 1) | (b[3] >> 7))),
                    ext4(u32::from((b[3] >> 3) & 15)),
                ];
                /* the low distance bit is whether colour 0 >= colour 1 as the
                 * 12-bit value of the three nibbles */
                let key = |c: &[i32; 3]| (c[0] << 16) | (c[1] << 8) | c[2];
                dist = DISTANCES[usize::from((b[3] & 4) | ((b[3] & 1) << 1) | u8::from(key(&c0) >= key(&c1)))];
            }
            let mut paint = [[0u8; 3]; 4];
            for c in 0..3 {
                if mode == Mode::T {
                    paint[0][c] = clamp255(c0[c]);
                    paint[1][c] = clamp255(c1[c] + dist);
                    paint[2][c] = clamp255(c1[c]);
                    paint[3][c] = clamp255(c1[c] - dist);
                } else {
                    paint[0][c] = clamp255(c0[c] + dist);
                    paint[1][c] = clamp255(c0[c] - dist);
                    paint[2][c] = clamp255(c1[c] + dist);
                    paint[3][c] = clamp255(c1[c] - dist);
                }
            }
            for y in 0..4 {
                for x in 0..4 {
                    let idx = index_of(x, y);
                    out[y * 4 + x] =
                        if !opaque && idx == 2 { [0; 4] } else { [paint[idx][0], paint[idx][1], paint[idx][2], 255] };
                }
            }
        }
        Mode::Planar => {
            let o = [
                ext6(u32::from((b[0] >> 1) & 0x3f)),
                ext7(u32::from(((b[0] & 1) << 6) | ((b[1] >> 1) & 0x3f))),
                ext6(u32::from(((b[1] & 1) << 5) | (b[2] & 0x18) | ((b[2] & 3) << 1) | (b[3] >> 7))),
            ];
            let h = [
                ext6(u32::from(((b[3] & 0x7c) >> 1) | (b[3] & 1))),
                ext7(u32::from((b[4] >> 1) & 0x7f)),
                ext6(u32::from(((b[4] & 1) << 5) | ((b[5] >> 3) & 0x1f))),
            ];
            let v = [
                ext6(u32::from(((b[5] & 7) << 3) | ((b[6] >> 5) & 7))),
                ext7(u32::from(((b[6] & 0x1f) << 2) | ((b[7] >> 6) & 3))),
                ext6(u32::from(b[7] & 0x3f)),
            ];
            for y in 0..4i32 {
                for x in 0..4i32 {
                    let mut t = [0u8, 0, 0, 255];
                    for c in 0..3 {
                        t[c] = clamp255((x * (h[c] - o[c]) + y * (v[c] - o[c]) + 4 * o[c] + 2) >> 2);
                    }
                    out[(y * 4 + x) as usize] = t;
                }
            }
        }
    }
    out
}

/// The 16 three-bit pixel indices of an EAC block (bytes 2..8), texel
/// `y * 4 + x`. EAC numbers the texels column by column.
fn eac_indices(b: &[u8]) -> [usize; 16] {
    let bits = b[2..8].iter().fold(0u64, |a, &v| (a << 8) | u64::from(v));
    let mut out = [0usize; 16];
    for x in 0..4 {
        for y in 0..4 {
            let shift = 45 - 3 * (x * 4 + y);
            out[y * 4 + x] = ((bits >> shift) & 7) as usize;
        }
    }
    out
}

/// The alpha plane of an RGBA8 EAC block (the first 8 bytes of its 16). The
/// GL core stores RGBA8 EAC as blocks and decodes none of it; the decoder is
/// here for the tests against Mesa and for a back end that would decode it.
#[cfg_attr(not(test), allow(dead_code))]
pub(crate) fn eac_alpha(b: &[u8; BLOCK8]) -> [u8; 16] {
    let base = i32::from(b[0]);
    let mult = i32::from(b[1] >> 4);
    let table = &EAC_MODIFIERS[usize::from(b[1] & 15)];
    let idx = eac_indices(b);
    let mut out = [0u8; 16];
    for (o, i) in out.iter_mut().zip(idx) {
        *o = clamp255(base + table[i] * mult);
    }
    out
}

/// One 64-bit EAC channel block as 11-bit codewords: 0..=2047 for R11_EAC,
/// -1023..=1023 for SIGNED_R11_EAC. A zero multiplier counts as 1/8 (the
/// modifier is added unscaled); the signed base codeword -128 reads as -127.
pub(crate) fn eac11(b: &[u8; BLOCK8], signed: bool) -> [i16; 16] {
    let mult = i32::from(b[1] >> 4);
    let table = &EAC_MODIFIERS[usize::from(b[1] & 15)];
    let idx = eac_indices(b);
    let (base, lo, hi) = if signed {
        let s = i32::from(b[0] as i8).max(-127);
        (s * 8, -1023, 1023)
    } else {
        (i32::from(b[0]) * 8 + 4, 0, 2047)
    };
    let mut out = [0i16; 16];
    for (o, i) in out.iter_mut().zip(idx) {
        let m = if mult == 0 { table[i] } else { table[i] * mult * 8 };
        *o = (base + m).clamp(lo, hi) as i16;
    }
    out
}

/// The value GL defines for an unsigned 11-bit EAC codeword: c / 2047.
pub(crate) fn unorm11_to_float(c: i16) -> f32 {
    f32::from(c) / 2047.0
}

/// The value GL defines for a signed 11-bit EAC codeword: c / 1023, in [-1, 1].
pub(crate) fn snorm11_to_float(c: i16) -> f32 {
    (f32::from(c) / 1023.0).clamp(-1.0, 1.0)
}

