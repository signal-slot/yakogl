# gen_tables.py - turn extract.py's JSON into the Rust ISA tables.
#
#   tools/pco-isa/extract.py <mesa pco dir> build/isa.json
#   tools/pco-isa/gen_tables.py build/isa.json src/shaderc/online/isa_tables.rs
#
# The output is data only: bit sets (fields made of byte/bit pieces, and the
# instruction forms built out of them), the enumerations that name field
# values, which instruction forms are legal in which pipeline phase, and the
# operation table that says which form plus which constant field values is
# which operation.  src/shaderc/online/decode.rs and encode.rs walk these.

import json
import sys

XFORM = {
    None: "Identity",
    "{} - 1": "SubOne",       # [1..4]  -> [0..3]
    "{} % 16": "WrapMod16",   # [1..16] -> [1..15,0]
    "{} >> 1": "Shr1",        # a 32-bit offset with bit 0 clear
    "{} >> 2": "Shr2",        # an 8-bit value with bits 1:0 clear
}

SET_ORDER = ["igrp_hdr", "src", "iss", "dst", "main", "backend", "bitwise", "ctrl"]
PHASES = ["0", "1", "2", "2_pck", "2_tst", "2_mov", "backend", "ctrl"]


def ident(s):
    return s.upper().replace(".", "_").replace("-", "_")


def emit(doc, out):
    w = out.write
    w("// SPDX-License-Identifier: Apache-2.0 AND MIT\n")
    w("// SPDX-FileCopyrightText: 2024 Imagination Technologies Ltd.\n")
    w("//\n")
    w("// isa_tables.rs - GENERATED by tools/pco-isa/gen_tables.py. DO NOT EDIT.\n")
    w("//\n")
    w("// The PowerVR Rogue USC encoding, as data.  The facts are extracted from\n")
    w("// Mesa's pco compiler (src/imagination/pco, Copyright (c) Imagination\n")
    w("// Technologies Ltd., MIT licence), whose pco_isa.py and pco_map.py declare\n")
    w("// the encoding rather than implement it; tools/pco-isa/extract.py reads those\n")
    w("// declarations and this file is written from them.  No Mesa source is\n")
    w("// vendored here.\n")
    w("//\n")
    w("// Regenerate with tools/pco-isa/README.md's two commands after a Mesa bump,\n")
    w("// and let the round-trip test over the offline blob table judge the result.\n")
    w("\n")
    w("#![cfg_attr(rustfmt, rustfmt_skip)]\n")
    w("\n")
    w("use super::isa::{BitSet, EnumDef, Field, FieldUse, OpEnc, Piece, Variant, Xform};\n")
    w("\n")

    # --- enumerations -------------------------------------------------------
    enums = doc["enums"]
    enum_index = {}
    w("/// Every enumeration a field value can be named by.\n")
    w("pub static ENUMS: &[EnumDef] = &[\n")
    for i, name in enumerate(sorted(enums)):
        e = enums[name]
        enum_index[name] = i
        elems = ", ".join(
            f'({el["value"]}, "{el["string"] or el["name"]}")'
            for el in e["elems"]
            if el["string"] is not None or True
        )
        w(f'    EnumDef {{ name: "{name}", elems: &[{elems}] }},\n')
    w("];\n\n")

    # --- bit sets -----------------------------------------------------------
    field_index = {}
    for sname in SET_ORDER:
        bs = doc["bit_sets"][sname]
        fields = list(bs["fields"].values())
        field_index[sname] = {f["name"]: i for i, f in enumerate(fields)}
        w(f"static {ident(sname)}_FIELDS: &[Field] = &[\n")
        for f in fields:
            pieces = ", ".join(
                f'Piece {{ byte: {p["byte"]}, hi: {p["hi"]}, lo: {p["lo"]} }}'
                for p in f["pieces"]
            )
            t = f["type"]
            xf = XFORM[t["encode"]]
            en = t["enum"]
            enr = f"Some({enum_index[en]})" if en is not None else "None"
            rs = "None" if f["reserved"] is None else f'Some({f["reserved"]})'
            w(
                f'    Field {{ name: "{f["name"]}", pieces: &[{pieces}], '
                f'bits: {t["num_bits"]}, xform: Xform::{xf}, enum_id: {enr}, '
                f"reserved: {rs} }},\n"
            )
        w("];\n\n")

        w(f"static {ident(sname)}_VARIANTS: &[Variant] = &[\n")
        for st in bs["structs"]:
            uses = []
            for e in st["encode"]:
                fi = field_index[sname][e["field"]]
                if e["kind"] == "fixed":
                    uses.append(
                        f'FieldUse {{ field: {fi}, fixed: Some({e["value"]}), name: "" }}'
                    )
                else:
                    uses.append(
                        f'FieldUse {{ field: {fi}, fixed: None, name: "{e["struct_field"]}" }}'
                    )
            spec = st["src_spec"]
            up = "None" if spec is None else ("Some(true)" if spec["is_upper"] else "Some(false)")
            w(
                f'    Variant {{ name: "{st["name"]}", bytes: {st["bytes"]}, '
                f'upper_src: {up}, uses: &[{", ".join(uses)}] }},\n'
            )
        w("];\n\n")

    w("/// The bit sets, in the order of [`BitSetId`](super::isa::BitSetId).\n")
    w("pub static BIT_SETS: &[BitSet] = &[\n")
    for sname in SET_ORDER:
        w(
            f'    BitSet {{ name: "{sname}", fields: {ident(sname)}_FIELDS, '
            f"variants: {ident(sname)}_VARIANTS }},\n"
        )
    w("];\n\n")

    # --- operations ---------------------------------------------------------
    # (phase, bit set, variant) plus the constant field values that tell two
    # operations sharing one instruction form apart.
    var_index = {
        s: {st["cname"]: i for i, st in enumerate(doc["bit_sets"][s]["structs"])}
        for s in SET_ORDER
    }
    set_of_variant = {}
    for s in SET_ORDER:
        for st in doc["bit_sets"][s]["structs"]:
            set_of_variant[st["cname"]] = s

    rows = []
    for e in doc["encode_maps"]:
        for ph in e["phases"]:
            for enc in e["encodings"]:
                s = set_of_variant[enc["struct"]]
                consts = []
                for f, v in sorted(enc["consts"].items()):
                    consts.append(f'("{f}", {v})')
                rows.append(
                    f'    OpEnc {{ name: "{e["op"]}", phase: {PHASES.index(ph)}, '
                    f"set: {SET_ORDER.index(s)}, variant: {var_index[s][enc['struct']]}, "
                    f'consts: &[{", ".join(consts)}] }},\n'
                )
    w("/// Which instruction form, in which phase, is which operation.\n")
    w("pub static OPS: &[OpEnc] = &[\n")
    for r in rows:
        w(r)
    w("];\n\n")

    # --- phase -> the instruction forms legal there --------------------------
    allow = {ph: {} for ph in PHASES}
    for e in doc["encode_maps"]:
        for ph in e["phases"]:
            for enc in e["encodings"]:
                s = set_of_variant[enc["struct"]]
                allow[ph].setdefault(s, set()).add(var_index[s][enc["struct"]])
    # --- control op -> the forms it can take ---------------------------------
    # A control instruction's own bytes cannot always say which it is (four of
    # the forms are zero bytes long), so the header's ctrlop field selects.
    ctrl_variants = doc["bit_sets"]["ctrl"]["structs"]
    ctrlop = doc["enums"]["ctrlop"]
    w("/// The control-instruction forms each `ctrlop` value selects. Four of\n")
    w("/// them encode in no bytes at all, so nothing but this field says which\n")
    w("/// instruction a control group holds.\n")
    w("pub static CTRLOP_VARIANTS: &[(u32, &[u16])] = &[\n")
    for el in sorted(ctrlop["elems"], key=lambda e: e["value"]):
        nm = "branch" if el["name"] == "b" else el["name"]
        idxs = [
            i
            for i, st in enumerate(ctrl_variants)
            if st["name"] == nm or st["name"].startswith(nm + "_")
        ]
        if not idxs:
            continue
        w(f'    ({el["value"]}, &{idxs!r}),\n'.replace("'", ""))
    w("];\n\n")

    w("/// Per phase, and per bit set, the variant indices that phase may hold.\n")
    w("/// The same instruction form means different operations in different\n")
    w("/// phases (main_op 6 is FMAD in phase 0 and MOVC in the move phase), so\n")
    w("/// the decoder needs the phase before it can read the bytes.\n")
    w("pub static PHASE_VARIANTS: &[&[(u8, &[u16])]] = &[\n")
    for ph in PHASES:
        inner = ", ".join(
            f'({SET_ORDER.index(s)}, &{sorted(v)!r})'.replace("[", "[").replace("'", "")
            for s, v in sorted(allow[ph].items())
        )
        w(f"    &[{inner}],\n")
    w("];\n")


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_tables.py <isa.json> <out.rs>")
    doc = json.load(open(sys.argv[1]))
    with open(sys.argv[2], "w") as f:
        emit(doc, f)
    print(f"wrote {sys.argv[2]}", file=sys.stderr)


if __name__ == "__main__":
    main()
