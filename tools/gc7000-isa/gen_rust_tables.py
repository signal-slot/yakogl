# gen_rust_tables.py - turn the committed GC7000 ISA table into the Rust tables.
#
#   tools/gc7000-isa/extract.py -o docs/online-shaderc/isa/gc7000-isa.json
#   tools/gc7000-isa/gen_rust_tables.py docs/online-shaderc/isa/gc7000-isa.json \
#       src/shaderc/online/vivante/isa_tables.rs
#   cargo test --no-default-features --features host-test,gpu-vivante,shaderc-online vivante::
#
# The table is docs/online-shaderc/isa/gc7000-isa.json, extracted from Mesa's
# etnaviv ISA description by tools/gc7000-isa/extract.py.  There is one table
# and one extractor; this script is only its Rust consumer.
#
# A GC7000 instruction is a fixed 128 bits, so an operation is a mask of the
# bits that identify it, the values those bits must hold, and the list of
# named fields that make up the rest.  Every operation's fields and pinned
# bits together cover all 128 bits with no gap and no overlap, which is what
# lets a decoded instruction be written back exactly.

import json
import sys


def derived_parts(expr):
    """Decompose a `derived` expression into (field, shift) pieces.

    The two the display templates need are `{TYPE_BIT2} << 2 | {TYPE_BIT01}`
    and `{HIGH_HALF} << 1 | {LOW_HALF}`: a value assembled from named fields,
    each shifted. Parsing them here keeps the table the authority -- the
    alternative is a second, hand-written account of the same composition in
    the printer, free to drift from the description it came from.

    An expression this cannot parse raises rather than being dropped: a
    derived field that silently stops being composed prints as nothing, and
    nothing is exactly what a correct value can also look like.
    """
    import re
    parts = []
    for term in expr.split("|"):
        t = term.strip().strip("()").strip()
        m = re.fullmatch(r"\{(\w+)\}(?:\s*<<\s*(\d+))?", t)
        if not m:
            raise SystemExit(f"gen_rust_tables: cannot parse derived expression {expr!r} at {t!r}")
        parts.append((m.group(1), int(m.group(2) or 0)))
    return parts


def masks(patterns):
    """The bits an operation pins, what it pins them to, and the bits it
    declares it does not care about.

    isaspec writes a don't-care bit as `x` inside a pattern, and the table
    keeps it as a hole in the pattern's `mask`. Such a bit is part of no
    field, so nothing in a decoded instruction would remember its value and an
    encoder starting from zero would silently drop it: the classic case of
    code with no representation for "this was not modelled" substituting a
    value that reads exactly like a real one. So the don't-care mask travels
    with the operation and the decoder keeps those bits verbatim."""
    care = 0
    bits = 0
    dont_care = 0
    for p in patterns:
        n = p["high"] - p["low"] + 1
        full = (1 << n) - 1
        m = p["mask"]
        care |= m << p["low"]
        bits |= (p["value"] & m) << p["low"]
        dont_care |= (full & ~m) << p["low"]
    return care, bits, dont_care


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_tables.py <etna.json> <out.rs>")
    doc = json.load(open(sys.argv[1]))
    leaves = doc["instructions"]

    with open(sys.argv[2], "w") as w:
        w.write(
            """// SPDX-License-Identifier: Apache-2.0 AND MIT
// SPDX-FileCopyrightText: 2023 Igalia S.L.
//
// isa_tables.rs - GENERATED by tools/gc7000-isa/gen_rust_tables.py. DO NOT EDIT.
//
// The Vivante GC7000 instruction set, as data, for the shipping decoder and
// encoder.  It is generated from docs/online-shaderc/isa/gc7000-isa.json,
// which tools/gc7000-isa/extract.py extracts from Mesa's etnaviv ISA
// description (src/etnaviv/isa/etnaviv.xml, Copyright (c) 2023 Igalia S.L.,
// MIT licence).  There is one table and one extractor; this file is its Rust
// consumer, and no Mesa source is vendored anywhere.
//
// Regenerate with the commands in tools/gc7000-isa/gen_rust_tables.py after a
// Mesa bump, and let the round trip over the whole shader corpus judge the
// result rather than the exit status.

#![cfg_attr(rustfmt, rustfmt_skip)]

use super::isa::{Field, Op};

"""
        )
        names = sorted(leaves)
        for name in names:
            l = leaves[name]
            ds = ", ".join(
                '("%s", &[%s])'
                % (
                    dn,
                    ", ".join(
                        '("%s", %d)' % (f, sh) for f, sh in derived_parts(dv["expr"])
                    ),
                )
                for dn, dv in sorted((l.get("derived") or {}).items())
                if dv.get("expr")
            )
            w.write(f'static {ident(name)}_DERIVED: &[(&str, &[(&str, u32)])] = &[{ds}];\n')
            fs = ", ".join(
                'Field { name: "%s", low: %d, high: %d, ty: %s, display: %s }'
                % (
                    name_,
                    f["low"],
                    f["high"],
                    f'Some("{f["type"]}")' if f["type"] else "None",
                    f'Some("{f["display"]}")' if f["display"] else "None",
                )
                for name_, f in sorted(l["fields"].items(), key=lambda kv: kv[1]["low"])
            )
            w.write(f'static {ident(name)}_FIELDS: &[Field] = &[{fs}];\n')
        w.write("\n/// Every operation the description defines, by name.\n")
        w.write("pub static OPS: &[Op] = &[\n")
        for name in names:
            l = leaves[name]
            care, bits, dont_care = masks(l["patterns"])
            # The table records the bitset chain; the instruction class is
            # the second link (#instruction-alu, -tex, -cf, -load, -store).
            chain = l.get("chain") or []
            meta = chain[1].removeprefix("#instruction-") if len(chain) > 1 else ""
            # `name` is the bitset name and is UNIQUE: it is the key the
            # builder resolves an operation by. `mnemonic` is what the
            # instruction is CALLED, and it is not unique -- isaspec's
            # displayname makes branch_unary and branch_binary both `branch`,
            # because they are one instruction with different operand counts.
            # Printing the bitset name disagrees with Mesa on exactly the 208
            # branch_unary occurrences in our corpus; printing the mnemonic as
            # a key would make `branch` ambiguous. They are different jobs.
            mnem = l.get("mnemonic") or name
            w.write(
                f'    Op {{ name: "{name}", mnemonic: "{mnem}", meta: "{meta}", '
                f"care: {hex(care)}, bits: {hex(bits)}, dont_care: {hex(dont_care)}, "
                f'display: {json.dumps(l.get("display") or "")}, '
                f"derived: {ident(name)}_DERIVED, fields: {ident(name)}_FIELDS }},\n"
            )
        w.write("];\n\n")

        # The named fragments an instruction's display expands, and the
        # enumerations that name a field's value in a listing.
        w.write("/// The display fragments `Op::display` refers to.\n")
        w.write("pub static TEMPLATES: &[(&str, &str)] = &[\n")
        for k, v in sorted(doc.get("templates", {}).items()):
            w.write(f"    ({json.dumps(k)}, {json.dumps(v)}),\n")
        w.write("];\n\n")
        w.write("/// Every enumeration, with the spelling a listing gives each value.\n")
        w.write("pub static ENUM_DISPLAY: &[(&str, &[(u32, &str)])] = &[\n")
        for en, ev in sorted(doc["enums"].items()):
            vals = ", ".join(
                f'({v["value"]}, {json.dumps(v["display"] if v["display"] is not None else (v["name"] or ""))})'
                for v in ev["values"]
            )
            w.write(f"    ({json.dumps(en)}, &[{vals}]),\n")
        w.write("];\n")

    print(f"{len(names)} operations -> {sys.argv[2]}", file=sys.stderr)


def ident(s):
    return s.upper().replace("-", "_").replace(".", "_")


if __name__ == "__main__":
    main()
