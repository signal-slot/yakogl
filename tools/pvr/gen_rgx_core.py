"""Generate driver/compat/pvr_rgx_core.h from the vendored DDK's
hwdefs/rogue/km/rgx_bvnc_defs_km.h: for every feature bit, erratum bit and
feature with a value the DDK knows, what the build configuration of this GPU
says about it (the PVR_RGX_HAS_* / PVR_RGX_VALUE_* macros, decided by the C
preprocessor from configs/rgxconfig_km_36.V.104.796.h and
cores/rgxcore_km_36.53.104.796.h, which config_kernel.h names), the words the
Rust rgxlayer answers from (PVR_RGX_FEATURES_FROM_HEADERS,
PVR_RGX_ERNS_BRNS_FROM_HEADERS) and X-macro lists the host check iterates.

The header decides nothing itself: it only spells out, name by name, the
questions; the answers come from the DDK headers at compile time. It is
regenerated and compared by tools/check.sh (`--check`).

Usage: gen_rgx_core.py [--check]   (from the repository root)
"""
import re
import sys

DDK = 'third_party/ti-img-rogue-ddk-25.2/hwdefs/rogue/km/rgx_bvnc_defs_km.h'
OUT = 'driver/compat/pvr_rgx_core.h'


def generate():
    h = open(DDK).read()
    feats = re.findall(r'#define RGX_FEATURE_([A-Z0-9_]+?)_BIT_MASK\b', h)
    errs = re.findall(r'#define ((?:FIX_HW_BRN|HW_ERN)_[0-9]+)_BIT_MASK\b', h)
    enum = re.search(r'typedef enum _RGX_FEATURE_WITH_VALUE_INDEX_ \{(.*?)\}', h, re.S).group(1)
    vals = [n for n in re.findall(r'RGX_FEATURE_(\w+)_IDX', enum) if n != 'WITH_VALUES_MAX']
    o = []
    w = o.append
    w('/* SPDX-License-Identifier: Apache-2.0 */')
    w('/*')
    w(' * pvr_rgx_core.h -- GENERATED by tools/pvr/gen_rgx_core.py from')
    w(' * ' + DDK + '; do not edit.')
    w(' *')
    w(' * What the build configuration (config_kernel.h: RGX_BVNC_CORE_KM_HEADER,')
    w(' * RGX_BNC_CONFIG_KM_HEADER, included by rgxdefs_km.h) says about every')
    w(' * feature, erratum and feature value the DDK knows. Include after rgxlayer.h.')
    w(' */')
    w('#ifndef PVR_RGX_CORE_H')
    w('#define PVR_RGX_CORE_H')
    w('')
    w('/* ---- feature bits (all of array index 0) ---- */')
    for n in feats:
        w(f'#if defined(RGX_FEATURE_{n})')
        w(f'#define PVR_RGX_HAS_{n} 1')
        w('#else')
        w(f'#define PVR_RGX_HAS_{n} 0')
        w('#endif')
    w('')
    w('/* ---- errata ---- */')
    for n in errs:
        w(f'#if defined({n})')
        w(f'#define PVR_RGX_HAS_{n} 1')
        w('#else')
        w(f'#define PVR_RGX_HAS_{n} 0')
        w('#endif')
    w('')
    w('/* ---- feature values (-1: not defined for this core) ---- */')
    for n in vals:
        w(f'#if defined(RGX_FEATURE_{n})')
        w(f'#define PVR_RGX_VALUE_{n} ((int)RGX_FEATURE_{n})')
        w('#else')
        w(f'#define PVR_RGX_VALUE_{n} (-1)')
        w('#endif')
    w('')
    w('#define PVR_RGX_FEATURES_FROM_HEADERS ( \\')
    for n in feats:
        w(f'\t(PVR_RGX_HAS_{n} ? RGX_FEATURE_{n}_BIT_MASK : 0) | \\')
    w('\t0)')
    w('#define PVR_RGX_ERNS_BRNS_FROM_HEADERS ( \\')
    for n in errs:
        w(f'\t(PVR_RGX_HAS_{n} ? {n}_BIT_MASK : 0) | \\')
    w('\t0)')
    w('')
    w('/* X(name, mask, present) */')
    w('#define PVR_RGX_FEATURE_BITS(X) \\')
    for n in feats:
        w(f'\tX({n}, RGX_FEATURE_{n}_BIT_MASK, PVR_RGX_HAS_{n}) \\')
    w('')
    w('/* X(name, mask, present) */')
    w('#define PVR_RGX_ERRATA(X) \\')
    for n in errs:
        w(f'\tX({n}, {n}_BIT_MASK, PVR_RGX_HAS_{n}) \\')
    w('')
    w('/* X(name, index, value) */')
    w('#define PVR_RGX_FEATURE_VALUES(X) \\')
    for n in vals:
        w(f'\tX({n}, RGX_FEATURE_{n}_IDX, PVR_RGX_VALUE_{n}) \\')
    w('')
    w('#endif /* PVR_RGX_CORE_H */')
    return '\n'.join(o) + '\n'


def main():
    text = generate()
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        if open(OUT).read() != text:
            print(f'{OUT} differs from gen_rgx_core.py output')
            return 1
        print(f'{OUT}: regenerated == committed')
        return 0
    open(OUT, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
