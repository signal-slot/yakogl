"""The partial render's SPM background-load shader (tools/pco_shc/spm_load/)
as generator output.

The resumed render of a partial render runs a fragment program as its
background object that samples the tiles the PR's end-of-tile program stored
to the SPM scratch back into the output registers: Mesa's
pvr_uscgen_spm_load() (src/imagination/vulkan/pvr_usc.c), which Mesa's
Vulkan driver generates with pco at device init (pvr_arch_spm.c). The driver
has no pco on the target, so the shader is generated once here, for the one
configuration the AM62P driver needs (docs/notes/pvr-render-pool.md, part
3, and docs/notes/pvr-pr-spm-const.md): one output dword (RGBA8), no tile
buffer, one sample, the BXS-4-64. Two steps, so that the second needs no
Mesa build:

  gen_spm_load.py capture <capture_spm_load> [--check]
      Runs Mesa 26.2.1's pco through tools/pco_shc/capture_spm_load.c (built
      in a Mesa tree with pco_shc, README.md) and writes
      tools/pco_shc/spm_load/spm_load.hex (the machine code, one dword per
      line) and spm_load.meta.txt (what the program needs around it: temps,
      shared registers, the sampler and image state slots, the coefficient
      and output registers, its entry and size). --check compares instead of
      writing; tools/check.sh runs that when the capture program is there
      (PCO_CAPTURE, tools/cts/deps.toml).

  gen_spm_load.py check
      Decodes the committed words with the repository's USC decoder
      (`yakogl-tools usc-dis`, the online compiler's decoder of
      src/shaderc/online/powervr, generated by tools/pco-isa from Mesa's
      pco_isa.py) and checks them against the metadata: every byte in a
      decoded instruction group, one shader end (the last group, `olchk`),
      one texture sample per source (the output registers' scratch, each
      tile buffer) reading the sampler and image state from the metadata's
      shared registers, a data fence, the output written to pixel output 0,
      the temps and shared registers the code names within the counts, the
      size, and the metadata's own consistency. tools/check.sh runs this
      always. YAKOGL_TOOLS names a prebuilt yakogl-tools (default: cargo
      run, as tools/glsl2usc.sh).

Run from the repository root.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tools/pco_shc/spm_load")
HEX = os.path.join(OUT, "spm_load.hex")
META = os.path.join(OUT, "spm_load.meta.txt")
BIN = os.path.join(ROOT, "build/spm_load/spm_load.bin")
PIXOUT0 = 32  # the special-register index of pixout0 (Mesa pco_isa.py; assemble.rs PCO_SR_PIXOUT0)

# The configuration: capture_spm_load <output_reg_count> <tile_buffer_count>
# <is_multisampled>, pvr_uscgen_spm_load_index() 0 (pvr_usc.h).
PROPS = ("1", "0", "0")

# Mesa's layout of the shared registers the shader reads (common/pvr_iface.h
# enum pvr_spm_load_data, pvr_usc.h pvr_uscgen_spm_load_data_size):
# the sampler at 0, the output registers' image state at 4, four dwords
# each (ROGUE_NUM_TEXSTATE_DWORDS); then six per tile buffer.
TEXSTATE_DWORDS = 4
DATA_SMP, DATA_REG_TEX, DATA_BUF_TEX_0 = 0, 4, 8

HEX_HEADER = """\
# SPDX-License-Identifier: Apache-2.0 AND MIT
# SPDX-FileCopyrightText: 2026 Signal Slot, Inc.
# SPDX-FileCopyrightText: 2025 Imagination Technologies Ltd.
# The partial render's SPM background-load shader for the BXS-4-64 (BVNC
# 36.53.104.796, TI AM62P): the USC machine code Mesa 26.2.1's pco compiles
# for pvr_uscgen_spm_load() (src/imagination/vulkan/pvr_usc.c, MIT) with
# struct pvr_spm_load_props {{ output_reg_count {o}, tile_buffer_count {t},
# is_multisampled {m} }}: one output dword (RGBA8), no tile buffer, one
# sample. One little-endian dword per line; the register metadata is
# spm_load.meta.txt. The machine code is Mesa's pco output for Mesa's own
# source, so the MIT part stays under its licence (LICENSES/MIT.txt, NOTICE).
# Written by: tools/pco_shc/gen_spm_load.py capture <mesa>/build/src/imagination/vulkan/capture_spm_load
"""

META_HEADER = """\
# SPDX-License-Identifier: Apache-2.0
# SPDX-FileCopyrightText: 2026 Signal Slot, Inc.
# The register metadata of spm_load.hex, the partial render's SPM
# background-load shader (Mesa 26.2.1 pvr_uscgen_spm_load() on the
# BXS-4-64, tools/pco_shc/capture_spm_load.c): what the PDS program that
# kicks it must set up. "key value" lines; the keys:
#   mesa, generator, device   the Mesa version, the generator and the GPU
#   output_reg_count, tile_buffer_count, is_multisampled
#                             the generator's inputs (struct pvr_spm_load_props)
#   index                     pvr_uscgen_spm_load_index() of those inputs
#   size_bytes, entry_offset  the machine code's size, and where it starts
#   temps                     pco's temp register count (the DOUTU's temps,
#                             ceil(temps / 4), docs/notes/pvr-pr-spm-const.md section 5)
#   shareds, coeffs, vtxins, interns, spilled_temps, scratch
#                             pco's other register counts (shareds is what pco
#                             allocated, not the preamble: see data_dwords)
#   data_dwords               the shared registers the shader reads, DMAed from
#                             the constants buffer (sh0 up, pvr_iface.h enum
#                             pvr_spm_load_data): the DOUTD's bsize
#   smp_state, tex_state      the sampler state and the output registers' image
#                             state in those shared registers (sh<n>, count)
#   pos_coeffs                the coefficient registers of gl_FragCoord
#                             (VARYING_SLOT_POS; cf<n>, count). count 0: pco
#                             reads the pixel position from the special
#                             registers (sr97/sr98 and sr100/sr101, chosen on
#                             sc64), not from an iterated varying, so no
#                             coefficient registers and no iterator setup
#   uses_z, uses_w            whether the shader reads gl_FragCoord.z / .w
#   sample_shading            runs per sample (the DOUTU's sample rate FULL)
#                             rather than per instance
#   point_sampler, usclib     pco's point-sampler and usclib use flags
#   output                    the pixel output registers written (po<n>, count,
#                             pipe format)
# Written by: tools/pco_shc/gen_spm_load.py capture <mesa>/build/src/imagination/vulkan/capture_spm_load
"""


def parse_capture(text):
    """(metadata lines, words) of capture_spm_load's output."""
    meta, words = [], None
    for line in text.splitlines():
        if line.startswith("words"):
            words = [int(w, 16) for w in line.split()[1:]]
        elif line.strip():
            meta.append(line.rstrip("\n"))
    if words is None:
        sys.exit("capture_spm_load printed no words line")
    return meta, words


def render(meta, words):
    o, t, m = PROPS
    hex_text = HEX_HEADER.format(o=o, t=t, m=m) + "".join(f"0x{w:08x}\n" for w in words)
    meta_text = META_HEADER + "".join(line + "\n" for line in meta)
    return hex_text, meta_text


def read_committed():
    """(metadata dict, words) of the committed files; a key repeated is an error."""
    meta = {}
    for line in open(META):
        if not line.strip() or line.startswith("#"):
            continue
        key, _, value = line.rstrip("\n").partition(" ")
        if key in meta:
            sys.exit(f"{META}: {key} twice")
        meta[key] = value
    words = []
    for line in open(HEX):
        if not line.strip() or line.startswith("#"):
            continue
        words.append(int(line.strip(), 16))
    return meta, words


def capture(capture_spm_load, check):
    out = subprocess.run([capture_spm_load, *PROPS], check=True, capture_output=True, text=True).stdout
    hex_text, meta_text = render(*parse_capture(out))
    if check:
        bad = []
        for path, text in ((HEX, hex_text), (META, meta_text)):
            if not os.path.exists(path) or open(path).read() != text:
                bad.append(os.path.relpath(path, ROOT))
        if bad:
            sys.exit(f"{' and '.join(bad)}: not what this pco build's capture_spm_load {' '.join(PROPS)} makes")
        print(f"gen_spm_load: spm_load.hex and spm_load.meta.txt = this pco build's capture_spm_load {' '.join(PROPS)}")
    else:
        os.makedirs(OUT, exist_ok=True)
        open(HEX, "w").write(hex_text)
        open(META, "w").write(meta_text)


def usc_dis(data):
    """The listing `yakogl-tools usc-dis` prints for the bytes."""
    os.makedirs(os.path.dirname(BIN), exist_ok=True)
    open(BIN, "wb").write(data)
    tool = [os.environ["YAKOGL_TOOLS"]] if os.environ.get("YAKOGL_TOOLS") else \
        ["cargo", "run", "--quiet", "--manifest-path", os.path.join(ROOT, "Cargo.toml"), "-p", "yakogl-tools", "--"]
    r = subprocess.run([*tool, "usc-dis", BIN], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"usc-dis failed ({r.returncode}):\n{r.stdout}{r.stderr}")
    return r.stdout


def parse_listing(text):
    """The groups of a usc-dis listing: dicts with offset, bytes, kind, the header
    fields, the phase lines (phase name, instruction name), the instr field
    lines, and the register operands named (bank, index) by source slot."""
    groups = []
    g = None
    for line in text.splitlines():
        m = re.match(r"\[([0-9a-f]+)\] (\d+) bytes, (\w+)", line)
        if m:
            g = {"offset": int(m.group(1), 16), "bytes": int(m.group(2)), "kind": m.group(3),
                 "hdr": {}, "phases": [], "instrs": [], "srcs": {}, "dst": None}
            groups.append(g)
            continue
        if g is None:
            continue
        s = line.strip()
        if s.startswith("hdr:"):
            g["hdr"] = dict(re.findall(r"(\w+)=([\w.]+)", s))
        elif re.match(r"phase\d+ ", s):
            g["phases"].append(tuple(s.split(" ", 1)))
        elif s.startswith("instr:"):
            g["instrs"].append(dict(re.findall(r"(\w+)=([\w.]+)", s)))
        elif s.startswith(("lower_src:", "upper_src:")):
            for _, bank, n, idx in re.findall(r"sb(\d)=(\w+) s(\d)=(\d+)", s):
                g["srcs"][int(n)] = (bank, int(idx))
        elif s.startswith("dst:"):
            m = re.search(r"dbN=(\w+) dN=(\d+)", s)
            if m:
                g["dst"] = (m.group(1), int(m.group(2)))
    m = re.search(r"^(\d+) instruction groups$", text, re.M)
    return groups, (int(m.group(1)) if m else None)


def check():
    meta, words = read_committed()
    data = b"".join(w.to_bytes(4, "little") for w in words)
    bad = []

    def expect(cond, what):
        if not cond:
            bad.append(what)

    def num(key):
        try:
            return int(meta[key])
        except (KeyError, ValueError):
            bad.append(f"meta: no numeric {key}")
            return 0

    # The metadata against itself and the configuration.
    o, t, m = PROPS
    expect(meta.get("mesa") == "26.2.1", "meta: mesa is not 26.2.1")
    expect(meta.get("generator") == "pvr_uscgen_spm_load", "meta: generator is not pvr_uscgen_spm_load")
    expect(meta.get("device") == "BXS-4-64 36.53.104.796", "meta: device is not the BXS-4-64")
    expect((meta.get("output_reg_count"), meta.get("tile_buffer_count"), meta.get("is_multisampled")) == (o, t, m),
           f"meta: the inputs are not {o} {t} {m}")
    expect(num("index") == 0, "meta: index is not 0 (pvr_uscgen_spm_load_index of 1 0 0)")
    regs, tbs, ms = num("output_reg_count"), num("tile_buffer_count"), num("is_multisampled")
    expect(num("size_bytes") == len(data), f"meta: size_bytes {meta.get('size_bytes')} is not the {len(data)} bytes of spm_load.hex")
    expect(len(data) > 0 and len(data) % 4 == 0, "spm_load.hex: not a dword multiple")
    expect(num("entry_offset") == 0, "meta: entry_offset is not 0")
    expect(num("temps") >= 1, "meta: no temps (the sample's result needs one)")
    expect(num("spilled_temps") == 0 and num("scratch") == 0, "meta: the shader spills or uses scratch memory")
    expect(num("data_dwords") == DATA_BUF_TEX_0 + tbs * (TEXSTATE_DWORDS + 2),
           "meta: data_dwords is not pvr_uscgen_spm_load_data_size of the inputs")
    expect(meta.get("smp_state") == f"sh{DATA_SMP} count {TEXSTATE_DWORDS}", "meta: smp_state is not sh0 x 4")
    expect(meta.get("tex_state") == f"sh{DATA_REG_TEX} count {TEXSTATE_DWORDS}", "meta: tex_state is not sh4 x 4")
    expect(num("sample_shading") == ms, "meta: sample_shading is not is_multisampled")
    fmt = {1: "r32_uint", 2: "r32g32_uint", 4: "r32g32b32a32_uint"}.get(regs)
    expect(meta.get("output") == f"po0 count {regs} format {fmt}", f"meta: output is not po0 count {regs} format {fmt}")
    # The position comes from the special registers, not an iterated varying
    # (META_HEADER): no coefficient registers, so no iterator for the PDS.
    expect(meta.get("pos_coeffs") == "cf0 count 0" and num("coeffs") == 0,
           "meta: pos_coeffs is not cf0 count 0 with coeffs 0 (the position is read from special registers)")
    expect(num("vtxins") == 0 and num("interns") == 0, "meta: a fragment program with vertex inputs or internal registers")

    # The words through the repository's decoder (yakogl-tools usc-dis).
    groups, n_groups = parse_listing(usc_dis(data))
    expect(n_groups is not None and n_groups == len(groups), "decode: usc-dis did not count the groups it listed")
    covered = sum(g["bytes"] for g in groups)
    expect(covered == len(data), f"decode: the groups cover {covered} of {len(data)} bytes")
    expect(groups and all(g["offset"] == sum(h["bytes"] for h in groups[:i]) for i, g in enumerate(groups)),
           "decode: the groups are not contiguous from 0")
    ends = [g for g in groups if g["hdr"].get("end") == "1"]
    expect(len(ends) == 1 and groups and ends[0] is groups[-1], "decode: not exactly one `end`, on the last group")
    last = groups[-1] if groups else {"hdr": {}, "dst": None, "phases": []}
    expect(last["hdr"].get("olchk") == "1", "decode: the last group does not write with olchk")
    expect(last["dst"] == ("special", PIXOUT0), "decode: the last group does not write pixout0 (special 32)")
    expect(len(last["phases"]) == 1 and last["phases"][0][1] == "mbyp", "decode: the last group is not a lone mbyp")
    smp_groups = [g for g in groups if any(name == "smp" for _, name in g["phases"])]
    expect(len(smp_groups) == 1 + tbs, f"decode: {len(smp_groups)} texture samples, not {1 + tbs} (one per source)")
    for g in smp_groups:
        inst = next((i for i in g["instrs"] if "dmn" in i), {})
        expect(inst.get("dmn") == "2d" and inst.get("lodm") == "replace" and inst.get("nncoords") == "0",
               f"decode: the sample at {g['offset']:#x} is not 2d with lod replace and normalised-coordinate mode")
        expect(inst.get("chan") == str(regs), f"decode: the sample at {g['offset']:#x} does not return {regs} channel(s)")
        # smp sources: s0 the image state, s1 the coordinates (temps), s2 the sampler state.
        expect(g["srcs"].get(0) == ("shared", DATA_REG_TEX), f"decode: the sample at {g['offset']:#x} does not read its image state from sh{DATA_REG_TEX}")
        expect(g["srcs"].get(2) == ("shared", DATA_SMP), f"decode: the sample at {g['offset']:#x} does not read its sampler from sh{DATA_SMP}")
        expect(g["srcs"].get(1, ("", 0))[0] == "temp", f"decode: the sample at {g['offset']:#x} does not take its coordinates from temps")
    expect(any(g["kind"] == "control" and g["hdr"].get("ctrlop") == "wdf" for g in groups),
           "decode: no `wdf` (the sample's data fence)")
    temps = [i for g in groups for b, i in list(g["srcs"].values()) + ([g["dst"]] if g["dst"] else []) if b == "temp"]
    expect(temps and max(temps) + 1 == num("temps"), f"decode: the code names temps up to r{max(temps) if temps else -1}, meta temps {meta.get('temps')}")
    shareds = sorted({i for g in groups for b, i in g["srcs"].values() if b == "shared"})
    expect(shareds == [DATA_SMP, DATA_REG_TEX], f"decode: the shared registers named are {shareds}, not [{DATA_SMP}, {DATA_REG_TEX}]")
    expect(all(i + TEXSTATE_DWORDS <= num("data_dwords") for i in shareds), "decode: a shared-register read past data_dwords")

    if bad:
        print("\n".join(bad))
        sys.exit(1)
    mix = {}
    for g in groups:
        for _, name in g["phases"]:
            mix[name] = mix.get(name, 0) + 1
    print(f"gen_spm_load: spm_load.hex decodes (usc-dis): {len(groups)} instruction groups, {sum(mix.values())} instructions "
          f"({', '.join(f'{k} x{v}' for k, v in sorted(mix.items()))}), {len(data)} bytes, "
          f"temps {meta['temps']}, {meta['data_dwords']} shared dwords read (sh{DATA_SMP} sampler, sh{DATA_REG_TEX} image), "
          f"{meta['pos_coeffs']}, output {meta['output']}")


def main():
    a = sys.argv[1:]
    want_check = "--check" in a
    a = [x for x in a if x != "--check"]
    if a == ["check"]:
        check()
    elif a[:1] == ["capture"] and len(a) == 2:
        capture(a[1], want_check)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
