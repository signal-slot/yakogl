"""The driver's USC blobs (driver/src/pvr_usc_*_blob.h) as generator output.

Two steps, so that the second needs no Mesa build:

  gen_usc_blobs.py capture <capture_usc>
      Runs Mesa 26.2.1's pco through tools/pco_shc/capture_usc.c (built in a
      Mesa tree, README.md) for every program in PROGRAMS and writes
      tools/pco_shc/usc_blobs.txt: the capture's output, one line each.
      --check compares instead of writing.

  gen_usc_blobs.py render [--check]
      Writes the four headers from usc_blobs.txt (--check: compares them, and
      compares the clear-attach words with the captured ones: Mesa's copy in
      tests/reference/pvr_internal.rs and the backend's, our encoder's, in
      src/pvr/internal.rs). tools/check.sh runs this with --check.

Run from the repository root.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFEST = os.path.join(ROOT, "tools/pco_shc/usc_blobs.txt")
DRV = os.path.join(ROOT, "driver/src")

# name -> capture_usc arguments. "precomp <NAME>" is resolved to the index
# of NAME in the build's pco_uscgen_programs.h.
PROGRAMS = [
    ("eot1", "eot 1"),
    ("eot2", "eot 2"),
    ("eot3", "eot 3"),
    ("eot2_tb", "eot 3 1"),
    ("eot3_tb", "eot 3 2"),
    ("eot4", "eot 4"),
    ("eot4_tb", "eot 4 3"),
    ("eot4_tb2", "eot 4 2 3"),
    ("eot4_tb3", "eot 4 1 2 3"),
    ("clear1", "clear 1"),
    ("clear2", "clear 2"),
    ("clear3", "clear 3"),
    ("vs_passthrough", "precomp VS_PASSTHROUGH_COMMON"),
    ("vs_nop", "precomp VS_NOP_COMMON"),
    ("fs_nop", "precomp FS_NOP_COMMON"),
]

# capture_usc.c TB_SENTINEL: (lo, hi) of the address of the k-th spilled emit
TB_SENTINELS = [(0xE0770000, 0x0000BEEF), (0xE1770000, 0x0000BDEF), (0xE2770000, 0x0000BCEF), (0xE3770000, 0x0000BBEF)]
TB_LO, TB_HI = TB_SENTINELS[0]
# the tile-buffer programs: name -> spilled emits (capture_usc arguments after the count)
TB_PROGRAMS = ["eot2_tb", "eot3_tb", "eot4_tb", "eot4_tb2", "eot4_tb3"]
TB_MAX_SPILLS = 3

GENERATED = (" * GENERATED by tools/pco_shc/gen_usc_blobs.py render from\n"
             " * tools/pco_shc/usc_blobs.txt, which gen_usc_blobs.py capture writes from\n"
             " * Mesa 26.2.1's pco (tools/pco_shc/capture_usc.c, README.md). Do not edit.\n")

GENERATED_OURS = (" * GENERATED by tools/pco_shc/gen_usc_blobs.py render. The VDM-sync, passthrough\n"
                  " * and plain end-of-tile (eot1..3) programs are the words of src/pvr/internal.rs,\n"
                  " * which yakogl-precompile --internal builds with our USC encoder; render refuses\n"
                  " * them unless they equal Mesa 26.2.1's pco (tools/pco_shc/usc_blobs.txt, written\n"
                  " * by gen_usc_blobs.py capture, tools/pco_shc/capture_usc.c, README.md).\n")

# program -> its words in src/pvr/internal.rs (ours, the encoder's)
OURS = {
    "eot1": "PVR_INTERNAL_EOT1",
    "eot2": "PVR_INTERNAL_EOT2",
    "eot3": "PVR_INTERNAL_EOT3",
    "vs_passthrough": "PVR_INTERNAL_VS_PASSTHROUGH",
    "vs_nop": "PVR_INTERNAL_VDM_SYNC",
}

LICENCE = """/*
 * SPDX-License-Identifier: Apache-2.0 AND MIT
 * SPDX-FileCopyrightText: 2026 Signal Slot, Inc.
 * SPDX-FileCopyrightText: 2025 Imagination Technologies Ltd.
 * Machine code compiled by Mesa 26.2.1's pco from {src} (MIT).
 * The upstream part stays under its licence (LICENSES/MIT.txt); our
 * changes are Apache-2.0. See NOTICE.
 */
"""
SRC_USC = "src/imagination/vulkan/pvr_usc.c\n * and src/imagination/pco/usclib"


TB_DWORDS = {}


def read_manifest():
    progs = {}
    for line in open(MANIFEST):
        if not line.strip() or line.startswith("#"):
            continue
        name, args, temps, words, *extra = [f.strip() for f in line.split("|")]
        assert temps.startswith("temps ") and words.startswith("words"), line
        progs[name] = (args, int(temps.split()[1]), [int(w, 16) for w in words.split()[1:]])
        # a tile-buffer program: what one spilled emit flushes from its buffer
        if extra:
            assert len(extra) == 1 and extra[0].startswith("tile_buffer_dwords "), line
            TB_DWORDS[name] = int(extra[0].split()[1])
    names = [n for n, _ in PROGRAMS]
    if sorted(progs) != sorted(names):
        sys.exit("usc_blobs.txt does not list exactly the programs of PROGRAMS")
    for n, a in PROGRAMS:
        if progs[n][0] != a:
            sys.exit(f"usc_blobs.txt: {n} was captured with '{progs[n][0]}', PROGRAMS says '{a}'")
    return progs


def hexw(w):
    return f"0x{w:08x}u"


def word_lines(words, indent="   ", per=4, sym=None):
    out = []
    for i in range(0, len(words), per):
        out.append(indent + " ".join((sym(w) if sym else hexw(w)) + "," for w in words[i:i + per]))
    return "\n".join(out)


def byte_lines(words, indent="   "):
    out = []
    for w in words:
        b = w.to_bytes(4, "little")
        out.append(indent + " ".join(f"0x{x:02x}," for x in b))
    return "\n".join(out)


def tb_addr_bytes(name, args, words):
    """Byte offsets of each spilled emit's address immediates (lo, hi) in a
    tile-buffer program, in emit order: the k-th spilled emit carries
    sentinel k. A program with several spilled emits has them at any byte
    (USC instructions are not dword aligned), so they are searched as
    bytes, and each must be there exactly once."""
    spills = len(args.split()) - 2
    assert 1 <= spills <= TB_MAX_SPILLS, f"{name}: {spills} spilled emits"
    blob = b"".join(w.to_bytes(4, "little") for w in words)
    out = []
    for k, (lo, hi) in enumerate(TB_SENTINELS):
        found = [blob.count(v.to_bytes(4, "little")) for v in (lo, hi)]
        if k >= spills:
            assert found == [0, 0], f"{name}: sentinel {k} without its emit"
            continue
        assert found == [1, 1], f"{name}: sentinel {k} found {found} times, not once"
        out.append(tuple(blob.index(v.to_bytes(4, "little")) for v in (lo, hi)))
    return out


def eot_h(p):
    plain = [p[f"eot{n}"] for n in (1, 2, 3, 4)]
    _, t1, w1 = plain[0]
    assert all(t == t1 for _, t, _ in plain), "the EOT programs share one temps count"
    tbt = p["eot2_tb"][1]
    assert all(p[n][1] == tbt for n in TB_PROGRAMS), "the tile-buffer EOT programs share one temps count"
    assert sorted(TB_DWORDS) == sorted(TB_PROGRAMS), "tile_buffer_dwords on the tile-buffer programs, only"
    tbdw = TB_DWORDS["eot2_tb"]
    assert all(d == tbdw for d in TB_DWORDS.values()), "every spilled emit flushes the same size"
    addr = {n: tb_addr_bytes(n, p[n][0], p[n][2]) for n in TB_PROGRAMS}
    for n in ("eot2_tb", "eot3_tb"):
        assert addr[n][0][0] % 4 == 0 and addr[n][0][1] % 4 == 0, f"{n}: the one-spill sentinel is dword aligned"
    tbsym = lambda w: "PVR_USC_EOT_TB_ADDR_LO" if w == TB_LO else "PVR_USC_EOT_TB_ADDR_HI" if w == TB_HI else hexw(w)
    cname = lambda n: "pvr_usc_eot_words" if n == "eot1" else f"pvr_usc_{n}_words"

    def addr_rows(names):
        rows = []
        for n in names:
            pairs = addr[n] if n else []
            cells = [f"{{ {lo}, {hi} }}" for lo, hi in pairs] + ["{ 0, 0 }"] * (TB_MAX_SPILLS - len(pairs))
            rows.append(f"   {{ {', '.join(cells)} }},{f' /* {n} */' if n else ''}")
        return "\n".join(rows)

    def ptrs(names):
        return ", ".join(cname(n) if n else "NULL" for n in names)

    def lens(names):
        return ", ".join(str(len(p[n][2])) if n else "0" for n in names)

    tb_n = [None, None, "eot2_tb", "eot3_tb", "eot4_tb"]
    tb4_k = [None, "eot4_tb", "eot4_tb2", "eot4_tb3"]
    plain_n = [None, "eot1", "eot2", "eot3", "eot4"]
    progs = "".join(f"static const uint32_t {cname(n)}[] = {{\n{word_lines(p[n][2])}\n}};\n" for n in ("eot2", "eot3", "eot4"))
    tbprogs = "".join(
        f"static const uint32_t {cname(n)}[] = {{\n{word_lines(p[n][2], sym=tbsym)}\n}};\n" for n in TB_PROGRAMS
    )
    listing = "".join(f" *   {cname(n):<26} capture_usc {p[n][0]}\n" for n in ["eot1", "eot2", "eot3", "eot4"] + TB_PROGRAMS)
    return LICENCE.format(src=SRC_USC) + f"""/*
 * pvr_usc_eot_blob.h
 *
 * USC end-of-tile (EOT) programs for PowerVR BXS-4-64 (BVNC 36.53.104.796,
 * TI AM62P): pvr_usc_eot() (src/imagination/vulkan/pvr_usc.c) with the
 * transfer context's props (pvr_arch_job_context.c
 * pvr_transfer_eot_shaders_init): shared_words, state_regs[i] = 2i, so
 * emit i reads its PBE state from shared registers sh[2i], sh[2i+1]; one
 * 16-byte instruction group per emit, the last one ending
 * (`emitpix.freep`).
 *
{listing} *
 * The _tb programs read emits from tile buffers (tile_buffer_addrs[i] set,
 * num_output_regs 4, msaa_samples 1): a pixel has four output registers
 * here, so three RGBA16F attachments do not fit, the shader stores the rest
 * to memory and the program loads each one back (flush_tile_buffer,
 * PVR_USC_EOT_TB_DWORDS dwords per spilled emit) before emitting it. A
 * tile buffer's address is two immediates in the program, a sentinel the
 * driver patches at upload: the k-th spilled emit (in emit order) reads
 * tile buffer k, its immediates at the byte offsets
 * pvr_usc_eot_*_addr_bytes[..][k] = {{ lo, hi }} (a program with several
 * spilled emits has them at any byte, not on a dword). The first sentinel,
 * PVR_USC_EOT_TB_ADDR_LO/HI, is the one-spill programs'. As captured,
 * pvr_usc_eot2_tb_words and pvr_usc_eot3_tb_words are BOTH three-emit
 * programs: the tile buffer on emit 1 and on emit 2 (the arguments above; a
 * two-emit program with the tile buffer on its last emit, capture_usc eot 2
 * 1, is a different program).
 *
{GENERATED_OURS} * eot4 and the tile-buffer programs stay pco's: our encoder has no list line
 * for four emits, and no builder for the loads from memory. Do not edit.
 */

#ifndef PVR_USC_EOT_BLOB_H
#define PVR_USC_EOT_BLOB_H

#include <stdint.h>

/* {len(w1) * 4} bytes = {len(w1)} dwords, little-endian. */
static const uint32_t pvr_usc_eot_words[] = {{
{word_lines(w1)}
}};

/* Byte view (identical data), for DMA/upload paths that want bytes. */
static const uint8_t pvr_usc_eot_bytes[] = {{
{byte_lines(w1)}
}};

#define PVR_USC_EOT_SIZE_BYTES {len(w1) * 4}
#define PVR_USC_EOT_TEMPS      {t1}

{progs}
#define PVR_USC_EOT_TB_ADDR_LO 0x{TB_LO:08x}u
#define PVR_USC_EOT_TB_ADDR_HI 0x{TB_HI:08x}u
#define PVR_USC_EOT_TB_TEMPS   {tbt}u
/* Dwords one spilled emit flushes from its tile buffer (pvr_usc_eot's
 * data_size: tile_size_x * tile_size_y * num_output_regs / USCs per tile). */
#define PVR_USC_EOT_TB_DWORDS  {tbdw}u
/* Spilled emits one program has at most, one tile buffer each. */
#define PVR_USC_EOT_TB_MAX_SPILLS {TB_MAX_SPILLS}

{tbprogs}
/* index by render-target count (2..4), the LAST emit from tile buffer 0;
 * [0] and [1] unused */
static const uint32_t *const pvr_usc_eot_tb_n_words[5] = {{
   {ptrs(tb_n)},
}};
static const uint32_t pvr_usc_eot_tb_n_dwords[5] = {{ {lens(tb_n)} }};
static const uint16_t pvr_usc_eot_tb_n_addr_bytes[5][PVR_USC_EOT_TB_MAX_SPILLS][2] = {{
{addr_rows(tb_n)}
}};

/* four render targets, index by the spilled emits k (1..3): the last k
 * emits from tile buffers 0..k-1; [0] unused */
static const uint32_t *const pvr_usc_eot4_tb_k_words[4] = {{
   {ptrs(tb4_k)},
}};
static const uint32_t pvr_usc_eot4_tb_k_dwords[4] = {{ {lens(tb4_k)} }};
static const uint16_t pvr_usc_eot4_tb_k_addr_bytes[4][PVR_USC_EOT_TB_MAX_SPILLS][2] = {{
{addr_rows(tb4_k)}
}};

/* index by render-target count (1..4); [0] unused */
static const uint32_t *const pvr_usc_eot_n_words[5] = {{
   {ptrs(plain_n)},
}};
static const uint32_t pvr_usc_eot_n_dwords[5] = {{ {lens(plain_n)} }};
#define PVR_USC_EOT_MAX_RT 4

#endif /* PVR_USC_EOT_BLOB_H */
"""


