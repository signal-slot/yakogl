HEADERS = [
    ("pvr_usc_eot_blob.h", eot_h),
    ("pvr_usc_clear_fs_blob.h", clear_fs_h),
    ("pvr_usc_clear_fs2_blob.h", clear_fs2_h),
    ("pvr_usc_vs_passthrough_blob.h", vs_h),
]


def rust_words(src, name, where):
    m = re.search(r"pub static " + name + r": \[u32; [^\]]+\] = \[(.*?)\];", src, re.S)
    if not m:
        sys.exit(f"{where} has no {name}")
    return [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]


def render(check):
    p = read_manifest()
    bad = 0
    internal = open(os.path.join(ROOT, "src/pvr/internal.rs")).read()
    for pname, rname in OURS.items():
        args, temps, pco = p[pname]
        ours = rust_words(internal, rname, "src/pvr/internal.rs")
        if ours != pco:
            print(f"src/pvr/internal.rs {rname} is not Mesa's {pname} (capture_usc {args})")
            bad += 1
        p[pname] = (args, temps, ours)
    for fname, fn in HEADERS:
        path = os.path.join(DRV, fname)
        text = fn(p)
        if check:
            if open(path).read() != text:
                print(f"{fname}: differs from the rendering of usc_blobs.txt")
                bad += 1
        else:
            open(path, "w").write(text)
    # The clear-attach programs: Mesa's copy (tests/reference/pvr_internal.rs)
    # and the backend's (src/pvr/internal.rs, our encoder's, which
    # yakogl-precompile --internal writes) must both be the captured words.
    copies = (
        ("tests/reference/pvr_internal.rs", ("PVR_USC_CLEAR_FS_WORDS", "PVR_USC_CLEAR_FS2_WORDS", "PVR_USC_CLEAR_FS3_WORDS")),
        ("src/pvr/internal.rs", ("PVR_INTERNAL_CLEAR_ATTACH1", "PVR_INTERNAL_CLEAR_ATTACH2", "PVR_INTERNAL_CLEAR_ATTACH3")),
    )
    for where, names in copies:
        rs = open(os.path.join(ROOT, where)).read()
        for rname, pname in zip(names, ("clear1", "clear2", "clear3")):
            if rust_words(rs, rname, where) != p[pname][2]:
                print(f"{where} {rname} is not Mesa's {pname} (capture_usc {p[pname][0]})")
                bad += 1
    if check:
        if bad:
            sys.exit(1)
        print(f"gen_usc_blobs: {len(HEADERS)} headers, 2 x 3 clear-attach programs and {len(OURS)} programs of ours = usc_blobs.txt")


def capture(capture_usc, check):
    build = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(capture_usc)))))
    hdr = open(os.path.join(build, "src/imagination/pco/uscgen/pco_uscgen_programs.h")).read()
    # The words are Mesa's pco output for Mesa's own sources, so the same
    # licence as the headers render() writes from them (LICENCE above).
    lines = ["# SPDX-License-Identifier: Apache-2.0 AND MIT",
             "# SPDX-FileCopyrightText: 2026 Signal Slot, Inc.",
             "# SPDX-FileCopyrightText: 2025 Imagination Technologies Ltd.",
             "# Mesa 26.2.1 pco, BXS-4-64 (36.53.104.796): tools/pco_shc/capture_usc.c output per program.",
             "# Written by: tools/pco_shc/gen_usc_blobs.py capture <mesa>/build/src/imagination/vulkan/capture_usc",
             "# name | capture_usc arguments | temps | words"]
    for name, args in PROGRAMS:
        argv = args.split()
        if argv[0] == "precomp":
            m = re.search(r"\b" + argv[1] + r"\s*=\s*(\d+)", hdr)
            if not m:
                sys.exit(f"{argv[1]} not in pco_uscgen_programs.h")
            argv = ["precomp", m.group(1)]
        out = subprocess.run([capture_usc] + argv, check=True, capture_output=True, text=True).stdout.split("\n")
        lines.append(f"{name} | {args} | {out[0]} | {out[1]}")
    text = "\n".join(lines) + "\n"
    if check:
        if open(MANIFEST).read() != text:
            sys.exit("usc_blobs.txt differs from what this pco build captures")
        print("gen_usc_blobs: usc_blobs.txt = this pco build's output")
    else:
        open(MANIFEST, "w").write(text)


def main():
    a = sys.argv[1:]
    check = "--check" in a
    a = [x for x in a if x != "--check"]
    if a[:1] == ["render"]:
        render(check)
    elif a[:1] == ["capture"] and len(a) == 2:
        capture(a[1], check)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
