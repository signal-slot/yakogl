# gate_st_table_selftest.sh - checks tools/vivante/gate_st_table.sh with stub
# etna_shc and generator programs, without a Mesa tree.
#
#   tools/vivante/gate_st_table_selftest.sh
#
# Prints "N ok, M failed" and exits 0 only if none failed.

set -eu
export LC_ALL=C
unset MESA_ETNA_TREE ETNA_SHC GATE_ST_TABLE_GEN

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
GATE=$HERE/gate_st_table.sh

ok=0
failed=0
pass() { ok=$((ok + 1)); }
fail() {
	failed=$((failed + 1))
	echo "FAIL: $1" >&2
}

TMP=$(mktemp -d "${TMPDIR:-/tmp}/gate_st_table_selftest.XXXXXX") || exit 1
trap 'rm -rf "$TMP"' EXIT

run_gate() {
	rc=0
	"$@" >"$TMP/out" 2>"$TMP/err" || rc=$?
}

# exit 2, and stderr is exactly one line: `gap:` naming MESA_ETNA_TREE
expect_gap() {
	local name=$1 n
	shift
	run_gate "$@"
	n=$(grep -c '^gap:' "$TMP/err" || true)
	if [ "$rc" -eq 2 ] && [ "$n" -eq 1 ] && [ "$(wc -l <"$TMP/err")" -eq 1 ] &&
		grep -q '^gap: .*MESA_ETNA_TREE' "$TMP/err" && grep -q 'NOT run' "$TMP/err"; then
		pass
	else
		fail "$name (rc=$rc, gap lines=$n)"
	fi
}

# Stub tool and generators.
mkdir -p "$TMP/tree/build-etnaviv/src/gallium/drivers/etnaviv"
SHC=$TMP/tree/build-etnaviv/src/gallium/drivers/etnaviv/etna_shc
printf '#!/bin/sh\nexit 0\n' >"$SHC"
printf '#!/bin/sh\necho "vivante_blobs_st.rs: regenerated byte for byte (3 rows)"\nexit 0\n' >"$TMP/gen_pass"
printf '#!/bin/sh\necho "vivante_blobs_st.rs: 1 changed"\necho "    changed: row_a"\nexit 1\n' >"$TMP/gen_diff"
printf '#!/bin/sh\necho "gap: no etna_shc or no glslangValidator" >&2\necho noise >&2\nexit 2\n' >"$TMP/gen_gap"
printf '#!/bin/sh\necho boom >&2\nexit 3\n' >"$TMP/gen_crash"
chmod +x "$SHC" "$TMP"/gen_*

# gap: no tree, missing tree, tree without the tool, ETNA_SHC not executable
expect_gap "no tree" "$GATE"
expect_gap "tree is not a directory" env MESA_ETNA_TREE="$TMP/nope" "$GATE"
mkdir "$TMP/empty"
expect_gap "tree without etna_shc" env MESA_ETNA_TREE="$TMP/empty" "$GATE"
expect_gap "ETNA_SHC not executable" env ETNA_SHC="$TMP/nope" "$GATE"
# a tool missing as the generator sees it (glslangValidator): one gap line
expect_gap "generator reports a gap" env MESA_ETNA_TREE="$TMP/tree" GATE_ST_TABLE_GEN="$TMP/gen_gap" "$GATE"
expect_gap "generator gap with ETNA_SHC" env ETNA_SHC="$SHC" GATE_ST_TABLE_GEN="$TMP/gen_gap" "$GATE"

# pass
run_gate env MESA_ETNA_TREE="$TMP/tree" GATE_ST_TABLE_GEN="$TMP/gen_pass" "$GATE"
if [ "$rc" -eq 0 ] && grep -q 'matches' "$TMP/out"; then pass; else fail "pass (rc=$rc)"; fi

# mismatch names the rows
run_gate env MESA_ETNA_TREE="$TMP/tree" GATE_ST_TABLE_GEN="$TMP/gen_diff" "$GATE"
if [ "$rc" -eq 1 ] && grep -q 'changed: row_a' "$TMP/out" && ! grep -q '^gap:' "$TMP/err"; then
	pass
else
	fail "mismatch (rc=$rc)"
fi

# a crash is a failure, neither a pass nor a gap
run_gate env MESA_ETNA_TREE="$TMP/tree" GATE_ST_TABLE_GEN="$TMP/gen_crash" "$GATE"
if [ "$rc" -eq 1 ] && ! grep -q '^gap:' "$TMP/err"; then pass; else fail "generator crash (rc=$rc)"; fi

# usage
run_gate "$GATE" extra
if [ "$rc" -eq 64 ]; then pass; else fail "usage (rc=$rc)"; fi

for s in "$GATE" "$HERE/gate_st_table_selftest.sh"; do
	if bash -n "$s"; then pass; else fail "bash -n $s"; fi
done

echo "$ok ok, $failed failed"
[ "$failed" -eq 0 ]
