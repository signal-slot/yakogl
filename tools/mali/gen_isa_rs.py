"""Generate the Mali-G610 (Valhall, arch 10) instruction table in Rust.

    tools/mali/gen_isa_rs.py <isa-v9-v14.xml> <valhall dir> > src/shaderc/online/mali/isa/v10.rs

Two readings of the ISA, both vendored unmodified under third_party/mesa-26.2.1/
(MIT), go into one file:

  - The encoding: Arm's src/panfrost/compiler/kraid/isa-v9-v14.xml
    ("Copyright (C) 2026 Arm Ltd.", "AUTOGENERATED"). Every <instruction>
    whose since..until range holds 10 becomes one Op: its exact fields (the
    opcode), its reserved bits, its free fields and virtual operands (the
    Instr's operands), and the fields it computes from them (<expression>).
    The expressions become Rust with checked arithmetic. Mesa's Kraid reads
    the same file with a proc macro (kraid/proc/isa/), which is where the
    semantics below come from: an exact field is a constant; `align(n)`
    stores the value, which must be a multiple of n; `shr(n)` stores
    value >> n; `minus(n)` stores value - n (proc/isa/encoder.rs:1036-1068);
    a virtual field is an input of the encoder (encoder.rs:907-918) and its
    expression gives it back from the word.
  - The disassembly: Mesa's src/panfrost/compiler/bifrost/valhall/ISA.xml,
    read by Mesa's own valhall.py (imported from the vendored directory,
    unmodified), transcribed from disasm.py's template as data: one list of
    print steps per instruction, interpreted by isa/mod.rs `describe_word`,
    so that our text and Mesa's can be compared line for line.

The generator fails (no output, exit 1) rather than emitting a table it cannot
vouch for: two non-alias variants whose opcode bits can match one word, an
alias whose base is missing or whose opcode does not contain the base's, an
expression naming a symbol the variant does not have or one defined after it,
a Mesa opcode tree in which an instruction's opcode is a prefix of another's,
a print table that does not exist, or a FAU table entry without its leading dot
(a step that indexes past a table is refused at run time, DescribeError::NoName,
where Mesa reads past its array).
"""

import importlib.util
import os
import sys
import xml.etree.ElementTree as ET

ARCH = 10


class GenError(Exception):
    pass


def check(cond, msg):
    if not cond:
        raise GenError(msg)


def rust_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def camel(s):
    out = ''
    for part in s.replace('.', '_').split('_'):
        if part:
            out += part[0].upper() + part[1:].lower()
    return out


# ---- Arm's XML ---------------------------------------------------------------


def in_arch(el):
    return int(el.get('since')) <= ARCH <= int(el.get('until'))


class EnumDef:
    def __init__(self, el):
        self.name = el.get('name')
        self.values = [(v.get('name'), int(v.get('value'))) for v in el.findall('value')]
        self.by_name = {n: v for n, v in self.values}
        check(len(self.by_name) == len(self.values), f'enum {self.name}: a name twice')
        self.valid = sorted(set(v for _, v in self.values))

    def rust(self):
        return 'E_' + self.name.upper()


class Symbol:
    """A physical field, a virtual field: what an expression can name."""

    def __init__(self, idx, el, enums, physical):
        self.idx = idx
        self.el = el
        self.name = el.get('name')
        self.physical = physical
        tname = el.get('type')
        self.tname = tname
        self.enum = enums.get(tname) if tname else None
        check(tname is None or self.enum is not None or tname in PLAIN_TYPES, f'{self.name}: unknown type {tname}')
        if physical:
            self.pos = int(el.get('pos'))
            self.width = int(el.get('width'))
            check(self.pos + self.width <= 64, f'{self.name}: past bit 63')
        mod = el.get('modifier')
        self.mod = None
        if mod:
            kind, arg = mod.rstrip(')').split('(')
            check(kind in ('align', 'shr', 'minus'), f'{self.name}: modifier {mod}')
            self.mod = (kind, int(arg))
        self.exact = None
        if el.get('exact') is not None:
            self.exact = literal(el.get('exact'), self.enum)
            check(self.mod is None, f'{self.name}: an exact field with a modifier')
        self.expr = el.find('expression')
        check(not (self.exact is not None and self.expr is not None), f'{self.name}: exact and expression')
        self.restrict = None
        if el.get('restrict'):
            check(self.enum is not None, f'{self.name}: restrict without an enum')
            self.restrict = sorted(set(self.enum.by_name[n] for n in el.get('restrict').split()))
        self.default = None
        if el.get('default') is not None:
            self.default = literal(el.get('default'), self.enum)
        self.min = int(el.get('min')) if el.get('min') is not None else None
        self.max = int(el.get('max')) if el.get('max') is not None else None
        check(physical or self.exact is not None or self.expr is not None, f'virtual {self.name}: no value')
        check(tname is not None or self.expr is not None or self.exact is not None, f'{self.name}: neither a type nor an expression')

    def kind(self):
        t = self.tname
        if self.enum is not None:
            return f'Kind::Enum(&{self.enum.rust()})'
        bits = self.width if self.physical else 32
        if self.mod and self.mod[0] == 'shr':
            bits += self.mod[1]
        if self.mod and self.mod[0] == 'minus':
            bits += 1
        if t == 'SourceEncoding':
            return 'Kind::Source'
        if t == 'SourceEncoding64':
            return 'Kind::Source64'
        if t in ('int', 'pc_rel_label_signed'):
            return f'Kind::Int {{ bits: {bits} }}'
        return f'Kind::Uint {{ bits: {bits} }}'


PLAIN_TYPES = {'uint', 'int', 'SourceEncoding', 'SourceEncoding64', 'pc_rel_label_signed', 'pc_rel_label_unsigned',
               'float', 'V2F16', 'V2I16', 'V4I8'}


def literal(text, enum):
    if enum is not None and text in enum.by_name:
        return enum.by_name[text]
    check(text.isdigit(), f'literal {text!r} is not a number nor a value of {enum.name if enum else None}')
    return int(text)


class Variant:
    def __init__(self, el, enums, line):
        self.el = el
        self.line = line
        self.name = el.get('name')
        self.variant = el.get('variant')
        self.alias = el.get('alias')
        self.alias_variant = el.get('alias_variant')
        self.unit = el.get('exec_unit')
        self.mnemonic = self.name + ('.' + self.variant if self.variant else '')
        self.syms = []
        self.zero = 0
        self.ignore = 0
        for ch in el:
            if ch.tag == 'field':
                self.syms.append(Symbol(len(self.syms), ch, enums, True))
            elif ch.tag == 'virtual':
                self.syms.append(Symbol(len(self.syms), ch, enums, False))
            elif ch.tag == 'reserved':
                p, w = int(ch.get('pos')), int(ch.get('width'))
                m = ((1 << w) - 1) << p
                check(ch.get('type') in ('zero', 'ignore'), f'{self.mnemonic}: reserved type')
                if ch.get('type') == 'zero':
                    self.zero |= m
                else:
                    self.ignore |= m
        self.by_name = {}
        for s in self.syms:
            check(s.name not in self.by_name, f'{self.mnemonic}: {s.name} twice')
            self.by_name[s.name] = s
        self.exact_mask = 0
        self.exact_bits = 0
        owned = self.zero | self.ignore
        check((self.zero & self.ignore) == 0, f'{self.mnemonic}: reserved overlap')
        for s in self.syms:
            if not s.physical:
                continue
            m = ((1 << s.width) - 1) << s.pos
            check((owned & m) == 0, f'{self.mnemonic}: {s.name} overlaps')
            owned |= m
            if s.exact is not None:
                check(s.exact < (1 << s.width), f'{self.mnemonic}: {s.name} exact too wide')
                self.exact_mask |= m
                self.exact_bits |= s.exact << s.pos
        check(owned == (1 << 64) - 1, f'{self.mnemonic}: bits {hex(~owned & ((1 << 64) - 1))} have no owner')
        # Operands: free physical fields and virtuals with an expression, XML order.
        self.operands = [s for s in self.syms if (s.physical and s.exact is None and s.expr is None)
                         or (not s.physical and s.expr is not None)]
        self.computed = [s for s in self.syms if s.physical and s.expr is not None]
        self.virtuals = [s for s in self.syms if not s.physical and s.expr is not None]
        self.fixed_virtuals = [s for s in self.syms if not s.physical and s.exact is not None]
        self.roles = self.syntax_roles()

    def syntax_roles(self):
        roles = {}
        syn = self.el.find('syntax')
        for ch in syn.iter():
            n = ch.get('name')
            if ch.tag == 'modifier':
                check(n in self.by_name, f'{self.mnemonic}: syntax modifier {n} names nothing')
                roles[n] = 'Role::Modifier'
            elif ch.tag == 'src':
                check(n in self.by_name, f'{self.mnemonic}: syntax src {n} names nothing')
                roles[n] = 'Role::Src'
            elif ch.tag in ('uint', 'int', 'pc_rel_label_signed', 'pc_rel_label_unsigned'):
                check(n in self.by_name, f'{self.mnemonic}: syntax {ch.tag} {n} names nothing')
                roles[n] = 'Role::Immediate'
        for n in ('staging_register_index', 'staging_register_write_index'):
            if n in self.by_name:
                roles[n] = 'Role::Staging'
        if 'dest_register_index' in self.by_name:
            roles['dest_register_index'] = 'Role::Dest'
        roles['flow'] = 'Role::Flow'
        roles['fau_page_index'] = 'Role::FauPage'
        return roles


# ---- expressions ---------------------------------------------------------------

# Rust for the XML's operators. A result is (code, kind): 'atom' (a value,
# a call, an index), 'cast' (`(a == b) as u32`, which binds tighter than
# every binary operator), 'op' (a binary operator) or 'if'. Parentheses go
# only where Rust needs them, so the generated code has none that rustc's
# unused_parens would name.
BITWISE = {'bitwise_and': '&', 'bitwise_or': '|', 'bitwise_xor': '^'}
COMPARE = {'equal': '==', 'less_than': '<', 'greater_equal': '>=', 'greater_than': '>', 'less_equal': '<=',
           'not_equal': '!='}
CHECKED = {'add': 'add', 'sub': 'sub', 'rshift': 'shr', 'lshift': 'shl'}
CHAINED = {'bitwise_and', 'bitwise_or', 'add'}


def operand(x):
    code, kind = x
    return f'({code})' if kind in ('op', 'if') else code


def atom(x):
    code, kind = x
    return code if kind == 'atom' else f'({code})'


def expr_rust(v, e, enums, upto):
    """Rust for one <expression>; `upto` is the set of symbol indices that
    are defined when it runs."""
    op = e.get('operator')
    if op is None:
        if e.get('identifier') is not None:
            n = e.get('identifier')
            check(n in v.by_name, f'{v.mnemonic}: expression names {n}, which it does not have')
            s = v.by_name[n]
            check(s.idx in upto, f'{v.mnemonic}: expression reads {n} before it is defined')
            return f's[{s.idx}]', 'atom'
        t = e.get('type') or e.get('enum')
        en = enums.get(t)
        return str(literal(e.get('literal'), en)), 'atom'
    args = list(e)
    sub = [expr_rust(v, a, enums, upto) for a in args]
    if op == 'if':
        check(len(sub) >= 3 and len(sub) % 2 == 1, f'{v.mnemonic}: if arity')
        out = ''
        for i in range(0, len(sub) - 1, 2):
            out += ('if ' if i == 0 else ' else if ') + f'{operand(sub[i])} != 0 {{ {sub[i + 1][0]} }}'
        return out + f' else {{ {sub[-1][0]} }}', 'if'
    if op == 'inside':
        for a in args[1:]:
            check(a.get('operator') is None and a.get('identifier') is None, f'{v.mnemonic}: inside of a non-literal')
        return f'[{", ".join(x[0] for x in sub[1:])}].contains(&{atom(sub[0])}) as u32', 'cast'
    if op == 'countones':
        check(len(sub) == 1, 'countones arity')
        return f'{atom(sub[0])}.count_ones()', 'atom'
    if op == 'mask':
        check(len(sub) == 1, 'mask arity')
        return f'mask({sub[0][0]})?', 'atom'
    check(op in BITWISE or op in COMPARE or op in CHECKED, f'{v.mnemonic}: unknown operator {op}')
    if op in CHAINED:
        check(len(sub) >= 2, f'{op} arity')
    else:
        check(len(sub) == 2, f'{op} arity')
    # Kraid folds a chain from the right (proc/isa/expr.rs:76-91); for and,
    # or and add the order does not change the value.
    out = sub[-1]
    for a in reversed(sub[:-1]):
        if op in BITWISE:
            out = (f'{operand(a)} {BITWISE[op]} {operand(out)}', 'op')
        elif op in COMPARE:
            out = (f'({operand(a)} {COMPARE[op]} {operand(out)}) as u32', 'cast')
        else:
            out = (f'{CHECKED[op]}({a[0]}, {out[0]})?', 'atom')
    return out


# ---- Mesa's ISA.xml (the disassembler) -----------------------------------------


def load_valhall(dirpath):
    # No __pycache__ under third_party/.
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location('valhall', os.path.join(dirpath, 'valhall.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod, mod.valhall_parse_isa(os.path.join(dirpath, 'ISA.xml'))


def mesa_table(enums, name, used):
    check(name in enums, f'Mesa print table valhall_{name} does not exist')
    used.add(name)
    return 'M_' + name.upper()


def mesa_steps(op, enums, safe_name, used):
    """disasm.py's print_instr(op), as data (the template, lines 107-193)."""
    st = [f'S::Text({rust_str(op.name)})']
    for mod in op.modifiers:
        if mod.name in ('staging_register_count', 'staging_register_write_count'):
            continue
        if op.name.startswith('ARSHIFT_') and mod.name == 'signed':
            continue
        if mod.is_enum:
            t = mesa_table(enums, safe_name(mod.enum), used)
            st.append(f'S::Table {{ start: {mod.start}, mask: {hex((1 << mod.size) - 1)}, table: &{t} }}')
        else:
            st.append(f'S::Flag {{ start: {mod.start}, text: {rust_str("." + mod.name)} }}')
    mesa_table(enums, 'flow', used)
    check(op.offset['flow'] == 59 and op.mask['flow'] == 0xF, f'{op.name}: flow not at 59')
    check(op.offset['fau_page'] == 57 and op.mask['fau_page'] == 3, f'{op.name}: fau page not at 57')
    st.append('S::Flow')
    no_comma = True
    for dest in op.dests:
        no_comma = False
        check(dest.offset['mode'] == 46 and dest.offset['value'] == 40, f'{op.name}: dest not at 40')
        st.append(f'S::Dest {{ size: {dest.size} }}')
    sr_count = None
    for sr in op.staging:
        if not no_comma:
            st.append('S::Text(", ")')
        no_comma = False
        # The template's loop, with its carried variable (disasm.py:129-137).
        if sr.count != 0:
            sr_count = f'Count::Fixed({sr.count})'
        else:
            for mod in op.modifiers:
                if mod.name == 'staging_register_write_count' and sr.write:
                    sr_count = f'Count::Field {{ start: {mod.start}, mask: {hex((1 << mod.size) - 1)}, plus: 1 }}'
                elif mod.name == 'staging_register_count':
                    sr_count = f'Count::Field {{ start: {mod.start}, mask: {hex((1 << mod.size) - 1)}, plus: 0 }}'
        check(sr_count is not None, f'{op.name}: a staging register count from nowhere')
        check(sr.mask['value'] == 0x3F, f'{op.name}: staging mask')
        st.append(f'S::Staging {{ start: {sr.offset["value"]}, count: {sr_count} }}')
    for src in op.srcs:
        if not no_comma:
            st.append('S::Text(", ")')
        no_comma = False
        check(src.mask['value'] == 0x3F and src.mask['mode'] == 3 and src.offset['mode'] == src.start + 6,
              f'{op.name}: source layout')
        if src.absneg:
            how = f'Float::AbsNeg {{ neg: {src.offset["neg"]}, abs: {src.offset["abs"]} }}'
        elif src.is_float:
            how = 'Float::Plain'
        else:
            how = 'Float::No'
        sfx = []
        if src.swizzle:
            t = 'widen' if src.size == 32 else 'swizzles_16_bit'
            sfx.append((src.offset['swizzle'], src.mask['swizzle'], t))
        if src.lanes:
            sfx.append((src.offset['widen'], src.mask['widen'], 'lanes_8_bit'))
        elif src.halfswizzle:
            sfx.append((src.offset['widen'], src.mask['widen'], 'half_swizzles_8_bit'))
        elif src.widen:
            sfx.append((src.offset['widen'], src.mask['widen'], f'swizzles_{src.size}_bit'))
        elif src.combine:
            sfx.append((src.offset['combine'], src.mask['combine'], 'combine'))
        if src.lane:
            sfx.append((src.offset['lane'], src.mask['lane'], f'lane_{src.size}_bit'))
        suffix = [f'Suffix::Table {{ start: {s}, mask: {hex(m)}, table: &{mesa_table(enums, t, used)} }}'
                  for s, m, t in sfx]
        if 'not' in src.offset:
            suffix.append(f'Suffix::Not {{ bit: {src.offset["not"]} }}')
        st.append(f'S::Src {{ start: {src.start}, size: {src.size}, float: {how}, suffix: &[{", ".join(suffix)}] }}')
    for imm in op.immediates:
        prefix = '#' if imm.name == 'constant' else imm.name + ':'
        st.append(f'S::Imm {{ prefix: {rust_str(", " + prefix)}, start: {imm.start}, size: {imm.size}, '
                  f'signed: {"true" if imm.signed else "false"} }}')
    return st


def mesa_opcode(op):
    """The opcode bits of one Mesa instruction: its subcodes, in tree order."""
    mask = val = 0
    for sc in op.opcode:
        check((mask & (sc.mask << sc.start)) == 0, f'{op.name}: subcodes overlap')
        mask |= sc.mask << sc.start
        val |= sc.value << sc.start
    return mask, val


def check_mesa_tree(instructions):
    # disasm.py's OpBucket: a node is an instruction or a switch, never both.
    paths = {}
    for op in instructions:
        key = tuple((sc.start, sc.mask, sc.value) for sc in op.opcode)
        check(key not in paths, f'{op.name}: the same opcode as {paths.get(key)}')
        paths[key] = op.name
    for k in paths:
        for j in range(1, len(k)):
            if k[:j] in paths:
                raise GenError(f'{paths[k]}: its opcode extends {paths[k[:j]]}\'s')


# ---- output --------------------------------------------------------------------


def generate(kraid_path, valhall_dir):
    out = []
    w = out.append
    text = open(kraid_path, encoding='utf-8').read()
    root = ET.fromstring(text)
    # Each <instruction>'s line in the file, for the table's comments.
    starts = [n for n, l in enumerate(text.split('\n'), 1) if l.lstrip().startswith('<instruction ')]
    check(len(starts) == len(root.findall('instruction')), 'an <instruction> tag that does not start its line')
    enums = {}
    for e in root.findall('enum'):
        if in_arch(e):
            check(e.get('name') not in enums, f'enum {e.get("name")}: two versions for v{ARCH}')
            enums[e.get('name')] = EnumDef(e)
    variants = []
    for k, el in enumerate(root.findall('instruction')):
        if in_arch(el):
            variants.append(Variant(el, enums, starts[k]))
    by_key = {}
    for v in variants:
        key = (v.name, v.variant)
        check(key not in by_key, f'{v.mnemonic} twice for v{ARCH}')
        by_key[key] = v
    # Decoding is unambiguous: no two non-alias opcodes can match one word.
    base = [v for v in variants if v.alias is None]
    for i in range(len(base)):
        for j in range(i + 1, len(base)):
            a, b = base[i], base[j]
            m = a.exact_mask & b.exact_mask
            check((a.exact_bits & m) != (b.exact_bits & m), f'{a.mnemonic} and {b.mnemonic} can match one word')
    for v in variants:
        if v.alias is not None:
            b = by_key.get((v.alias, v.alias_variant))
            check(b is not None and b.alias is None, f'{v.mnemonic}: alias of a missing {v.alias}')
            check((v.exact_mask & b.exact_mask) == b.exact_mask and (v.exact_bits & b.exact_mask) == b.exact_bits,
                  f'{v.mnemonic}: its opcode does not contain {b.mnemonic}\'s')
            v.base = b
    names = {}
    for v in variants:
        n = camel(v.mnemonic)
        if n[0].isdigit():
            n = 'X' + n
        check(n not in names, f'{v.mnemonic} and {names.get(n)} have one Rust name {n}')
        names[n] = v.mnemonic
        v.rust = n
    max_ops = max(len(v.operands) for v in variants)
    max_syms = max(len(v.syms) for v in variants)

    _, (minstr, mimm, menums, _, safe_name) = load_valhall(valhall_dir)
    check_mesa_tree(minstr)
    check(len(mimm) == 32, 'Mesa immediates: not 32')

    w('// SPDX-License-Identifier: Apache-2.0 AND MIT')
    w('// SPDX-FileCopyrightText: 2026 Arm Ltd.')
    w('// SPDX-FileCopyrightText: 2021 Collabora, Ltd.')
    w('//')
    w('// v10.rs - GENERATED by tools/mali/gen_isa_rs.py from Mesa 26.2.1\'s')
    w('// src/panfrost/compiler/kraid/isa-v9-v14.xml (the encoding) and')
    w('// src/panfrost/compiler/bifrost/valhall/ISA.xml through valhall.py (the')
    w('// disassembly), third_party/mesa-26.2.1/, unmodified.')
    w('// DO NOT EDIT: tools/check.sh regenerates it and requires these bytes.')
    w('//')
    w('//! The Valhall v10 instruction table: one [`Op`] per `<instruction>` of')
    w('//! isa-v9-v14.xml valid for arch 10, its operands, the fields it computes,')
    w('//! and Mesa\'s disassembler as print steps. The code that reads it is')
    w('//! `super` (isa/mod.rs).')
    w('// The layout is the generator\'s: regenerated, not formatted.')
    w('#![cfg_attr(rustfmt, rustfmt_skip)]')
    w('')
    w('use super::{add, mask, shl, shr, sub, Count, EnumInfo, ExprError, Float, Kind, MesaOp, Modifier, OpInfo, Operand, Role, Suffix, Sym, SymKind, Unit, S};')
    w('')
    w(f'/// The `<instruction>` elements of isa-v9-v14.xml valid for v{ARCH}.')
    w(f'pub const VARIANTS: usize = {len(variants)};')
    w('/// The most operands one variant has.')
    w(f'pub const MAX_OPERANDS: usize = {max_ops};')
    w('/// The most fields and virtuals one variant has.')
    w(f'pub const MAX_SYMBOLS: usize = {max_syms};')
    w('')
    used_enums = sorted({s.enum.name for v in variants for s in v.syms if s.enum is not None})
    for en in used_enums:
        e = enums[en]
        vals = ', '.join(f'({rust_str(n)}, {x})' for n, x in e.values)
        w(f'pub static {e.rust()}: EnumInfo = EnumInfo {{ name: {rust_str(e.name)}, values: &[{vals}], valid: &[{", ".join(map(str, e.valid))}] }};')
    w('')
    w('/// One per variant, in isa-v9-v14.xml order; [`OPS`] has the same order.')
    w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
    w('#[repr(u16)]')
    w('pub enum Op {')
    for k, v in enumerate(variants):
        w(f'    /// `{v.mnemonic}`{" (an alias of `" + v.base.mnemonic + "`)" if v.alias else ""}, line {v.line}.')
        w(f'    {v.rust} = {k},')
    w('}')
    w('')
    w('impl Op {')
    w('    /// Every variant, in order.')
    w('    pub const ALL: [Op; VARIANTS] = [')
    for v in variants:
        w(f'        Op::{v.rust},')
    w('    ];')
    w('}')
    w('')
    units = {'fma': 'Unit::Fma', 'cvt': 'Unit::Cvt', 'sfu': 'Unit::Sfu', 'msg': 'Unit::Msg'}
    for k, v in enumerate(variants):
        w(f'// {v.mnemonic}: isa-v9-v14.xml line {v.line}.')
        w(f'static SYMS_{k}: [Sym; {len(v.syms)}] = [')
        for s in v.syms:
            if s.exact is not None:
                sk = f'SymKind::Exact({s.exact})'
            elif s.physical and s.expr is not None:
                sk = 'SymKind::Computed'
            else:
                sk = f'SymKind::Operand({v.operands.index(s)})'
            if s.physical:
                code = f'Sym::field({rust_str(s.name)}, {s.pos}, {s.width}, {s.kind()}, {sk})'
            else:
                code = f'Sym::virt({rust_str(s.name)}, {s.kind()}, {sk})'
            if s.mod:
                code += f'.modifier(Modifier::{s.mod[0].capitalize()}({s.mod[1]}))'
            if s.restrict is not None:
                code += f'.restrict(&[{", ".join(map(str, s.restrict))}])'
            if s.min is not None:
                code += f'.range({s.min}, {s.max})'
            w(f'    {code},')
        w('];')
        w(f'static OPERANDS_{k}: [Operand; {len(v.operands)}] = [')
        for s in v.operands:
            d = 'None' if s.default is None else f'Some({s.default})'
            role = v.roles.get(s.name, 'Role::Other')
            w(f'    Operand {{ name: {rust_str(s.name)}, sym: {s.idx}, role: {role}, default: {d} }},')
        w('];')
        if v.virtuals:
            w(f'fn virtuals_{k}(s: &mut [u32; MAX_SYMBOLS]) -> Result<(), ExprError> {{')
            defined = {x.idx for x in v.syms if x.physical or x.exact is not None}
            for s in v.virtuals:
                code = expr_rust(v, s.expr, enums, defined)[0]
                w(f'    s[{s.idx}] = {code};')
                defined.add(s.idx)
            w('    Ok(())')
            w('}')
        if v.computed:
            w(f'fn computed_{k}(s: &mut [u32; MAX_SYMBOLS]) -> Result<(), ExprError> {{')
            defined = {x.idx for x in v.syms if not (x.physical and x.expr is not None)}
            for s in v.computed:
                code = expr_rust(v, s.expr, enums, defined)[0]
                w(f'    s[{s.idx}] = {code};')
                defined.add(s.idx)
            w('    Ok(())')
            w('}')
    w('')
    w('/// The variants\' tables, in [`Op`] order.')
    w('pub static OPS: [OpInfo; VARIANTS] = [')
    for k, v in enumerate(variants):
        alias = f'Some(Op::{v.base.rust})' if v.alias else 'None'
        var = 'None' if v.variant is None else f'Some({rust_str(v.variant)})'
        virt = f'Some(virtuals_{k})' if v.virtuals else 'None'
        comp = f'Some(computed_{k})' if v.computed else 'None'
        w(f'    OpInfo {{ op: Op::{v.rust}, mnemonic: {rust_str(v.mnemonic)}, name: {rust_str(v.name)}, variant: {var}, '
          f'alias_of: {alias}, unit: {units[v.unit]}, line: {v.line}, exact_mask: {hex(v.exact_mask)}, '
          f'exact_bits: {hex(v.exact_bits)}, zero_mask: {hex(v.zero)}, ignore_mask: {hex(v.ignore)}, '
          f'syms: &SYMS_{k}, operands: &OPERANDS_{k}, virtuals: {virt}, computed: {comp} }},')
    w('];')
    w('')
    # Mesa's disassembler.
    used = set()
    mops = []
    for op in minstr:
        steps = mesa_steps(op, menums, safe_name, used)
        m, val = mesa_opcode(op)
        mops.append(f'    MesaOp {{ name: {rust_str(op.name)}, mask: {hex(m)}, value: {hex(val)}, steps: &[\n' + ''.join(f'        {x},\n' for x in steps) + '    ] },')
    w('/// Mesa\'s `va_immediates` (ISA.xml `<lut name="Immediates">`).')
    w('pub static MESA_IMMEDIATES: [u32; 32] = [' + ', '.join(hex(x) for x in mimm) + '];')
    for name in sorted(used | {'fau_special_page_0', 'fau_special_page_1', 'fau_special_page_3'}):
        e = menums[name]
        ents = [('' if v.default else '.' + v.value) for v in e.values]
        if name.startswith('fau_special_page'):
            # va_print_src prints these from their second byte (`+ 1`).
            check(all(x.startswith('.') for x in ents), f'valhall_{name}: an entry with no leading dot')
            check(len(ents) == 16, f'valhall_{name}: not 16 entries')
        w(f'pub static M_{name.upper()}: [&str; {len(ents)}] = [' + ', '.join(rust_str(x) for x in ents) + '];')
    w(f'/// Mesa\'s instructions (ISA.xml), in its order: {len(minstr)}.')
    w(f'pub static MESA_OPS: [MesaOp; {len(minstr)}] = [')
    out.extend(mops)
    w('];')
    return '\n'.join(out) + '\n'


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        sys.stdout.write(generate(argv[1], argv[2]))
    except GenError as e:
        print(f'gen_isa_rs.py: {e}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
