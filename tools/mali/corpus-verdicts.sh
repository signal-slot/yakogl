# The Mali back end's verdict on every shader source under tools/shaders,
# one line each ("<path>: ok" or "<path>: <the gap>"), sorted by path, as
# src/shaderc/online/mali/tests.rs `the_corpus_verdicts_are_pinned` reads
# them. tools/mali/corpus-verdicts.txt pins them: the test fails until a
# change that moves a verdict writes the file again.
#
#   tools/mali/corpus-verdicts.sh            print the verdicts
#   tools/mali/corpus-verdicts.sh --tally    the verdicts counted, largest first
#   tools/mali/corpus-verdicts.sh --write    write tools/mali/corpus-verdicts.txt
set -euo pipefail
cd "$(dirname "$0")/../.."
out=$(YAKOGL_CORPUS_PRINT=1 cargo test -q --no-default-features --features host-test,gpu-mali,shaderc-online,no-shader-table \
  --lib -- --exact shaderc::online::mali::tests::the_corpus_verdicts_are_pinned --nocapture 2>/dev/null |
  sed -n 's/^corpus: //p')
[ -n "$out" ] || { echo "corpus-verdicts.sh: the test printed no verdict" >&2; exit 1; }
case "${1-}" in
  --tally) printf '%s\n' "$out" | sed 's/^[^:]*: //' | sort | uniq -c | sort -rn ;;
  --write)
    {
      echo "# SPDX-License-Identifier: Apache-2.0"
      echo "# SPDX-FileCopyrightText: 2026 Signal Slot, Inc."
      echo "# GENERATED by tools/mali/corpus-verdicts.sh --write: the Mali back end's"
      echo "# verdict on every source under tools/shaders (the_corpus_verdicts_are_pinned)."
      printf '%s\n' "$out"
    } > tools/mali/corpus-verdicts.txt
    echo "tools/mali/corpus-verdicts.txt: $(printf '%s\n' "$out" | wc -l) verdicts" ;;
  "") printf '%s\n' "$out" ;;
  *) echo "usage: $0 [--tally|--write]" >&2; exit 2 ;;
esac
