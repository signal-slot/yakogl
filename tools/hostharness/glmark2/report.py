"""glmark2 host run (run.sh): the findings table and the shader corpus.

usage: report.py <out> --commit C --size WxH --frames N [--shaders DIR]
                 [--findings FINDINGS.md] [--settings FILE] [--profile] gpu...

Reads <out>/entries.txt, <out>/logs/<gpu>/<i>.{log,rc} and
<out>/capture/<gpu>/<hash>.<stage>. Prints the summary; with --shaders,
rewrites DIR/*.glsl and DIR/index.txt (the README there is kept); with
--findings, rewrites the part of FINDINGS.md between the generated markers
(the text around them is kept). --settings names the file of the V3D
settings the run used (run.sh's v3d-settings.txt), listed in the summary.
--profile (run.sh GM2_PROFILE=1) writes <out>/profile-<gpu>.md from shim.c's
"gm2: gl-time", "gm2: gl-frames" and "gm2: draw-steps" lines and, where run.sh's GM2_PERF=1
left them, logs/<gpu>/<i>.perf-{self,children}.txt.
"""
import argparse
import collections
import os
import re
import sys

BEGIN = "<!-- generated by tools/hostharness/glmark2/report.py: begin -->"
END = "<!-- generated by tools/hostharness/glmark2/report.py: end -->"

# What a line of a run is, in order; the first match names it. A line that
# is neither one of these nor NOISE is a finding of kind "other", so a line
# nobody expected is listed rather than lost.
CLASSES = [
    # an allocation refused (the V3D's carve-out, src/osal/linux.c, as the
    # board prints it), or the backend's line about one it could not make
    ("GPU memory", re.compile(r"out of GPU memory|no GPU memory")),
    # the V3D samples CPU-made tiled copies of each texture: their budget's
    # high-water, and copies given back early
    ("tiled copy", re.compile(r"^yakogl/v3d: (tiled copies high-water |a stale tiled copy )")),
    # the V3D's sampler-key program variants ("N built, M refused"): before
    # "refused draw", whose pattern its "0 refused (" would match
    ("sampler variant", re.compile(r"^yakogl/v3d: sampler variants ")),
    ("GL error", re.compile(r"^GL error 0x[0-9a-f]+ in \S+")),
    ("compile failure", re.compile(r"^gm2: compile-failed ")),
    ("link failure", re.compile(r"^gm2: link-failed ")),
    ("refused draw", re.compile(r"draw (was )?refused|the draw is refused|; refused\b|refused \(")),
    ("incomplete texture", re.compile(r"incomplete")),
    ("glGetError", re.compile(r"^gm2: glGetError ")),
    ("eglGetError", re.compile(r"^gm2: eglGetError ")),
    ("framebuffer", re.compile(r"^gm2: fb-incomplete ")),
    ("glmark2 error", re.compile(r"^Error: ")),
    ("panic", re.compile(r"panicked|panic:", re.I)),
    ("depth resolve", re.compile(r"did not resolve its depth")),
    ("dropped", re.compile(r"dropped|did not complete")),
    # glGetUniformLocation of a name the program has no active uniform for:
    # -1, no GL error (ES 2.0 2.10.4); listed, as it may hide a uniform the
    # compiler dropped
    ("no such uniform", re.compile(r"has no uniform '")),
]
# Lines that are not findings: glmark2's banner and result lines, the
# library's start-up and exit report, a bring-up dump (src/gl/draw.rs,
# dump_small_fs_block), shim.c's records (read separately).
NOISE = re.compile(
    r"^\s|^$|^=+$|FPS: \d|glmark2 Score:|^osal\(linux\): heap |^pvr_backend: init ok"
    r"|^osal\(linux\): v3d (carve-out|pending frees)"
    # the V3D backend's start-up lines and its per-frame job-arena high-water
    # (src/v3d/backend.rs); the binner pool is "not read" because the host
    # has no binner (linux.c answers OSAL_QUERY_V3D_BIN_POOL with no data)
    r"|^yakogl/v3d: (depth and stencil (apart|in one buffer)|job arenas for |two job arena sets"
    r"|clear program built|job arenas high-water at frame |binner tile pool high-water at frame \d+: not read"
    # the TFU path taken (linux.c models the TFU as the Pi 4's image turns it on)
    r"|tiled copies of \d+ bytes or more by the TFU$|the TFU made the \d+-level chain of a "
    # glGenerateMipmap's TFU counters (frame 1 and shutdown) and the jobs and
    # CPU waits of the run
    r"|TFU mipmap at (frame \d+|shutdown): |\d+ jobs submitted, \d+ CPU waits for a job$)"
    r"|^gm2: (shader|scene-begin|scene-end|egl-config|draw|gl-time|gpu-time|gl-frames|v3d-frames|v3d-waits) ")
SCENE_END = re.compile(r"^gm2: scene-end (.*): (ok|failed|unsupported) frames=(\d+) draws=(\d+) refused=(\d+)"
                       r" gl_errors=(\d+) incomplete_draws=(\d+)$")
# The library's warning for the first draw that sampled an incomplete texture
# (src/gl/draw.rs; once per process, so once per entry here).
INCOMPLETE_LINE = "is incomplete and samples (0,0,0,1)"
# The V3D carve-out's line at exit (src/osal/linux.c report_heaps): one
# process per entry, so the entry's high-water.
CARVE = re.compile(r"^osal\(linux\): v3d carve-out: (\d+) bytes used at close, (\d+) at most, of (\d+); "
                   r"frees held \d+ \(\d+ bytes\); longest free run (\d+) bytes \(\d+ runs\); "
                   r"allocations refused (\d+)$")
SHADER = re.compile(r"^gm2: shader \d+ (vert|frag) ([0-9a-f]{16})$")
CONFIG = re.compile(r"^gm2: egl-config (.*)$")
# GM2_PROFILE (shim.c): an entry point's calls, wall and cpu ns per phase
# (without the GPU work linux.c models), the modelled GPU work's jobs and
# wall ns per phase, and the counted frames (gpu_jobs and gpu_ns since the
# GPU work was split out; a log from before has neither)
PHASES = ("setup", "frames", "teardown")
GL_TIME = re.compile(r"^gm2: gl-time (\w+) " + " ".join(r"%s=(\d+),(\d+),(\d+)" % p for p in PHASES) + "$")
GPU_TIME = re.compile(r"^gm2: gpu-time (\w+) " + " ".join(r"%s=(\d+),(\d+)" % p for p in PHASES) + "$")
GL_FRAMES = re.compile(r"^gm2: gl-frames swaps=(\d+) counted=(\d+) wall_ns=(\d+) cpu_ns=(\d+) gl_wall_ns=(\d+)"
                       r"(?: gpu_jobs=(\d+) gpu_ns=(\d+))?$")
# shim.c's per-step laps of a draw over the counted frames; the step names in
# src/draw_steps.rs Step order (the library's own, nothing else prints them);
# 12 is the STEPS == 12 assert there
DRAW_STEPS = re.compile(r"^gm2: draw-steps counted=(\d+) scopes=(\d+) untimed=(\d+) ns=(\d+(?:,\d+){11})$")
STEP_NAMES = ("GlProgram", "GlUniforms", "GlAttribs", "GlTextures", "GlState", "GcRest", "GcDs",
              "GcTiledCopy", "GcFrame", "GcUniforms", "GcVertex", "GcEmit")
# a line of perf report --stdio --sort symbol: [children%] self% [k|.] symbol,
# then the IPC columns ("-  -" where the samples carry no IPC)
PERF_LINE = re.compile(r"^\s*([\d.]+)%\s+(?:([\d.]+)%\s+)?\[(.)\]\s+(.+?)(?:\s+(?:-|[\d.]+%?)\s+(?:-|[\d.]+%?))?\s*$")
# the process's start-up frames, above every sample: not listed
PERF_SCAFFOLD = re.compile(r"^(_start|main|__libc_start_call_main|__libc_start_main(@@\S+)?)$")


def normalise(line):
    """One finding per kind of line: object names and ids out."""
    line = re.sub(r"^gm2: (compile-failed|link-failed) \d+", r"gm2: \1 <id>", line)
    line = re.sub(r"\b(texture|framebuffer|renderbuffer|buffer|program|shader) \d+", r"\1 <n>", line)
    line = re.sub(r"\d+ refused since init", "<n> refused since init", line)
    return line


def classify(line):
    for name, rx in CLASSES:
        if rx.search(line):
            return name
    return None if NOISE.search(line) else "other"


def read_runs(out, gpus):
    entries = open(os.path.join(out, "entries.txt")).read().splitlines()
    runs = {}
    for g in gpus:
        for i, entry in enumerate(entries):
            base = os.path.join(out, "logs", g, str(i))
            lines = open(base + ".log", errors="replace").read().splitlines()
            rc = int(open(base + ".rc").read().strip() or "0")
            r = {"entry": entry, "rc": rc, "end": None, "findings": collections.Counter(), "shaders": [],
                 "configs": [], "carve": None, "gl_time": {}, "gpu_time": {}, "gl_frames": None,
                 "draw_steps": None}
            # glmark2 prints "<info string>:" without a newline before a
            # scene's frames (main-loop.cpp, log_scene_info), so the first
            # line the library or shim.c writes after it carries that prefix
            prefixes = [m.group(1) + ":" for m in map(SCENE_END.match, lines) if m]
            for ln in lines:
                for p in prefixes:
                    if ln.startswith(p):
                        ln = ln[len(p):]
                m = SCENE_END.match(ln)
                if m:
                    r["end"] = (m.group(2),) + tuple(int(x) for x in m.groups()[2:])
                    continue
                m = SHADER.match(ln)
                if m:
                    r["shaders"].append((m.group(2), m.group(1)))
                    continue
                m = CONFIG.match(ln)
                if m:
                    r["configs"].append(m.group(1))
                    continue
                m = CARVE.match(ln)
                if m:
                    r["carve"] = tuple(int(x) for x in m.groups())
                    continue
                m = GL_TIME.match(ln)
                if m:
                    v = [int(x) for x in m.groups()[1:]]
                    r["gl_time"][m.group(1)] = {p: tuple(v[3 * k:3 * k + 3]) for k, p in enumerate(PHASES)}
                    continue
                m = GPU_TIME.match(ln)
                if m:
                    v = [int(x) for x in m.groups()[1:]]
                    r["gpu_time"][m.group(1)] = {p: tuple(v[2 * k:2 * k + 2]) for k, p in enumerate(PHASES)}
                    continue
                m = DRAW_STEPS.match(ln)
                if m:
                    r["draw_steps"] = {"counted": int(m.group(1)), "scopes": int(m.group(2)),
                                       "untimed": int(m.group(3)), "ns": [int(x) for x in m.group(4).split(",")]}
                    continue
                m = GL_FRAMES.match(ln)
                if m:
                    r["gl_frames"] = dict(zip(("swaps", "counted", "wall", "cpu", "gl_wall", "gpu_jobs", "gpu"),
                                              (int(x or 0) for x in m.groups())))
                    continue
                c = classify(ln)
                if c:
                    r["findings"][(c, normalise(ln.strip()))] += 1
            if rc != 0:
                why = {124: "timed out"}.get(rc, "exit status %d" % rc)
                r["findings"][("run", "the process ended with %s" % why)] += 1
            if r["end"] is not None:
                check_counters(r)
            if r["end"] is None:
                r["findings"][("run", "no scene-end line: the scene never finished")] += 1
            elif r["end"][0] != "ok":
                r["findings"][("scene", "glmark2: scene %s" % r["end"][0])] += 1
            runs[(g, i)] = r
    return entries, runs


def check_counters(r):
    """The scene-end line's GL core counters against the library's own lines
    of the same process: every GL error is logged here (run.sh sets
    YAKOGL_ERROR_LOG), and the incomplete-texture warning comes with the
    first such draw. A disagreement is a finding, so a counter that stops
    counting cannot pass as a zero."""
    gl_errors, incomplete = r["end"][4], r["end"][5]
    lines = sum(n for (kind, _), n in r["findings"].items() if kind == "GL error")
    if gl_errors != lines:
        r["findings"][("counter", "gl_errors=%d but %d GL error lines" % (gl_errors, lines))] += 1
    warned = any(INCOMPLETE_LINE in text for (kind, text) in r["findings"] if kind == "incomplete texture")
    if (incomplete > 0) != warned:
        r["findings"][("counter", "incomplete_draws=%d but the incomplete-texture line is %s"
                       % (incomplete, "there" if warned else "absent"))] += 1


def scene_of(entry):
    return entry.split(":", 1)[0]


def shader_files(out, gpus, entries, runs):
    """hash -> (stage, text, [entry index]); the texts must agree across GPUs."""
    found = {}
    for g in gpus:
        for i in range(len(entries)):
            for h, stage in runs[(g, i)]["shaders"]:
                path = os.path.join(out, "capture", g, "%s.%s" % (h, stage))
                text = open(path, newline="").read()
                if h in found:
                    if found[h][0] != stage or found[h][1] != text:
                        sys.exit("report.py: shader %s differs between runs" % h)
                    if i not in found[h][2]:
                        found[h][2].append(i)
                else:
                    found[h] = (stage, text, [i])
    names = {}
    for h, (stage, text, idx) in found.items():
        idx.sort()
        names[h] = "%s-%s.%s.glsl" % (scene_of(entries[idx[0]]), h, stage)
    return found, names


def write_shaders(d, commit, entries, found, names):
    os.makedirs(d, exist_ok=True)
    for f in os.listdir(d):
        if f.endswith(".glsl"):
            os.remove(os.path.join(d, f))
    index = ["# <file>: the default-benchmark entries (run.sh, entries.txt order) that compiled it",
             "# glmark2 %s; regenerate with tools/hostharness/glmark2/run.sh (README.md)" % commit]
    for h in sorted(found, key=lambda h: names[h]):
        stage, text, idx = found[h]
        with open(os.path.join(d, names[h]), "w", newline="") as f:
            f.write("// SPDX-License-Identifier: GPL-3.0-only\n")
            f.write("// glmark2 %s: the text glmark2 passed to glShaderSource (README.md)\n" % commit[:8])
            f.write(text)
        index.append("%s: %s" % (names[h], "; ".join(entries[i] for i in idx)))
    with open(os.path.join(d, "index.txt"), "w") as f:
        f.write("\n".join(index) + "\n")


def md_escape(s):
    return s.replace("|", "\\|")


def generated(args, entries, runs, found, names):
    g_all = args.gpus
    o = []
    o.append("Run: glmark2 `%s`, the default benchmark list (%d entries), `--size %s`, "
             "%d frames per entry (`-b :nframes=%d`), one process per entry; GPUs: %s."
             % (args.commit, len(entries), args.size, args.frames, args.frames, ", ".join(g_all)))
    o.append("")
    o.append("### EGL config chosen")
    o.append("")
    o.append("| GPU | surface | config |")
    o.append("|---|---|---|")
    for g in g_all:
        cfgs = collections.Counter(c for i in range(len(entries)) for c in runs[(g, i)]["configs"])
        for c, n in sorted(cfgs.items()):
            kind, _, rest = c.partition(" ")
            o.append("| %s | %s | `%s` (%d of %d runs) |" % (g, kind, rest, n, len(entries)))
    o.append("")
    o.append("### Scenes")
    o.append("")
    o.append("| # | entry | " + " | ".join("%s: status, frames, draws, refused, GL errors, incomplete-texture draws" % g
                                         for g in g_all) + " |")
    o.append("|---|---|" + "---|" * len(g_all))
    for i, e in enumerate(entries):
        cells = []
        for g in g_all:
            end = runs[(g, i)]["end"]
            cells.append("%s, %d, %d, %d, %d, %d" % end if end else "**no end** (rc %d)" % runs[(g, i)]["rc"])
        o.append("| %d | `%s` | %s |" % (i, md_escape(e), " | ".join(cells)))
    o.append("")
    carve_gpus = [g for g in g_all if any(runs[(g, i)]["carve"] for i in range(len(entries)))]
    if carve_gpus:
        o.append("### GPU memory")
        o.append("")
        settings = []
        if args.settings:
            settings = [ln.strip() for ln in open(args.settings) if ln.strip()]
        o.append("The V3D carve-out modelled by `src/osal/linux.c` (the Zephyr V3D OSAL's allocator and free "
                 "rule), settings: %s. Per entry (one process): the most bytes allocated at once, the "
                 "carve-out's allocatable bytes, the longest free run at exit, and the allocations refused."
                 % (", ".join("`%s`" % s for s in settings) or "the defaults"))
        o.append("")
        o.append("| # | entry | " + " | ".join("%s: high-water, of, longest free at exit, refused" % g
                                             for g in carve_gpus) + " |")
        o.append("|---|---|" + "---|" * len(carve_gpus))
        for i, e in enumerate(entries):
            cells = []
            for g in carve_gpus:
                c = runs[(g, i)]["carve"]
                cells.append("%d, %d, %d, %d" % (c[1], c[2], c[3], c[4]) if c else "no line")
            o.append("| %d | `%s` | %s |" % (i, md_escape(e), " | ".join(cells)))
        o.append("")
    o.append("### Findings")
    o.append("")
    o.append("Every GL error (the library's own line, with the entry point), compile or link failure, "
             "refused draw, incomplete-texture line, error the client read back, glmark2 error line, "
             "failed run, and every other line the library logged that is not start-up or exit "
             "bookkeeping (kinds `depth resolve`, `no such uniform`, `other`), per entry and GPU. A count "
             "is the number of times the line came in the entry's setup and %d frames, one per GPU in "
             "the GPU column's order. Ids are replaced by `<n>`." % args.frames)
    o.append("")
    o.append("| # | entry | GPU | kind | finding | count |")
    o.append("|---|---|---|---|---|---|")
    clean = []
    for i, e in enumerate(entries):
        rows = collections.OrderedDict()
        for g in g_all:
            for (kind, text), n in runs[(g, i)]["findings"].items():
                rows.setdefault((kind, text), []).append((g, n))
        if not rows:
            clean.append(i)
        for (kind, text), per in rows.items():
            gpus = ", ".join(g for g, _ in per)
            counts = ", ".join(str(n) for _, n in per)
            o.append("| %d | `%s` | %s | %s | `%s` | %s |" % (i, md_escape(e), gpus, kind, md_escape(text), counts))
    o.append("")
    o.append("Entries with no finding on any GPU: %s." % (", ".join(str(i) for i in clean) or "none"))
    o.append("")
    o.append("### Shaders")
    o.append("")
    nv = sum(1 for h in found if found[h][0] == "vert")
    o.append("%d distinct shader texts (%d vertex, %d fragment) passed to glShaderSource, in "
             "`<out>/shaders/` of the run (`index.txt` maps each to its entries; not committed, "
             "tools/shaders/glmark2/README.md)."
             % (len(found), nv, len(found) - nv))
    return "\n".join(o)


def read_perf(path):
    """perf report --stdio --sort symbol: [(percent, symbol)], the children
    column first where there is one (run.sh's .perf-children.txt)."""
    rows = []
    if not os.path.exists(path):
        return rows
    for ln in open(path, errors="replace"):
        if ln.startswith("#"):
            continue
        m = PERF_LINE.match(ln)
        if m and not PERF_SCAFFOLD.match(m.group(4)):
            rows.append((float(m.group(1)), m.group(4)))
    return rows


def draw_steps_section(d):
    """The library's per-step laps of a draw (shim.c "gm2: draw-steps"): us a
    draw in each step over the counted frames. Starts with a blank line."""
    if not d:
        return []
    if not d["scopes"]:
        return ["", "No draw reported its steps (%d laps untimed)." % d["untimed"]]
    us = 1e3
    total = sum(d["ns"])
    if not total and d["untimed"]:
        return ["", "Draw steps: the clock was refused (GM2_NOCLK=1 or no clock): %d laps over %d draws "
                "untimed, not measured, not zero." % (d["untimed"], d["scopes"])]
    o = ["", "Draw steps (src/draw_steps.rs laps over the counted frames): %d timed draws, %.1f a frame; "
         "%.3f us a draw in all." % (d["scopes"], d["scopes"] / d["counted"], total / d["scopes"] / us)]
    if d["untimed"]:
        o += ["", "%d laps could not read the clock (%.1f a draw): not measured, not zero."
              % (d["untimed"], d["untimed"] / d["scopes"])]
    o += ["", "| step | us a draw | share |", "|---|---|---|"]
    for name, ns in zip(STEP_NAMES, d["ns"]):
        if ns:
            o.append("| `%s` | %.3f | %.1f%% |" % (name, ns / d["scopes"] / us, 100.0 * ns / total))
    return o


def profile(args, g, entries, runs):
    """GM2_PROFILE: per entry, the counted frames' time and every entry point
    ranked by its wall time in them, in ms a frame; the setup phase's top
    entry points in ms; with GM2_PERF, the functions perf sampled most in the
    counted frames, as ms a frame of the frames' cpu time."""
    ms = 1e6
    o = ["# glmark2 host profile: %s" % g, "",
         "Run: glmark2 `%s`, `--size %s`, %d frames per entry, one process per entry (run.sh "
         "GM2_PROFILE=1, README.md \"Profile\"). Host time on this machine, not the board's: "
         "linux.c's submits complete at once, so no GPU wait is in it. Counted frames: frames 2 to %d "
         "(the first frame is in setup). Wall = CLOCK_MONOTONIC, cpu = the thread's CPU time. "
         "The GPU work linux.c models on the CPU (the V3D's TFU jobs) is the board GPU's, not the "
         "CPU's: it is not in the wall and cpu figures, and its own column gives its host time."
         % (args.commit, args.size, args.frames, args.frames), ""]
    for i, e in enumerate(entries):
        r = runs[(g, i)]
        f = r["gl_frames"]
        o += ["## %d `%s`" % (i, md_escape(e)), ""]
        if not f or not f["counted"]:
            o += ["No counted frames (%s)." % ("no gl-frames line" if not f else "%d swaps" % f["swaps"]), ""]
            continue
        n = f["counted"]
        o.append("%d counted frames: %.3f ms wall, %.3f ms cpu a frame; in GL and EGL calls %.3f ms "
                 "(%.0f%%), in glmark2 itself %.3f ms."
                 % (n, f["wall"] / n / ms, f["cpu"] / n / ms, f["gl_wall"] / n / ms,
                    100.0 * f["gl_wall"] / f["wall"] if f["wall"] else 0.0, (f["wall"] - f["gl_wall"]) / n / ms))
        if f["gpu_jobs"]:
            o.append("Modelled GPU work (the TFU, linux.c) outside those figures: %.1f jobs, %.3f ms of host "
                     "time a frame." % (f["gpu_jobs"] / n, f["gpu"] / n / ms))
        o += ["", "| entry point | calls a frame | wall ms a frame | cpu ms a frame | share of GL wall "
              "| modelled GPU jobs, ms a frame |", "|---|---|---|---|---|---|"]
        frames = sorted(((t["frames"], name) for name, t in r["gl_time"].items() if t["frames"][0]),
                        key=lambda x: -x[0][1])
        for (calls, wall, cpu), name in frames:
            jobs, gpu = r["gpu_time"].get(name, {}).get("frames", (0, 0))
            o.append("| `%s` | %.1f | %.3f | %.3f | %.1f%% | %s |"
                     % (name, calls / n, wall / n / ms, cpu / n / ms,
                        100.0 * wall / f["gl_wall"] if f["gl_wall"] else 0.0,
                        "%.1f, %.3f" % (jobs / n, gpu / n / ms) if jobs else "-"))
        o += draw_steps_section(r["draw_steps"])
        setup = sorted(((t["setup"], name) for name, t in r["gl_time"].items() if t["setup"][0]),
                       key=lambda x: -x[0][1])
        total = sum(t[1] for t, _ in setup)
        o += ["", "Setup and first frame: %.1f ms wall in GL and EGL calls; the top entry points: %s."
              % (total / ms, ", ".join("`%s` %.1f ms (%d calls)" % (name, wall / ms, calls)
                                       for (calls, wall, _), name in setup[:8])), ""]
        base = os.path.join(args.out, "logs", g, str(i))
        for kind, title in (("self", "own samples"), ("children", "samples with its callees")):
            rows = read_perf(base + ".perf-%s.txt" % kind)
            if not rows:
                continue
            # perf samples the modelled GPU work too (linux.c's tfu_* and the
            # v3d_tex_* calls under them): the samples are shares of the cpu
            # time with it
            sampled = f["cpu"] + f["gpu"]
            o += ["perf, per function, %s (%% of the counted frames' samples, as ms of their cpu time a frame%s):"
                  % (title, ", the modelled GPU work's included: linux.c's `tfu_*` functions" if f["gpu"] else ""),
                  "", "| function | share | cpu ms a frame |", "|---|---|---|"]
            for pct, sym in rows[:40]:
                o.append("| `%s` | %.1f%% | %.3f |" % (md_escape(sym), pct, pct / 100.0 * sampled / n / ms))
            o.append("")
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("gpus", nargs="+")
    ap.add_argument("--commit", required=True)
    ap.add_argument("--size", required=True)
    ap.add_argument("--frames", type=int, required=True)
    ap.add_argument("--shaders")
    ap.add_argument("--findings")
    ap.add_argument("--settings")
    ap.add_argument("--profile", action="store_true")
    args = ap.parse_args()

    entries, runs = read_runs(args.out, args.gpus)
    found, names = shader_files(args.out, args.gpus, entries, runs)
    text = generated(args, entries, runs, found, names)
    print(text)
    if args.profile:
        for g in args.gpus:
            path = os.path.join(args.out, "profile-%s.md" % g)
            with open(path, "w") as f:
                f.write(profile(args, g, entries, runs) + "\n")
            print("profile: %s" % path)
    if args.shaders:
        write_shaders(args.shaders, args.commit, entries, found, names)
    if args.findings:
        cur = open(args.findings).read() if os.path.exists(args.findings) else "%s\n%s\n" % (BEGIN, END)
        if BEGIN not in cur or END not in cur:
            sys.exit("report.py: %s has no generated markers" % args.findings)
        head, rest = cur.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        with open(args.findings, "w") as f:
            f.write(head + BEGIN + "\n" + text + "\n" + END + tail)


if __name__ == "__main__":
    main()
