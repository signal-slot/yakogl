"""The entry-point list shim.c's timing wrappers are made from (GM2_PROFILE,
README.md "Profile").

usage: gen_timed.py <header>... > gm2-timed.h

Reads the one-line prototypes of the Khronos headers YakoGL ships
(include/GLES2/gl2.h, gl2ext.h, include/EGL/egl.h, eglext.h) and writes one
macro call per entry point, the first header naming it winning:

    GM2_TIMED_VOID(name, (params), (args))
    GM2_TIMED_RET(ret, name, (params), (args))

shim.c defines the two macros: each call becomes a wrapper that times the
call and forwards it to what lookup() would have answered without the
profile. A prototype this script cannot read stops it, so an entry point is
never left out without a word.
"""
import re
import sys

PROTO = re.compile(r"^(?:GL_APICALL|EGLAPI)\s+(.+?)\s*(?:GL_APIENTRY|EGLAPIENTRY)\s+(\w+)\s*\((.*)\)\s*;\s*$")
# the last identifier of a parameter is its name ("const GLchar *const*string")
PARAM_NAME = re.compile(r"(\w+)\s*$")


def entries(paths):
    seen = set()
    for path in paths:
        for n, line in enumerate(open(path), 1):
            if not line.startswith(("GL_APICALL", "EGLAPI")):
                continue
            m = PROTO.match(line)
            if not m:
                sys.exit("gen_timed.py: %s:%d: a prototype it cannot read: %s" % (path, n, line.strip()))
            ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
            if name in seen:
                continue
            seen.add(name)
            args = []
            if params not in ("", "void"):
                for p in params.split(","):
                    a = PARAM_NAME.search(p.strip())
                    if not a or a.group(1) in ("void", "const"):
                        sys.exit("gen_timed.py: %s:%d: a parameter without a name: %s" % (path, n, p))
                    args.append(a.group(1))
            yield ret, name, params or "void", ", ".join(args)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = ["/* generated by tools/hostharness/glmark2/gen_timed.py from %s */"
           % " ".join("/".join(p.split("/")[-2:]) for p in sys.argv[1:])]
    for ret, name, params, args in entries(sys.argv[1:]):
        if ret == "void":
            out.append("GM2_TIMED_VOID(%s, (%s), (%s))" % (name, params, args))
        else:
            out.append("GM2_TIMED_RET(%s, %s, (%s), (%s))" % (ret, name, params, args))
    print("\n".join(out))


if __name__ == "__main__":
    main()
