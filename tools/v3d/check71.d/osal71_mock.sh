# osal71_mock: the V3D 7.1 OSAL (src/osal/zephyr_v3d71.c) with the driver's
# hardware steps (driver/src/v3d/v3d_hw.c, the BCM2712 path) and the board's
# clock hook (driver/zephyr/lib/board/rpi5/rpi5_v3d.c), built for the host
# against a register model of the hub, the core, the SMS and pm, and run
# through gles_osal.h's ops as the GL core calls them. Pinned:
#   - the PM watchdog's count is the first register read, before any clock
#     call or V3D access, and an image whose watchdog is not armed is refused
#     with nothing else touched;
#   - init's sequence: the mailbox, clock 5 on/off/on around pm's 2712 reset
#     bit, the SMS powered up and reset, the identity, the interrupts masked,
#     the MMU on the carve-out's page table (its page, the scratch page) and
#     its first entry;
#   - one bin + render job, write for write: v3d_submit_bin's order, the
#     binning polled to FLDONE, v3d_submit_render's order, the render polled
#     to FRDONE in wait(), then the TMU write-back and the L2T clean; the tile
#     state zeroed; a wait with timeout 0 before the end answers 1;
#   - a binner out of memory fed the first overflow block (BPOA, BPOS), an
#     MMU fault in the render reset through the SMS (the job's -EFAULT, one
#     recovery, the next job runs), a kick with a bad magic refused with no
#     register written, and a 4.2 identity refused at init by name;
#   - the 7.1 TFU (osal_v3d71_tfu): a render in flight finished first, then
#     the TFUC clear, IIA IIS ICA IUA IOA IOC(0x00086061 at 0x71c) IOS COEF0-3
#     and ICFG|IOC_SET last, write for write; done by TFUC or by TFU_CS's
#     count; an MMU fault (-EFAULT) and a job that never ends (bounded poll,
#     -ETIMEDOUT) each reset the GPU, which runs the next TFU and render; the
#     4.2-shaped TFU queries stay unanswered.
#
