/* ---- the register model: the four BCM2712 blocks at their ARM addresses */
static uint32_t hub[0x4000 / 4], core[0x6000 / 4], sms[0x700 / 4], pm[0x1000 / 4];
static uint32_t sms_state;
static uint32_t now_us;
static struct {
	uint32_t wdog;          /* what PM_WDOG reads */
	bool outomem_first;     /* the bin runs out of memory once before FLDONE */
	bool render_fault;      /* the render raises an MMU fault */
	uint32_t frdone_reads;  /* FRDONE after this many core INT_STS reads */
	uint32_t sts_reads;     /* core INT_STS reads since the render started */
	bool rendering;
	bool tfu_hang;          /* a TFU job never ends */
	bool tfu_fault;         /* a TFU job ends in an MMU fault */
	bool tfu_cvt_only;      /* a TFU job moves TFU_CS's count but raises no TFUC */
} model;

/* the log: register writes, PM_WDOG reads, clock and mailbox calls */
struct ev {
	char kind, blk; /* 'W'/'R' with 'H','C','S','P'; 'K' clock (val on); 'M' mailbox */
	uint32_t off, val;
};
#define EVS 4096
static struct ev evs[EVS];
static int nev;

static void log_ev(char kind, char blk, uint32_t off, uint32_t val)
{
	if (nev < EVS)
		evs[nev++] = (struct ev){ kind, blk, off, val };
}

static uint32_t *decode(mm_reg_t a, char *blk, uint32_t *off)
{
	const struct {
		uint64_t base;
		uint32_t *mem;
		size_t size;
		char name;
	} b[] = {
		{ BCM2712_V3D_HUB_BASE, hub, sizeof(hub), 'H' },
		{ BCM2712_V3D_CORE0_BASE, core, sizeof(core), 'C' },
		{ BCM2712_V3D_SMS_BASE, sms, sizeof(sms), 'S' },
		{ BCM2712_PM_BASE, pm, sizeof(pm), 'P' },
	};
	for (size_t i = 0; i < sizeof(b) / sizeof(b[0]); i++) {
		if (a >= b[i].base && a < b[i].base + b[i].size) {
			*blk = b[i].name;
			*off = (uint32_t)(a - b[i].base);
			return &b[i].mem[*off / 4];
		}
	}
	return NULL;
}

static int stray; /* accesses outside the four blocks */

uint32_t mock_read32(mm_reg_t a)
{
	char blk;
	uint32_t off;
	uint32_t *p = decode(a, &blk, &off);

	if (!p) {
		stray++;
		return 0;
	}
	if (blk == 'P' && off == 0x24) {
		log_ev('R', 'P', off, model.wdog);
		return model.wdog;
	}
	if (blk == 'S' && (off == V3D_SMS_REE_CS || off == V3D_SMS_TEE_CS))
		return (*p & ~V3D_SMS_CS_STATE_MASK) | sms_state;
	if (blk == 'C' && off == V3D_CTL_0_INT_STS && model.rendering && !model.render_fault &&
	    ++model.sts_reads >= model.frdone_reads) {
		*p |= V3D_CTL_0_INT_STS_INT_FRDONE_SET;
		model.rendering = false;
	}
	return *p;
}

void mock_write32(uint32_t v, mm_reg_t a)
{
	char blk;
	uint32_t off;
	uint32_t *p = decode(a, &blk, &off);

	if (!p) {
		stray++;
		return;
	}
	log_ev('W', blk, off, v);
	switch (blk) {
	case 'S':
		*p = v & ~V3D_SMS_CS_STATE_MASK;
		if (off == V3D_SMS_TEE_CS && (v & V3D_SMS_CS_CLEAR_POWER_OFF_SET))
			sms_state = V3D_SMS_STATE_IDLE;
		if (off == V3D_SMS_TEE_CS && (v & V3D_SMS_CS_POWER_OFF_SET))
			sms_state = V3D_SMS_STATE_POWER_OFF;
		if (off == V3D_SMS_REE_CS && V3D_SMS_CS_STATE_GET(v) == V3D_SMS_STATE_RESET_REQUEST)
			sms_state = V3D_SMS_STATE_IDLE;
		return;
	case 'H':
		if (off == V3D_HUB_CTL_INT_CLR) {
			hub[V3D_HUB_CTL_INT_STS / 4] &= ~v;
			return;
		}
		if (off == V3D_MMU0_CACHE_CTL)
			v &= ~(V3D_MMU0_CACHE_CTL_FLUSH_SET | V3D_MMU0_CACHE_CTL_FLUSHING_SET);
		if (off == V3D_MMU0_CTL)
			v &= ~(V3D_MMU0_CTL_TLB_CLEAR_SET | V3D_MMU0_CTL_TLB_CLEARING_SET);
		if (off == V3D71_TFU_ICFG && !model.tfu_hang) {
			/* the job runs at once: the conversion counter moves, then
			 * TFUC (or a fault, or nothing but the counter) */
			uint32_t *cs = &hub[V3D71_TFU_CS / 4];

			*cs = (*cs & ~(0xffu << 16)) | (((V3D_TFU_CS_CVTCT_GET(*cs) + 1u) & 0xffu) << 16);
			if (model.tfu_fault)
				hub[V3D_HUB_CTL_INT_STS / 4] |= V3D_HUB_CTL_INT_STS_INT_MMU_PTI_SET;
			else if (!model.tfu_cvt_only)
				hub[V3D_HUB_CTL_INT_STS / 4] |= V3D_HUB_CTL_INT_STS_INT_TFUC_SET;
		}
		*p = v;
		return;
	case 'C':
		if (off == V3D_CTL_0_INT_CLR) {
			core[V3D_CTL_0_INT_STS / 4] &= ~v;
			return;
		}
		if (off == V3D_CTL_0_L2TCACTL)
			return; /* every L2T operation ends at once */
		*p = v;
		if (off == V3D_CLE_0_CT0QEA)
			core[V3D_CTL_0_INT_STS / 4] |= model.outomem_first ? V3D_CTL_0_INT_STS_INT_OUTOMEM_SET
									  : V3D_CTL_0_INT_STS_INT_FLDONE_SET;
		if (off == V3D_PTB_0_BPOS && v != 0 && model.outomem_first) {
			model.outomem_first = false;
			core[V3D_CTL_0_INT_STS / 4] |= V3D_CTL_0_INT_STS_INT_FLDONE_SET;
		}
		if (off == V3D_CLE_0_CT1QEA) {
			model.rendering = true;
			model.sts_reads = 0;
			if (model.render_fault)
				hub[V3D_HUB_CTL_INT_STS / 4] |= V3D_HUB_CTL_INT_STS_INT_MMU_PTI_SET;
		}
		return;
	default:
		*p = v;
	}
}

