/* Host memory as "physical": the low 32 bits of the address (a 24-bit page
 * number, as the 36-bit PA of the BCM2712's MMU needs), the high bits kept
 * here to map it back. */
static uintptr_t hi;
uintptr_t mock_phys_addr(const void *p)
{
	hi = (uintptr_t)p & ~(uintptr_t)0xffffffffu;
	return (uintptr_t)p & 0xffffffffu;
}

void mock_map_phys_bare(uint8_t **virt, uintptr_t phys, size_t size, uint32_t flags)
{
	(void)size;
	(void)flags;
	*virt = (uint8_t *)(hi | phys);
}

