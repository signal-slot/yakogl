static int find(char kind, char blk, uint32_t off, int from)
{
	for (int i = from; i < nev; i++)
		if (evs[i].kind == kind && evs[i].blk == blk && evs[i].off == off)
			return i;
	return -1;
}

static int find_kind(char kind, int from)
{
	for (int i = from; i < nev; i++)
		if (evs[i].kind == kind)
			return i;
	return -1;
}

/* the writes from `from` on, against `want` exactly (block, offset, value) */
struct w {
	char blk;
	uint32_t off, val;
};
static int writes_are(int from, const struct w *want, int n, const char *what)
{
	int j = 0;

	for (int i = from; i < nev && j <= n; i++) {
		if (evs[i].kind != 'W')
			continue;
		if (j == n) {
			printf("  %s: a write more: %c+0x%x = 0x%08x\n", what, evs[i].blk, evs[i].off, evs[i].val);
			return 0;
		}
		if (evs[i].blk != want[j].blk || evs[i].off != want[j].off || evs[i].val != want[j].val) {
			printf("  %s: write %d is %c+0x%x = 0x%08x, wanted %c+0x%x = 0x%08x\n", what, j, evs[i].blk,
			       evs[i].off, evs[i].val, want[j].blk, want[j].off, want[j].val);
			return 0;
		}
		j++;
	}
	if (j != n)
		printf("  %s: %d of %d writes\n", what, j, n);
	return j == n;
}

static void model_reset(void)
{
	memset(hub, 0, sizeof(hub));
	memset(core, 0, sizeof(core));
	memset(sms, 0, sizeof(sms));
	memset(pm, 0, sizeof(pm));
	sms_state = V3D_SMS_STATE_POWER_OFF;
	/* a 7.1 as Mesa's simulator and the Pi 5 name it (hw_mock_test --v71) */
	hub[V3D_HUB_CTL_IDENT1 / 4] = 0x00081117u;
	hub[V3D_HUB_CTL_IDENT2 / 4] = V3D_HUB_CTL_IDENT2_WITH_MMU_SET;
	hub[V3D_HUB_CTL_IDENT3 / 4] = 0x00000700u;
	core[V3D_CTL_0_IDENT0 / 4] = 0x07443356u;
	core[V3D_CTL_0_IDENT1 / 4] = 0x81001441u;
	hub[V3D_MMU0_DEBUG_INFO / 4] = (6u << 8) | (2u << 4); /* PA 36, VA 32 bits */
	memset(&model, 0, sizeof(model));
	model.wdog = 10u << 16; /* armed: 10 s left */
	model.frdone_reads = 3;
	nev = 0;
}

struct job {
	struct osal_gpu_mem bcl, rcl, ta, ts;
	struct v3d_kick k;
};

static int job_alloc(const struct osal_ops *o, struct job *j)
{
	int rc = o->gpu_alloc(0, 4096, 0, &j->bcl) | o->gpu_alloc(0, 4096, 0, &j->rcl) |
		 o->gpu_alloc(0, 64 * 1024, 0, &j->ta) | o->gpu_alloc(0, 4096, 0, &j->ts);
	j->k = (struct v3d_kick){
		.magic = V3D_KICK_MAGIC,
		.bcl_start = (uint32_t)j->bcl.gpu, .bcl_end = (uint32_t)j->bcl.gpu + 0x40,
		.rcl_start = (uint32_t)j->rcl.gpu, .rcl_end = (uint32_t)j->rcl.gpu + 0x80,
		.tile_alloc = (uint32_t)j->ta.gpu, .tile_alloc_size = 64 * 1024,
		.tile_state = (uint32_t)j->ts.gpu, .tile_state_size = 4096,
	};
	memset(j->ts.cpu, 0xff, 4096);
	return rc;
}

int main(void)
{
	const struct osal_ops *o = &osal_zephyr_ops;

	osal_zephyr_register();
	CHECK(registered == o, "osal_zephyr_register registers osal_zephyr_ops");

	/* 1. no watchdog: refused, nothing but PM_WDOG read */
	model_reset();
	model.wdog = 0;
	int rc = o->init(NULL);
	CHECK(rc == -ENODEV, "init without the watchdog returned %d", rc);
	CHECK(nev == 1 && evs[0].kind == 'R' && evs[0].blk == 'P' && evs[0].off == 0x24,
	      "without the watchdog: %d events, the first %c%c+0x%x", nev, nev ? evs[0].kind : '-',
	      nev ? evs[0].blk : '-', nev ? evs[0].off : 0);

	/* 2. init */
	model_reset();
	rc = o->init(NULL);
	CHECK(rc == 0, "init returned %d", rc);
	CHECK(evs[0].kind == 'R' && evs[0].blk == 'P' && evs[0].off == 0x24,
	      "the first access is PM_WDOG (it is %c%c+0x%x)", evs[0].kind, evs[0].blk, evs[0].off);
	int m = find_kind('M', 0), k0 = find_kind('K', 0);
	CHECK(m == 1 && k0 == 2, "the mailbox mapped (event %d) before the first clock call (%d)", m, k0);
	int k1 = find_kind('K', k0 + 1), grafx = find('W', 'P', BCM2712_PM_GRAFX, 0), k2 = find_kind('K', k1 + 1);
	CHECK(k0 >= 0 && evs[k0].off == RPI_FW_CLK_V3D && evs[k0].val == 1 && k1 > k0 && evs[k1].val == 0 &&
		      grafx > k1 && k2 > grafx && evs[k2].val == 1,
	      "clock 5 on (%d), off (%d), pm's reset bit (%d), on (%d)", k0, k1, grafx, k2);
	CHECK(grafx >= 0 && (evs[grafx].val & 0xff000000u) == BCM2711_PM_WRITE_KEY &&
		      (evs[grafx].val & BCM2712_PM_GRAFX_V3D_RESET_N_SET),
	      "PM_GRAFX written 0x%08x", grafx >= 0 ? evs[grafx].val : 0);
	int tee = find('W', 'S', V3D_SMS_TEE_CS, 0), ree = find('W', 'S', V3D_SMS_REE_CS, 0);
	CHECK(tee > k2 && ree > tee && evs[tee].val == V3D_SMS_CS_CLEAR_POWER_OFF_SET &&
		      evs[ree].val == V3D_SMS_STATE_RESET_REQUEST,
	      "the SMS: TEE_CS at %d, REE_CS at %d", tee, ree);
	CHECK(find_kind('W', 0) == grafx, "no write before pm's reset bit (the first write at %d)",
	      find_kind('W', 0));
	int quiesce = find('W', 'C', V3D_CTL_0_INT_MSK_SET, 0), ptb = find('W', 'H', V3D_MMU0_PT_PA_BASE, 0);
	CHECK(quiesce > ree && ptb > quiesce && evs[quiesce].val == ~0u,
	      "interrupts masked (%d) after the SMS, before the MMU (%d)", quiesce, ptb);
	CHECK(stray == 0, "%d accesses outside the four blocks", stray);

	struct osal_gpu_mem probe;
	rc = o->gpu_alloc(0, 4096, 0, &probe);
	CHECK(rc == 0 && probe.gpu >= 0x00100000u && (probe.gpu & 0xfff) == 0, "an alloc: %d at VA 0x%llx", rc,
	      (unsigned long long)probe.gpu);
	const uint64_t carve_phys = probe.phys - (probe.gpu - 0x00100000u);
	uint32_t *pt = (uint32_t *)((uint8_t *)probe.cpu - (probe.gpu - 0x00100000u));
	CHECK(ptb >= 0 && evs[ptb].val == (uint32_t)(carve_phys >> 12), "PT_PA_BASE 0x%x, the carve-out page 0x%llx",
	      ptb >= 0 ? evs[ptb].val : 0, (unsigned long long)(carve_phys >> 12));
	int ill = find('W', 'H', V3D_MMU0_ILLEGAL_ADR, 0), mctl = find('W', 'H', V3D_MMU0_CTL, 0);
	CHECK(ill > ptb && evs[ill].val == ((uint32_t)((carve_phys + 512u * 1024u) >> 12) | V3D_MMU0_ILLEGAL_ADR_ENABLE_SET),
	      "the scratch page after the table: ILLEGAL_ADR 0x%08x", ill >= 0 ? evs[ill].val : 0);
	CHECK(mctl > ptb && (evs[mctl].val & V3D_MMU0_CTL_ENABLE_SET) && (evs[mctl].val & V3D_MMU0_CTL_PT_INVALID_ABORT_SET),
	      "MMU0_CTL 0x%08x", mctl >= 0 ? evs[mctl].val : 0);
	CHECK(pt[probe.gpu >> 12] == (V3D_MMU_PTE_VALID_SET | V3D_MMU_PTE_WRITABLE_SET | (uint32_t)(probe.phys >> 12)),
	      "the PTE of VA 0x%llx is 0x%08x", (unsigned long long)probe.gpu, pt[probe.gpu >> 12]);
	CHECK(pt[0] == 0 && pt[(0x00100000u >> 12)] == 0, "VA 0 and the table's own pages unmapped");
	uint32_t vpm = 0;
	CHECK(o->query(OSAL_QUERY_V3D_VPM_BYTES, &vpm, sizeof(vpm)) == 0 && vpm != 0 && vpm % 8192u == 0,
	      "the VPM size answered (%u)", vpm);

	/* 3. one bin + render job */
	struct job j1;
	CHECK(job_alloc(o, &j1) == 0, "the job's buffers");
	int mark = nev;
	int64_t f1 = o->submit(&j1.k, sizeof(j1.k));
	CHECK(f1 == 1, "submit returned %lld", (long long)f1);
	const struct w bin_render[] = {
		{ 'C', V3D_CTL_0_INT_CLR, V3D_CTL_0_INT_STS_INT_FLDONE_SET | V3D_CTL_0_INT_STS_INT_OUTOMEM_SET },
		{ 'C', V3D_PTB_0_BPOS, 0 },
		{ 'C', V3D_CTL_0_L2TCACTL, V3D_CTL_0_L2TCACTL_L2TFLS_SET },
		{ 'C', V3D_CTL_0_SLCACTL, V3D_CTL_0_SLCACTL_ALL },
		{ 'C', V3D_CLE_0_CT0QMA, j1.k.tile_alloc },
		{ 'C', V3D_CLE_0_CT0QMS, j1.k.tile_alloc_size },
		{ 'C', V3D_CLE_0_CT0QTS, V3D_CLE_0_CT0QTS_CTQTSEN_SET | j1.k.tile_state },
		{ 'C', V3D_CLE_0_CT0QBA, j1.k.bcl_start },
		{ 'C', V3D_CLE_0_CT0QEA, j1.k.bcl_end },
		{ 'C', V3D_CTL_0_INT_CLR, V3D_CTL_0_INT_STS_INT_FLDONE_SET },
		{ 'C', V3D_CTL_0_INT_CLR, V3D_CTL_0_INT_STS_INT_FRDONE_SET },
		{ 'C', V3D_CTL_0_L2TCACTL, V3D_CTL_0_L2TCACTL_L2TFLS_SET },
		{ 'C', V3D_CTL_0_SLCACTL, V3D_CTL_0_SLCACTL_ALL },
		{ 'C', V3D_CLE_0_CT1QBA, j1.k.rcl_start },
		{ 'C', V3D_CLE_0_CT1QEA, j1.k.rcl_end },
	};
	CHECK(writes_are(mark, bin_render, 15, "submit"), "submit's writes: bin, FLDONE, render");
	bool zero = true;
	for (int i = 0; i < 4096; i++)
		zero = zero && ((uint8_t *)j1.ts.cpu)[i] == 0;
	CHECK(zero, "the tile state zeroed before the bin");
	struct osal_v3d_bin_pool bp;
	CHECK(o->query(OSAL_QUERY_V3D_BIN_POOL, &bp, sizeof(bp)) == 0 && bp.jobs == 1 && bp.pool == j1.k.tile_alloc &&
		      bp.overflow_used == 0 && bp.overflow_blocks == CONFIG_YAKOGL_V3D_BIN_OVERFLOW_BLOCKS,
	      "the bin pool record: jobs %u pool 0x%x overflow %u of %u", bp.jobs, bp.pool, bp.overflow_used,
	      bp.overflow_blocks);
	CHECK(o->wait(f1, 0) == 1, "a poll before FRDONE answers 1");
	CHECK(o->completed() == 0, "nothing completed before FRDONE");
	mark = nev;
	rc = o->wait(f1, 1000000);
	CHECK(rc == 0, "wait returned %d", rc);
	const struct w end[] = {
		{ 'C', V3D_CTL_0_INT_CLR, V3D_CTL_0_INT_STS_INT_FRDONE_SET },
		{ 'C', V3D_CTL_0_L2TCACTL, V3D_CTL_0_L2TCACTL_TMUWCF_SET },
		{ 'C', V3D_CTL_0_L2TCACTL,
		  V3D_CTL_0_L2TCACTL_L2TFLS_SET | (V3D_CACHE_FLUSH_MODE_CLEAN << V3D_CTL_0_L2TCACTL_L2TFLM_LSB) },
	};
	CHECK(writes_are(mark, end, 3, "wait"), "wait's writes: FRDONE cleared, TMU write-back, L2T clean");
	CHECK(o->completed() == 1 && o->wait(f1, 0) == 0, "fence 1 completed");
	struct osal_v3d_job_us us;
	osal_v3d_last_completed_job_us(&us);
	CHECK(us.jobs == 1 && us.bin > 0 && us.render > 0, "the job's times: fence %u bin %u render %u", us.jobs,
	      us.bin, us.render);
	CHECK(stray == 0, "%d accesses outside the four blocks", stray);

	/* 4. a binner out of memory: the first overflow block */
	struct job j2;
	CHECK(job_alloc(o, &j2) == 0, "the second job's buffers");
	model.outomem_first = true;
	mark = nev;
	int64_t f2 = o->submit(&j2.k, sizeof(j2.k));
	int bpoa = find('W', 'C', V3D_PTB_0_BPOA, mark), bpos = find('W', 'C', V3D_PTB_0_BPOS, bpoa > 0 ? bpoa : mark);
	CHECK(f2 == 2 && bpoa > mark && bpos > bpoa, "submit %lld: BPOA at %d, BPOS at %d", (long long)f2, bpoa, bpos);
	CHECK(bpoa > 0 && evs[bpoa].val >= 0x00100000u && (evs[bpoa].val & 0xfff) == 0 && evs[bpos].val == 256u * 1024u,
	      "the overflow block: BPOA 0x%08x BPOS %u", bpoa > 0 ? evs[bpoa].val : 0, bpos > 0 ? evs[bpos].val : 0);
	CHECK(o->query(OSAL_QUERY_V3D_BIN_POOL, &bp, sizeof(bp)) == 0 && bp.jobs == 2 && bp.overflow_used == 1,
	      "overflow used %u", bp.overflow_used);
	CHECK(o->wait(f2, 1000000) == 0 && osal_v3d_bin_oom_jobs() == 0, "job 2 completed");

	/* 5. an MMU fault in the render: -EFAULT, a reset through the SMS */
	struct job j3;
	CHECK(job_alloc(o, &j3) == 0, "the third job's buffers");
	model.render_fault = true;
	quiet = true;
	int64_t f3 = o->submit(&j3.k, sizeof(j3.k));
	mark = nev;
	rc = o->wait(f3, 1000000);
	quiet = false;
	CHECK(rc == -EFAULT, "the faulting job's wait returned %d", rc);
	int off = find('W', 'S', V3D_SMS_TEE_CS, mark), up = find('W', 'S', V3D_SMS_TEE_CS, off + 1);
	int pt2 = find('W', 'H', V3D_MMU0_PT_PA_BASE, mark);
	CHECK(off > mark && evs[off].val == V3D_SMS_CS_POWER_OFF_SET && up > off &&
		      evs[up].val == V3D_SMS_CS_CLEAR_POWER_OFF_SET && pt2 > up && evs[pt2].val == (uint32_t)(carve_phys >> 12),
	      "the reset: SMS off (%d), on (%d), the same page table (%d)", off, up, pt2);
	CHECK(osal_v3d_recoveries() == 1 && osal_v3d_mmu_faults() == 1 && !osal_v3d_hung(),
	      "recoveries %u, MMU faults %u, hung %d", osal_v3d_recoveries(), osal_v3d_mmu_faults(), osal_v3d_hung());
	model.render_fault = false;
	model.rendering = false;
	hub[V3D_HUB_CTL_INT_STS / 4] = 0;
	int64_t f4 = o->submit(&j3.k, sizeof(j3.k));
	CHECK(f4 == 4 && o->wait(f4, 1000000) == 0, "the job after the reset: fence %lld", (long long)f4);
	CHECK(o->wait(f3, 0) == -EFAULT, "fence 3 keeps its error");

	/* 6. a kick that is not a V3D kick: refused, nothing written */
	struct v3d_kick bad = j1.k;
	bad.magic = 0x12345678u;
	mark = nev;
	quiet = true;
	CHECK(o->submit(&bad, sizeof(bad)) == -EINVAL && find_kind('W', mark) < 0, "a bad magic: refused, no write");
	bad = j1.k;
	bad.bcl_end = bad.bcl_start;
	CHECK(o->submit(&bad, sizeof(bad)) == -EINVAL && find_kind('W', mark) < 0, "an empty BCL: refused, no write");
	CHECK(o->submit(&j1.k, sizeof(j1.k) - 4) == -EINVAL, "a short kick refused");
	quiet = false;

	/* 7. the queries the 4.2 OSAL answers, the TFU refused */
	uint32_t v = 0;
	CHECK(o->query(OSAL_QUERY_V3D_DRAWS_PER_JOB, &v, sizeof(v)) == 0 && v == CONFIG_YAKOGL_V3D_DRAWS_PER_JOB,
	      "draws per job %u", v);
	CHECK(o->query(OSAL_QUERY_V3D_TILED_BUDGET, &v, sizeof(v)) == 0 && v == CONFIG_YAKOGL_V3D_TILED_COPIES_BYTES,
	      "tiled budget %u", v);
	struct osal_v3d_cpu_of q = { .gpu = j1.bcl.gpu, .bytes = 16 };
	CHECK(o->query(OSAL_QUERY_V3D_CPU_OF_GPU, &q, sizeof(q)) == 0 && q.cpu == j1.bcl.cpu, "cpu_of the BCL");
	CHECK(o->query(OSAL_QUERY_V3D_TFU_RUN, &v, sizeof(v)) == -ENOTSUP && osal_v3d_tfu(NULL, NULL) == -ENOTSUP,
	      "the TFU refused");
	char line[256];
	osal_mem_line(line, sizeof(line));
	CHECK(strncmp(line, "osal(v3d71) mem: ", 17) == 0, "the mem line: %s", line);

	/* 8. a free waits for the job that may read it, then comes back */
	uint32_t used0, used1;
	osal_v3d_mem_used(&used0, NULL, NULL);
	CHECK(o->gpu_free(&j2.ta) == 0, "a free");
	osal_v3d_mem_used(&used1, NULL, NULL);
	CHECK(used1 == used0 - 64u * 1024u, "the free's 64 KiB back (used %u -> %u)", used0, used1);

	/* 8b. the 7.1 TFU: the registers, IOC included, in order, and the wait */
	const struct v3d_tfu71_job tj = {
		.icfg = 0x00430000u, .iia = 0x00200000u, .iis = 0x00100040u, .ica = 0x11111111u, .iua = 0x00300000u,
		.ioa = 0x00240000u, .ioc = 0x00086061u, .ios = 0x00000040u,
		.coef = { 0xa0a0a0a0u, 0xb1b1b1b1u, 0xc2c2c2c2u, 0xd3d3d3d3u },
	};
	struct osal_v3d71_tfu_status ts;
	uint32_t ran, nfail;
	CHECK(osal_v3d71_tfu_present(), "the 7.1 TFU is present after init");
	CHECK(o->query(OSAL_QUERY_V3D_TFU_MIN_BYTES, &v, sizeof(v)) == -ENOTSUP &&
		      o->query(OSAL_QUERY_V3D_TFU_QUEUE, &v, sizeof(v)) == -ENOTSUP,
	      "the 4.2-shaped TFU queries stay unanswered (no IOC in their jobs)");
	CHECK(osal_v3d71_tfu(NULL, 0, &ts) == -ENODEV, "no job: -ENODEV");
	/* a render still in flight is finished before the TFU's first write */
	struct job j5;
	CHECK(job_alloc(o, &j5) == 0, "the TFU test's job buffers");
	int64_t f5 = o->submit(&j5.k, sizeof(j5.k));
	mark = nev;
	quiet = true;
	rc = osal_v3d71_tfu(&tj, 1000000, &ts);
	quiet = false;
	CHECK(rc == 0, "the TFU job returned %d", rc);
	CHECK(o->completed() == (uint32_t)f5, "the render in flight completed before the TFU ran");
	int frd = find('W', 'C', V3D_CTL_0_INT_CLR, mark), tclr = find('W', 'H', V3D_HUB_CTL_INT_CLR, mark);
	CHECK(frd >= 0 && tclr > frd, "FRDONE consumed (%d) before the TFU's first write (%d)", frd, tclr);
	const struct w tfu_writes[] = {
		{ 'H', V3D_HUB_CTL_INT_CLR, V3D_HUB_CTL_INT_STS_INT_TFUC_SET | V3D_HUB_CTL_INT_STS_INT_TFUF_SET },
		{ 'H', V3D71_TFU_IIA, tj.iia },
		{ 'H', V3D71_TFU_IIS, tj.iis },
		{ 'H', V3D71_TFU_ICA, tj.ica },
		{ 'H', V3D71_TFU_IUA, tj.iua },
		{ 'H', V3D71_TFU_IOA, tj.ioa },
		{ 'H', V3D71_TFU_IOC, 0x00086061u },
		{ 'H', V3D71_TFU_IOS, tj.ios },
		{ 'H', V3D71_TFU_COEF0, tj.coef[0] },
		{ 'H', V3D71_TFU_COEF1, tj.coef[1] },
		{ 'H', V3D71_TFU_COEF2, tj.coef[2] },
		{ 'H', V3D71_TFU_COEF3, tj.coef[3] },
		{ 'H', V3D71_TFU_ICFG, tj.icfg | V3D_TFU_ICFG_IOC_SET },
		{ 'H', V3D_HUB_CTL_INT_CLR, V3D_HUB_CTL_INT_STS_INT_TFUC_SET | V3D_HUB_CTL_INT_STS_INT_TFUF_SET },
	};
	CHECK(V3D71_TFU_IOC == 0x71c && V3D71_TFU_ICFG == 0x708, "IOC is at 0x71c and ICFG at 0x708");
	CHECK(tclr > 0 && writes_are(tclr, tfu_writes, 14, "tfu"),
	      "the TFU's writes: clear, IIA IIS ICA IUA IOA IOC(0x00086061) IOS COEF0-3, ICFG|IOC_SET last, clear");
	CHECK(ts.us == 0 && V3D_TFU_CS_CVTCT_GET(ts.cs_after) == V3D_TFU_CS_CVTCT_GET(ts.cs_before) + 1 &&
		      (ts.hub_int_sts & V3D_HUB_CTL_INT_STS_INT_TFUC_SET),
	      "done by TFUC at once: us %u, CS 0x%08x -> 0x%08x, hub 0x%08x", ts.us, ts.cs_before, ts.cs_after,
	      ts.hub_int_sts);
	CHECK((hub[V3D_HUB_CTL_INT_STS / 4] & V3D_HUB_CTL_INT_STS_INT_TFUC_SET) == 0, "TFUC cleared after the job");
	CHECK(hub[V3D71_TFU_IOC / 4] == 0x00086061u, "IOC reached the register (0x%08x)", hub[V3D71_TFU_IOC / 4]);
	/* completion by the conversion counter alone (no TFUC) */
	model.tfu_cvt_only = true;
	rc = osal_v3d71_tfu(&tj, 1000, &ts);
	model.tfu_cvt_only = false;
	CHECK(rc == 0 && !(ts.hub_int_sts & V3D_HUB_CTL_INT_STS_INT_TFUC_SET), "done by TFU_CS's count: %d", rc);
	/* an MMU fault: -EFAULT, one recovery */
	uint32_t rec0 = osal_v3d_recoveries();
	model.tfu_fault = true;
	quiet = true;
	mark = nev;
	rc = osal_v3d71_tfu(&tj, 1000, &ts);
	quiet = false;
	model.tfu_fault = false;
	hub[V3D_HUB_CTL_INT_STS / 4] = 0;
	CHECK(rc == -EFAULT && osal_v3d_recoveries() == rec0 + 1 && find('W', 'S', V3D_SMS_TEE_CS, mark) > 0,
	      "an MMU fault in the TFU: %d, recoveries %u -> %u", rc, rec0, osal_v3d_recoveries());
	/* a job that never ends: the bounded poll returns -ETIMEDOUT, the GPU is reset and works after */
	rec0 = osal_v3d_recoveries();
	model.tfu_hang = true;
	quiet = true;
	mark = nev;
	const uint32_t t0 = now_us;
	rc = osal_v3d71_tfu(&tj, 200, &ts);
	const uint32_t spent = now_us - t0;
	quiet = false;
	model.tfu_hang = false;
	CHECK(rc == -ETIMEDOUT && ts.us == 200 && !(ts.hub_int_sts & V3D_HUB_CTL_INT_STS_INT_TFUC_SET),
	      "a hung TFU: %d after %u us", rc, ts.us);
	CHECK(spent >= 200 && spent < 100000, "the wait is bounded by the timeout (%u us spent)", spent);
	CHECK(osal_v3d_recoveries() == rec0 + 1 && !osal_v3d_hung() && find('W', 'S', V3D_SMS_TEE_CS, mark) > 0,
	      "the timeout reset the GPU through the SMS (recoveries %u)", osal_v3d_recoveries());
	CHECK(find('W', 'H', V3D71_TFU_ICFG, mark) > 0 && find('W', 'H', V3D71_TFU_ICFG, mark) < find('W', 'S', V3D_SMS_TEE_CS, mark),
	      "ICFG started the job before the reset");
	rc = osal_v3d71_tfu(&tj, 1000, &ts);
	CHECK(rc == 0, "a TFU job after the reset ran: %d", rc);
	osal_v3d71_tfu_counts(&ran, &nfail, &v);
	CHECK(ran == 3 && nfail == 2, "counts: %u ran, %u failed", ran, nfail);
	hub[V3D_HUB_CTL_INT_STS / 4] = 0;
	model.rendering = false;
	int64_t f6 = o->submit(&j5.k, sizeof(j5.k));
	CHECK(o->wait(f6, 1000000) == 0, "a render after the TFU jobs");

	/* 9. a 4.2 identity on the BCM2712: refused at init by name */
	o->shutdown();
	model_reset();
	hub[V3D_HUB_CTL_IDENT1 / 4] = (1u << 8) | (2u << 4) | 4u;
	core[V3D_CTL_0_IDENT0 / 4] = 0x04443356u;
	quiet = true;
	rc = o->init(NULL);
	quiet = false;
	CHECK(rc == -ENODEV && find('W', 'H', V3D_MMU0_PT_PA_BASE, 0) < 0, "a 4.2 refused (%d) before the MMU", rc);

	/* 10. the FFI-facing records keep their sizes */
	CHECK(sizeof(struct v3d_kick) == 40, "struct v3d_kick is %zu bytes", sizeof(struct v3d_kick));
	CHECK(sizeof(struct osal_v3d_bin_pool) == 40, "struct osal_v3d_bin_pool");
	CHECK(V3D_KICK_MAGIC == 0x4b443356u, "the kick magic");
	CHECK(stray == 0, "%d accesses outside the four blocks", stray);

	printf("osal71_mock_test: %d checks run (planned %d), %d failed\n", checks, PLANNED, failed);
	return failed || checks != PLANNED ? 1 : 0;
}
