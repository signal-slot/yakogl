"""Licence / SPDX audit of the tracked files.

Walks `git ls-files` (or the directory tree with --no-git) and reports, by
class:

  missing-spdx        no SPDX-License-Identifier in the file header, and no
                      allowlist rule or .license sidecar covers the file
  unknown-id          an identifier (in a header, a sidecar or an allowlist
                      rule) with no LICENSES/<id>.* file
  unused-license      a LICENSES/ entry that no file, rule or third_party
                      declaration uses
  third-party-mismatch  a third_party file whose header licence is not the
                      licence its UPSTREAM file declares
  third-party-unlabelled  (info) a third_party file with no licence text at
                      all; it is covered by its UPSTREAM file
  generated           files that say they are generated, with their own
                      licence and the licence of their generator
  generated-mismatch  a generated file whose licence differs from its
                      generator's
  undecided           (info) a file whose allowlist expression is `undecided`:
                      its origin or licence is an open owner decision, so it
                      is listed and neither given nor denied a licence

Allowlist (the "dep5-like table"): DEFAULT_ALLOW below, plus any file given
with --allow.  A rule line is `glob | SPDX expression | reason`; `*` matches
across `/`.  An expression of `generated-ok` exempts a generated file from
generated-mismatch (its licence is its input data's).  An expression of `-` means "the file is a licence text and has no
licence of its own".  An expression of `undecided` parks a file whose
provenance is not settled (patches, upstream-looking corpora); it is reported
as `undecided`, claims no licence, and is not a finding.  A file `X.license` next to `X` (REUSE sidecar) is read
like a header and covers `X`.

The repository's own table is tools/license_audit.allow (read by default).

Exit status is 0 unless --strict is given and there are findings
(third-party-unlabelled, undecided and generated rows are information, not
findings).  --fail-on CLASS[,CLASS] makes only those classes count (check 25
of tools/cts/cts-selftest.sh uses missing-spdx,unknown-id,third-party-mismatch,
generated-mismatch: unused-license stays information until the owner decides
the LicenseRef texts).

    tools/license_audit.py                 text report
    tools/license_audit.py --json          machine-readable
    tools/license_audit.py --strict        non-zero on findings
    tools/license_audit.py --fail-on missing-spdx,unknown-id
                                           non-zero on those classes only
    tools/license_audit.py --self-test     run the fixtures in
                                           tools/testdata/license_audit/
"""

import argparse
import collections
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = os.path.join(HERE, "testdata", "license_audit")

# Not scanned: the self-test fixtures carry deliberately wrong headers.
EXCLUDE_PREFIXES = ("tools/testdata/license_audit/",)

# The repository's own allowlist, read by default when it exists under --root.
REPO_ALLOW = "tools/license_audit.allow"

# How many lines at the top of a file are "the header".
HEADER_LINES = 60
GENERATED_LINES = 15

# glob | SPDX expression | reason.  Order does not matter; the first match wins.
DEFAULT_ALLOW = [
    ("LICENSE", "-", "licence text"),
    ("LICENSES/*", "-", "licence texts"),
    ("NOTICE", "Apache-2.0", "project notice; plain text, no comment syntax"),
    ("third_party/*/UPSTREAM", "Apache-2.0",
     "our provenance record of the upstream, not upstream's file"),
    ("third_party/UPSTREAM.template", "Apache-2.0", "our file format template"),
    ("Cargo.lock", "Apache-2.0", "generated by cargo; cannot carry a comment header"),
    ("*/Cargo.lock", "Apache-2.0", "generated by cargo; cannot carry a comment header"),
    ("*.json", "Apache-2.0", "JSON has no comments"),
]

COMMENT_START = re.compile(r"^\s*(//|/\*|\*|#|\.\.\s|<!--|;|--|%|REM\b|\"\"\"|''')")
SPDX_RE = re.compile(r"SPDX-License-Identifier:\s*(.*)")
ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.\-]*\+?$")
OPERATORS = {"AND", "OR", "WITH"}

# A comment that says the file is generated (not one that merely mentions it).
GENERATED_RE = re.compile(
    r"^(?:@generated\b|GENERATED\b|do not edit|"
    r"(?:this file (?:is|was) )?(?:auto-?)?generated"
    r"(?: code| file| by| from| with|[.,:;]|\s*$))", re.IGNORECASE)
COMMENT_STRIP = re.compile(r"^\s*(?://[/!]?|/\*+|\*|#|<!--|;|--|%)\s*")
GENERATOR_CMD_RE = re.compile(r"\bby\s+`?([\w.+-]+)")
GENERATOR_PATH_RE = re.compile(r"\b((?:[\w.+-]+/)+[\w.+-]+\.(?:py|sh|rs|pl))\b")

# Licence text in a header that has no SPDX line (upstream files).
TEXT_PATTERNS = [
    (re.compile(r"@License\s+Dual MIT/GPLv2"), ("MIT", "GPL-2.0-only")),
    (re.compile(r"@License\s+MIT\b"), ("MIT",)),
    (re.compile(r"Permission is hereby granted, free of charge", re.I), ("MIT",)),
    (re.compile(r"Licensed under the Apache License", re.I), ("Apache-2.0",)),
    (re.compile(r"Redistribution and use in source and binary forms", re.I),
     ("BSD-3-Clause",)),
    (re.compile(r"GNU General Public License", re.I), ("GPL-2.0-only",)),
]


def run_git(root, *args):
    return subprocess.run(["git", "-C", root, *args], check=True,
                          capture_output=True).stdout


def list_files(root, use_git):
    if use_git:
        out = run_git(root, "ls-files", "-z").decode("utf-8", "surrogateescape")
        names = [n for n in out.split("\0") if n]
    else:
        names = []
        for d, _, fs in os.walk(root):
            for f in fs:
                names.append(os.path.relpath(os.path.join(d, f), root))
    names = [n.replace(os.sep, "/") for n in names]
    return sorted(n for n in names
                  if not n.startswith(EXCLUDE_PREFIXES) and
                  os.path.isfile(os.path.join(root, n)))


def read_header(path, nlines=HEADER_LINES):
    """First lines of a text file, or None for binary / unreadable files."""
    try:
        with open(path, "rb") as f:
            blob = f.read(16384)
    except OSError:
        return None
    if b"\0" in blob:
        return None
    return blob.decode("utf-8", "replace").splitlines()[:nlines]


def parse_expression(text):
    """Split an SPDX expression into (ids, problems)."""
    text = re.split(r"\s+(?:—|--|–)\s+", text)[0]
    text = re.sub(r"(\*/|-->|\"\"\"|''').*$", "", text).strip().strip('`"\'')
    toks = re.findall(r"[()]|[^\s()]+", text)
    ids, problems, prev_id = [], [], False
    for t in toks:
        if t in "()":
            prev_id = False
        elif t in OPERATORS:
            prev_id = False
        elif ID_RE.match(t):
            if prev_id:
                problems.append("missing operator before %r" % t)
            ids.append(t.rstrip("+"))
            prev_id = True
        else:
            problems.append("bad token %r" % t)
    if not ids:
        problems.append("empty expression")
    return ids, problems


def header_spdx(lines, bare=False):
    """(expression text, ids, problems) of the first SPDX line in a comment."""
    for ln in lines:
        m = SPDX_RE.search(ln)
        if m and (bare or COMMENT_START.match(ln)):
            ids, problems = parse_expression(m.group(1))
            expr = re.sub(r"\s*(\*/|-->).*$", "", m.group(1)).strip()
            return expr, ids, problems
    return None


def text_licences(lines):
    """Alternatives named by licence text; None if the header has none."""
    blob = "\n".join(lines)
    for rx, alts in TEXT_PATTERNS:
        if rx.search(blob):
            return alts
    return None


def load_licenses(root):
    d = os.path.join(root, "LICENSES")
    have = {}
    if os.path.isdir(d):
        for n in sorted(os.listdir(d)):
            have[re.sub(r"\.(txt|md)$", "", n)] = n
    return have


def load_allow(extra):
    rules = list(DEFAULT_ALLOW)
    for path in extra:
        with open(path, encoding="utf-8") as f:
            for n, ln in enumerate(f, 1):
                ln = ln.strip()
                if not ln or ln.startswith("#"):
                    continue
                parts = [p.strip() for p in ln.split("|")]
                if len(parts) != 3:
                    sys.exit("%s:%d: want 'glob | SPDX | reason'" % (path, n))
                rules.append(tuple(parts))
    return rules


def allow_rule(rules, rel):
    for glob, expr, reason in rules:
        if fnmatch.fnmatchcase(rel, glob):
            return glob, expr, reason
    return None


def parse_upstream(path):
    """Declared licence ids and `generated:` text of a third_party UPSTREAM."""
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    fields, cur = {}, None
    for ln in lines:
        m = re.match(r"^([a-z][a-z-]*):\s*(.*)$", ln)
        if m and not ln.startswith(" "):
            cur = m.group(1)
            fields[cur] = m.group(2)
        elif cur and ln.startswith(" "):
            fields[cur] += "\n" + ln.strip()
        else:
            cur = None
    lic = fields.get("licence", "")
    first = re.split(r"[\s(]", lic.strip(), maxsplit=1)[0]
    declared = [first] if first else []
    # "Dual MIT/GPLv2": the DDK is usable under either alternative
    if re.search(r"dual\s+mit/gplv2", lic, re.I):
        declared.append("GPL-2.0-only")
    return declared, fields.get("generated", ""), lic


def brace_expand(s):
    m = re.search(r"\{([^{}]*)\}", s)
    if not m:
        return [s]
    out = []
    for alt in m.group(1).split(","):
        out += brace_expand(s[:m.start()] + alt + s[m.end():])
    return out


def upstream_generated_paths(text):
    """Repo-relative paths named in an UPSTREAM `generated:` field."""
    paths = {}
    for tok in re.findall(r"[\w./{},+-]+\.(?:h|c|rs|py|cmake)\b|[\w./{},+-]*\{[^}]*\}[\w./+-]*", text):
        for p in brace_expand(tok):
            if "/" in p:
                paths[p] = True
    return list(paths)


def audit(root, use_git=True, allow_files=()):
    allow_files = list(allow_files)
    repo_allow = os.path.join(root, REPO_ALLOW)
    if os.path.isfile(repo_allow) and repo_allow not in allow_files:
        allow_files.append(repo_allow)
    rules = load_allow(allow_files)
    # `glob | generated-ok | reason`: the output carries the licence of its
    # input data, not of its generator; not a generated-mismatch.
    gen_ok = [r for r in rules if r[1] == "generated-ok"]
    rules = [r for r in rules if r[1] != "generated-ok"]
    files = list_files(root, use_git)
    fileset = set(files)
    have = load_licenses(root)
    res = collections.OrderedDict()
    res["root"] = root
    res["files"] = len(files)
    missing, allowed, unknown, undecided = [], [], [], []
    missing_text = {}   # missing-spdx files whose header has licence text
    used = collections.defaultdict(set)      # licence id -> {users}
    header = {}                               # rel -> (expr, ids) of own licence
    unlabelled, mismatch = [], []
    spdx_count = 0

    def note_ids(rel, ids, how):
        for i in ids:
            used[i].add(rel)
            if i not in have:
                unknown.append({"file": rel, "id": i, "via": how})

    # third_party declarations
    tp = {}
    tpdir = os.path.join(root, "third_party")
    if os.path.isdir(tpdir):
        for n in sorted(os.listdir(tpdir)):
            up = os.path.join(tpdir, n, "UPSTREAM")
            if os.path.isfile(up):
                tp[n] = parse_upstream(up)
                note_ids("third_party/%s/UPSTREAM" % n, tp[n][0], "UPSTREAM licence")

    generated_paths = {}
    for n, (_, gen, lic) in tp.items():
        for p in upstream_generated_paths(gen):
            generated_paths[p] = (n, tp[n][0])

    for rel in files:
        if rel.endswith(".license") and rel[:-8] in fileset:
            continue   # sidecars are read for their file
        lines = read_header(os.path.join(root, rel))
        sidecar = rel + ".license"
        if sidecar in fileset:
            slines = read_header(os.path.join(root, sidecar)) or []
            hs = header_spdx(slines, bare=True)
            how = "sidecar"
        else:
            hs = header_spdx(lines) if lines else None
            how = "header"
        m = re.match(r"third_party/([^/]+)/", rel)
        tpname = m.group(1) if m and m.group(1) in tp else None
        rule = allow_rule(rules, rel)

        if hs:
            expr, ids, problems = hs
            spdx_count += 1
            header[rel] = (expr, ids)
            note_ids(rel, ids, how)
            for p in problems:
                unknown.append({"file": rel, "id": expr, "via": "malformed: " + p})
        elif rule and rule[1] == "undecided":
            undecided.append({"file": rel, "rule": rule[0], "reason": rule[2]})
        elif rule:
            glob, expr, reason = rule
            allowed.append({"file": rel, "rule": glob, "expr": expr, "reason": reason})
            if expr != "-":
                ids, _ = parse_expression(expr)
                header[rel] = (expr, ids)
                note_ids(rel, ids, "allowlist " + glob)
        elif tpname:
            pass   # classified below
        else:
            missing.append(rel)
            alts = text_licences(lines) if lines else None
            if alts:
                missing_text[rel] = list(alts)

        if tpname:
            declared = tp[tpname][0]
            if hs:
                alts = tuple(hs[1])
            else:
                alts = text_licences(lines) if lines else None
            if rule and not hs:
                continue   # allowlisted (our UPSTREAM files, upstream data files)
            if alts is None:
                unlabelled.append(rel)
                continue
            if not (set(alts) & set(declared)) and not (
                    hs and set(hs[1]) <= set(declared)):
                mismatch.append({"file": rel, "header": sorted(alts),
                                 "upstream": declared, "third_party": tpname})

    # generated files and their generator
    gen_rows, gen_bad = [], []
    for rel in files:
        lines = read_header(os.path.join(root, rel), GENERATED_LINES)
        gen_by_upstream = generated_paths.get(rel)
        marked = False
        genpath = None
        if lines:
            for ln in lines:
                if COMMENT_START.match(ln) and GENERATED_RE.match(
                        COMMENT_STRIP.sub("", ln)):
                    marked = True
                    mm = GENERATOR_PATH_RE.search(ln)
                    if mm and genpath is None:
                        genpath = mm.group(1)
                    if genpath is None:
                        # "GENERATED by `yakogl-tools gl-consts`": a command
                        # name; look for its source under tools/
                        cm = GENERATOR_CMD_RE.search(ln)
                        for cand in ("tools/%s/src/main.rs", "tools/%s/main.rs",
                                     "tools/%s.py", "tools/%s/Cargo.toml"):
                            if cm and cand % cm.group(1) in fileset:
                                genpath = cand % cm.group(1)
                                break
                    break
        if not marked and not gen_by_upstream:
            continue
        own = header.get(rel)
        if own is None and lines:
            alts = text_licences(read_header(os.path.join(root, rel)) or [])
            own = (" OR ".join(alts), list(alts)) if alts else None
        gen_lic, gen_name = None, None
        if genpath and genpath in header:
            gen_lic, gen_name = header[genpath][1], genpath
        elif genpath and genpath in fileset:
            gen_name = genpath
        elif gen_by_upstream:
            gen_lic, gen_name = gen_by_upstream[1], "upstream " + gen_by_upstream[0]
        row = {"file": rel, "licence": own[0] if own else None,
               "generator": gen_name,
               "generator_licence": " / ".join(gen_lic) if gen_lic else None}
        gen_rows.append(row)
        if own and gen_lic and not (set(own[1]) & set(gen_lic)) \
                and not allow_rule(gen_ok, rel):
            gen_bad.append(row)

    unused = sorted(i for i in have if i not in used)
    by_id = {i: len(u) for i, u in sorted(used.items())}
    res["spdx_files"] = spdx_count
    res["licenses"] = sorted(have)
    res["id_use"] = by_id
    res["missing-spdx"] = missing
    res["missing-spdx-text"] = missing_text
    res["allowlisted"] = allowed
    res["undecided"] = undecided
    res["unknown-id"] = unknown
    res["unused-license"] = unused
    res["third-party-mismatch"] = mismatch
    res["third-party-unlabelled"] = unlabelled
    res["generated"] = gen_rows
    res["generated-mismatch"] = gen_bad
    return res


FINDING_CLASSES = ("missing-spdx", "unknown-id", "unused-license",
                   "third-party-mismatch", "generated-mismatch")


def count_findings(res, classes=FINDING_CLASSES):
    return sum(len(res[c]) for c in classes)


def group_dir(rel, depth):
    parts = rel.split("/")
    if len(parts) <= 1:
        return "(root)"
    return "/".join(parts[:min(depth, len(parts) - 1)])


def summarise(files, depth):
    c = collections.Counter(group_dir(f if isinstance(f, str) else f["file"], depth)
                            for f in files)
    return sorted(c.items())


def print_report(res, depth, out=sys.stdout):
    w = lambda s="": print(s, file=out)
    w("licence audit: %d files, %d with an SPDX line, %d allowlisted"
      % (res["files"], res["spdx_files"], len(res["allowlisted"])))
    w("LICENSES/: " + ", ".join(res["licenses"]))
    w("identifier use: " + ", ".join("%s=%d" % kv for kv in res["id_use"].items()))
    for cls in ("missing-spdx", "third-party-unlabelled", "undecided",
                "allowlisted"):
        rows = res[cls]
        w()
        w("%s: %d" % (cls, len(rows)))
        for d, n in summarise(rows, depth):
            w("  %5d  %s" % (n, d))
    w()
    w("  of missing-spdx, with licence text in the header: %d"
      % len(res["missing-spdx-text"]))
    w("unknown-id: %d" % len(res["unknown-id"]))
    for r in res["unknown-id"]:
        w("  %s: %s (%s)" % (r["file"], r["id"], r["via"]))
    w("unused-license: %d" % len(res["unused-license"]))
    for r in res["unused-license"]:
        w("  " + r)
    w("third-party-mismatch: %d" % len(res["third-party-mismatch"]))
    for r in res["third-party-mismatch"]:
        w("  %s: header %s, UPSTREAM %s" % (r["file"], "/".join(r["header"]),
                                          "/".join(r["upstream"])))
    w("generated: %d (mismatch: %d)" % (len(res["generated"]),
                                         len(res["generated-mismatch"])))
    for r in res["generated"]:
        flag = "MISMATCH " if r in res["generated-mismatch"] else ""
        w("  %s%s: %s <- %s [%s]" % (flag, r["file"], r["licence"],
                                     r["generator"], r["generator_licence"]))
    w()
    n = count_findings(res)
    w("findings: %d" % n)


def self_test():
    """Run every fixture: <name>/tree is audited, <name>/expected.json holds
    the classes and file lists the audit must give."""
    failures = 0
    names = sorted(d for d in os.listdir(FIXTURES)
                   if os.path.isdir(os.path.join(FIXTURES, d)))
    if not names:
        print("self-test: no fixtures in %s" % FIXTURES)
        return 1
    for name in names:
        base = os.path.join(FIXTURES, name)
        with open(os.path.join(base, "expected.json"), encoding="utf-8") as f:
            exp = json.load(f)
        allow = [os.path.join(base, "allow.txt")] if os.path.exists(
            os.path.join(base, "allow.txt")) else []
        res = audit(os.path.join(base, "tree"), use_git=False, allow_files=allow)
        got = {
            "missing-spdx": res["missing-spdx"],
            "unknown-id": sorted(r["file"] + ":" + r["id"] for r in res["unknown-id"]),
            "unused-license": res["unused-license"],
            "third-party-mismatch": [r["file"] for r in res["third-party-mismatch"]],
            "third-party-unlabelled": res["third-party-unlabelled"],
            "allowlisted": sorted(r["file"] for r in res["allowlisted"]),
            "undecided": sorted(r["file"] for r in res["undecided"]),
            "generated": {r["file"]: [r["generator"], r["generator_licence"]]
                          for r in res["generated"]},
            "generated-mismatch": [r["file"] for r in res["generated-mismatch"]],
        }
        ok = True
        for k, v in exp.items():
            if got.get(k) != v:
                ok = False
                print("FAIL %s: %s\n  want %r\n  got  %r" % (name, k, v, got.get(k)))
        print("%s %s" % ("ok  " if ok else "FAIL", name))
        failures += not ok
    # strict exit status
    proc = subprocess.run([sys.executable, os.path.abspath(__file__), "--root",
                           os.path.join(FIXTURES, "basic", "tree"), "--no-git",
                           "--allow", os.path.join(FIXTURES, "basic", "allow.txt")],
                          capture_output=True)
    strict = subprocess.run([sys.executable, os.path.abspath(__file__), "--root",
                             os.path.join(FIXTURES, "basic", "tree"), "--no-git",
                             "--allow", os.path.join(FIXTURES, "basic", "allow.txt"),
                             "--strict"], capture_output=True)
    if proc.returncode != 0 or strict.returncode == 0:
        print("FAIL exit status: plain=%d strict=%d (want 0 and non-zero)"
              % (proc.returncode, strict.returncode))
        failures += 1
    else:
        print("ok   exit status (0 without --strict, non-zero with it)")
    # --fail-on: a source file without SPDX fails (basic has nohdr.rs), a
    # tree of headed files, allowlisted data and an `undecided` patch passes,
    # and a new headerless source file added to that clean tree fails.
    def fail_on(tree, allow, classes):
        return subprocess.run([sys.executable, os.path.abspath(__file__),
                               "--root", tree, "--no-git", "--allow", allow,
                               "--fail-on", classes],
                              capture_output=True).returncode
    clean = os.path.join(FIXTURES, "clean")
    cl_tree, cl_allow = os.path.join(clean, "tree"), os.path.join(clean, "allow.txt")
    classes = "missing-spdx,unknown-id,third-party-mismatch,generated-mismatch"
    r_bad = fail_on(os.path.join(FIXTURES, "basic", "tree"),
                    os.path.join(FIXTURES, "basic", "allow.txt"), classes)
    r_ok = fail_on(cl_tree, cl_allow, classes)
    with tempfile.TemporaryDirectory() as tmp:
        shutil.copytree(cl_tree, os.path.join(tmp, "tree"))
        with open(os.path.join(tmp, "tree", "new.rs"), "w") as f:
            f.write("fn main() {}\n")
        r_new = fail_on(os.path.join(tmp, "tree"), cl_allow, classes)
    if r_bad == 0 or r_ok != 0 or r_new == 0:
        print("FAIL --fail-on: headerless=%d clean=%d clean+new.rs=%d "
              "(want non-zero, 0, non-zero)" % (r_bad, r_ok, r_new))
        failures += 1
    else:
        print("ok   --fail-on (a new source file without SPDX fails, "
              "an undecided patch does not)")
    print("self-test: %s" % ("FAILED" if failures else "passed"))
    return 1 if failures else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=os.path.dirname(HERE),
                    help="repository root (default: the one containing tools/)")
    ap.add_argument("--no-git", action="store_true",
                    help="walk the directory instead of git ls-files")
    ap.add_argument("--allow", action="append", default=[],
                    help="extra allowlist file (glob | SPDX | reason)")
    ap.add_argument("--depth", type=int, default=2,
                    help="directory depth of the summaries (default 2)")
    ap.add_argument("--list", metavar="CLASS",
                    help="print every file of one class (missing-spdx, ...)")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--strict", action="store_true",
                    help="exit non-zero when there are findings")
    ap.add_argument("--fail-on", metavar="CLASSES",
                    help="exit non-zero when one of these comma-separated "
                         "classes is not empty (instead of --strict's set)")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        sys.exit(self_test())
    res = audit(a.root, not a.no_git, a.allow)
    if a.list:
        for r in res[a.list]:
            print(r if isinstance(r, str) else json.dumps(r))
    elif a.json:
        json.dump(res, sys.stdout, indent=1)
        print()
    else:
        print_report(res, a.depth)
    if a.strict and count_findings(res):
        sys.exit(1)
    if a.fail_on:
        classes = [c for c in a.fail_on.split(",") if c]
        bad = [c for c in classes if c not in res]
        if bad:
            sys.exit("--fail-on: unknown class %s" % ", ".join(bad))
        if count_findings(res, classes):
            sys.exit(1)


if __name__ == "__main__":
    main()
