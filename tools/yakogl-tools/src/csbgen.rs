//! `yakogl-tools csbgen-bindings [--check]`: the Rust backend's view of Mesa's
//! csbgen packers.
//!
//! bindgen (the crate, 0.72) over driver/compat/pvr_csbgen_rs.h with
//! `--wrap-static-fns`: src/pvr/csbgen.rs (the declarations) and
//! driver/src/pvr/generated/csbgen_wrap.c (non-static wrappers around the
//! static inline `ROGUE_*_pack()` functions, which build.rs compiles). Both are
//! committed, so no build of the library runs bindgen or needs libclang;
//! `--check` regenerates them into a temporary directory and fails when either
//! differs from the committed file (tools/check.sh).
//!
//! The packers are the ones the backend fills: the texture and PBE state words
//! and the fragment registers it hands the render service.

use crate::{repo_root, Error, R};
use std::fs;
use std::path::{Path, PathBuf};

/// Every packer src/pvr/backend.rs calls (their structs and enums come along).
const PACKERS: &[&str] = &[
    "TEXSTATE_IMAGE_WORD0",
    "TEXSTATE_IMAGE_WORD1",
    "TEXSTATE_STRIDE_IMAGE_WORD1",
    "TEXSTATE_SAMPLER_WORD0",
    "TEXSTATE_SAMPLER_WORD1",
    "PBESTATE_STATE_WORD0",
    "PBESTATE_STATE_WORD1",
    "PBESTATE_REG_WORD0",
    "PBESTATE_REG_WORD1",
    "CR_PDS_BGRND0_BASE",
    "CR_PDS_BGRND1_BASE",
    "CR_PDS_BGRND3_SIZEINFO",
    "CR_TE_PSG",
    "CR_PPP_CTRL",
    "CR_ISP_BGOBJVALS",
    "CR_ISP_AA",
    "CR_ISP_CTL",
    "CR_ISP_ZLSCTL",
    "CR_ISP_ZLOAD_BASE",
    "CR_ISP_STENCIL_LOAD_BASE",
    "CR_ISP_SCISSOR_BASE",
    "CR_ISP_DBIAS_BASE",
    "CR_ISP_OCLQRY_BASE",
    "CR_USC_PIXEL_OUTPUT_CTRL",
];

const RS_OUT: &str = "src/pvr/csbgen.rs";
const C_OUT: &str = "driver/src/pvr/generated/csbgen_wrap.c";

const RS_HEAD: &str = "// SPDX-License-Identifier: MIT
// Generated by `yakogl-tools csbgen-bindings` (bindgen 0.72) from
// driver/compat/pvr_csbgen_rs.h, i.e. Mesa 26.2.1's csbgen output in
// driver/src/pvr/generated/csbgen/rogue/: do not edit. tools/check.sh
// regenerates it. The pack functions are the wrappers in
// driver/src/pvr/generated/csbgen_wrap.c (build.rs compiles them).";

const C_HEAD: &str = "/* SPDX-License-Identifier: MIT */
/* Generated by `yakogl-tools csbgen-bindings` (bindgen 0.72 --wrap-static-fns)
 * from driver/compat/pvr_csbgen_rs.h: do not edit. tools/check.sh regenerates
 * it; build.rs compiles it for a PowerVR build. */
";

/// The include paths of driver/compat/pvr_mesa.h's csbgen part.
fn clang_args(root: &Path) -> Vec<String> {
    let m = root.join("third_party/mesa-26.2.1");
    [
        root.join("driver/compat"),
        root.join("driver/src/pvr/generated"),
        m.join("src/imagination"),
        m.join("src"),
        m.join("include"),
    ]
    .iter()
    .map(|p| format!("-I{}", p.display()))
    .chain(["-DNDEBUG".to_string()])
    .collect()
}

/// (Rust text, C text) for the bindings, generated in `tmp`.
fn generate(root: &Path, tmp: &Path) -> R<(String, String)> {
    let fns = format!("ROGUE_({})_pack", PACKERS.join("|"));
    // bindgen writes `#include "<header as given>"` into the C file: run from
    // driver/compat with the bare name, so the committed file names no path
    // of this checkout (build.rs puts driver/compat on the include path).
    std::env::set_current_dir(root.join("driver/compat")).map_err(|e| Error::Fatal(format!("chdir: {e}")))?;
    let wrap = tmp.join("csbgen_wrap");
    let target = bindgen::RustTarget::stable(82, 0).map_err(|e| Error::Fatal(format!("rust target: {e}")))?;
    let b = bindgen::Builder::default()
        .header("pvr_csbgen_rs.h")
        .clang_args(clang_args(root))
        .rust_target(target)
        .use_core()
        .ctypes_prefix("core::ffi")
        .allowlist_function(&fns)
        .prepend_enum_name(false)
        .derive_default(true)
        .derive_copy(true)
        .derive_debug(false)
        .layout_tests(true)
        .generate_comments(false)
        .merge_extern_blocks(true)
        .wrap_static_fns(true)
        .wrap_static_fns_path(&wrap)
        .formatter(bindgen::Formatter::Rustfmt)
        .rustfmt_configuration_file(Some(root.join("rustfmt.toml")))
        .raw_line(RS_HEAD)
        .generate()
        .map_err(|e| Error::Fatal(format!("bindgen: {e}")))?;
    let rs = b.to_string();
    let c = fs::read_to_string(wrap.with_extension("c")).map_err(|e| Error::Fatal(format!("bindgen wrapper: {e}")))?;
    Ok((rs, format!("{C_HEAD}{c}")))
}

pub fn main(args: &[String]) -> R<()> {
    let check = match args {
        [] => false,
        [a] if a == "--check" => true,
        _ => return Err(Error::Usage("usage: yakogl-tools csbgen-bindings [--check]".into())),
    };
    let root = PathBuf::from(repo_root());
    let tmp = tempfile::tempdir().map_err(|e| Error::Fatal(format!("tempdir: {e}")))?;
    let (rs, c) = generate(&root, tmp.path())?;
    let outs = [(RS_OUT, rs), (C_OUT, c)];
    if check {
        let mut stale = Vec::new();
        for (path, text) in &outs {
            if fs::read_to_string(root.join(path)).ok().as_deref() != Some(text.as_str()) {
                stale.push(*path);
            }
        }
        if !stale.is_empty() {
            return Err(Error::Exit(format!(
                "csbgen-bindings: {} differ(s) from what bindgen makes now (run `yakogl-tools csbgen-bindings`)",
                stale.join(", ")
            )));
        }
        println!("csbgen-bindings: {RS_OUT} and {C_OUT} are up to date");
    } else {
        for (path, text) in &outs {
            fs::write(root.join(path), text).map_err(|e| Error::Fatal(format!("{path}: {e}")))?;
            println!("wrote {path}");
        }
    }
    Ok(())
}
