//! `yakogl-tools gl-consts`: generate src/gl/consts.rs (GL tokens, u32) and
//! src/gl/egl_consts.rs (EGL tokens, i32) from the Khronos headers under
//! include/. Rerun when those headers change.

use crate::py::{self, g, grp, re, PW};
use crate::{Error, R};

/// `open(path, encoding="utf-8", errors="replace")` iterated by line.
fn lines(path: &str) -> R<Vec<String>> {
    let text = py::universal_newlines(&py::lossy_text(&py::read_bytes(path)?));
    Ok(text.split_inclusive('\n').map(String::from).collect())
}

fn collect(root: &str, paths: &[&str], prefix: &str) -> R<Vec<(String, i128)>> {
    let def = re(&format!(r"\A#define\s+((?:GL|EGL)_{PW}+)\s+(.+?)\s*(?:/\*.*)?\z"));
    let num = re(r"\A(-?(?:0[xX][0-9a-fA-F]+|\d+))([uU]?[lL]{0,2})\z");
    let cast = re(r"\AEGL_CAST\(\s*EGLint\s*,\s*(-?\d+)\s*\)\z");
    let mut out: Vec<(String, i128)> = Vec::new();
    let mut seen: std::collections::HashMap<String, i128> = std::collections::HashMap::new();
    for p in paths {
        for line in lines(&py::join(root, p))? {
            let Some(m) = def.captures(py::rstrip(&line)) else {
                continue;
            };
            if !g(&m, 1).starts_with(prefix) {
                continue;
            }
            let (name, val) = (g(&m, 1).to_string(), py::strip(g(&m, 2)));
            let v = if let Some(n) = num.captures(val) {
                py::py_int_str(g(&n, 1), true)?
            } else if let Some(c) = cast.captures(val) {
                py::py_int_str(grp(&c, 1).unwrap_or(""), false)?
            } else if let Some(v) = seen.get(val) {
                *v // alias of an earlier token
            } else {
                continue;
            };
            if seen.contains_key(&name) {
                continue;
            }
            seen.insert(name.clone(), v);
            out.push((name, v));
        }
    }
    Ok(out)
}

fn render(items: &[(String, i128)], signed: bool) -> String {
    let mut f = String::from(
        "// SPDX-License-Identifier: Apache-2.0\n\
         // GENERATED by `yakogl-tools gl-consts` from the Khronos headers. DO NOT EDIT.\n\
         #![allow(dead_code)]\n\n",
    );
    for (name, v) in items {
        let v = *v;
        let line = if signed {
            if (-(1i128 << 31)..(1i128 << 31)).contains(&v) {
                if v >= 0 {
                    format!("pub const {name}: i32 = {};\n", py::hex(v, true))
                } else {
                    format!("pub const {name}: i32 = {v};\n")
                }
            } else {
                format!("pub const {name}: u64 = {};\n", py::hex(v, true))
            }
        } else if (0..=0xFFFF_FFFF).contains(&v) {
            format!("pub const {name}: u32 = {};\n", py::hex(v, true))
        } else if v < 0 {
            format!("pub const {name}: i32 = {v};\n")
        } else {
            format!("pub const {name}: u64 = {};\n", py::hex(v, true))
        };
        f.push_str(&line);
    }
    f
}

pub fn main(_argv: &[String]) -> R<()> {
    let root = crate::repo_root();
    let gl = collect(&root, &["include/GLES3/gl3.h", "include/GLES2/gl2.h", "include/GLES2/gl2ext.h"], "GL_")?;
    let egl = collect(&root, &["include/EGL/egl.h", "include/EGL/eglext.h"], "EGL_")?;
    let w = |p: &str, t: String| -> R<()> {
        std::fs::write(py::join(&root, p), t).map_err(|e| Error::Fatal(format!("cannot write {p}: {e}")))
    };
    w("src/gl/consts.rs", render(&gl, false))?;
    w("src/gl/egl_consts.rs", render(&egl, true))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn values_and_aliases() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().to_str().unwrap();
        std::fs::write(
            format!("{root}/h.h"),
            "#define GL_A 0x10 /* c */\r\n#define GL_B GL_A\n#define GL_C 0xFFFFFFFFFFFFFFFFull\n\
             #define GL_D -1\n#define GL_A 5\n#define GL_E foo\n#define EGL_X EGL_CAST(EGLint,-2)\n\
             #define GL_F 0\n",
        )
        .unwrap();
        let gl = collect(root, &["h.h"], "GL_").unwrap();
        assert_eq!(
            render(&gl, false).lines().skip(4).collect::<Vec<_>>(),
            [
                "pub const GL_A: u32 = 0x10;",
                "pub const GL_B: u32 = 0x10;",
                "pub const GL_C: u64 = 0xffffffffffffffff;",
                "pub const GL_D: i32 = -1;",
                "pub const GL_F: u32 = 0x0;",
            ]
        );
        let egl = collect(root, &["h.h"], "EGL_").unwrap();
        assert_eq!(render(&egl, true).lines().nth(4), Some("pub const EGL_X: i32 = -2;"));
    }
}
