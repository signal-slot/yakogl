"""Turn the dEQP-GLES2 negative_api sources into one C++ file we can run on the host.

The dEQP cases are written as ES2F_ADD_API_CASE(name, "description", { body }).
The body is almost plain C++ over the GL entry points, so we copy it verbatim and
supply the few dEQP helpers it uses (expectError, m_log, m_context, glu::, tcu::)
from deqp_shim.hpp. Nothing is rewritten: what runs here is what the conformance
suite runs.

Usage: extract.py <VK-GL-CTS>/modules/gles2/functional <out.inc>
"""
import os
import re
import sys

FILES = [
    "es2fNegativeBufferApiTests.cpp",
    "es2fNegativeFragmentApiTests.cpp",
    "es2fNegativeShaderApiTests.cpp",
    "es2fNegativeStateApiTests.cpp",
    "es2fNegativeTextureApiTests.cpp",
    "es2fNegativeVertexArrayApiTests.cpp",
]


def match_brace(text, start):
    """Index just past the '}' matching the '{' at `start`, skipping strings."""
    depth = 0
    i = start
    while i < len(text):
        ch = text[i]
        if ch == '"' or ch == "'":
            i = skip_literal(text, i)
            continue
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise SystemExit("unbalanced braces")


def skip_literal(text, i):
    """Index just past the string or char literal starting at `i`."""
    quote = text[i]
    i += 1
    while text[i] != quote:
        i += 2 if text[i] == '\\' else 1
    return i + 1


def body_brace(text, at):
    """Index of the case body's '{'. The description argument is a string and
    may itself contain a brace ("glUniform{1234}f"), so skip literals."""
    i = at
    while True:
        if text[i] in '"\'':
            i = skip_literal(text, i)
            continue
        if text[i] == '{':
            return i
        i += 1


def preamble(text, init_at):
    """The file-scope helpers (macros, constants, functions) the bodies call."""
    body = text[:init_at]
    out = []
    for m in re.finditer(r'^#define [A-Z_]+\(.*?(?<!\\)\n', body, re.M | re.S):
        out.append(m.group(0))
    for m in re.finditer(r'^static\b', body, re.M):
        i, depth = m.end(), 0
        while True:                       # a function body starts at '{', a constant ends at ';'
            ch = body[i]
            if ch in '"\'':
                i = skip_literal(body, i)
                continue
            if ch == '(':
                depth += 1
            elif ch == ')':
                depth -= 1
            elif depth == 0 and ch == ';':
                out.append(body[m.start():i + 1] + "\n")
                break
            elif depth == 0 and ch == '{':
                out.append(body[m.start():match_brace(body, i)] + "\n")
                break
            i += 1
    return out


def main():
    src_dir, out_path = sys.argv[1], sys.argv[2]
    chunks = ['/* Generated by tests/negative_api/extract.py from the dEQP-GLES2 sources. */\n']
    table = []

    for fname in FILES:
        text = open(os.path.join(src_dir, fname)).read()
        group = re.search(r'TestCaseGroup\(context, "(\w+)"', text).group(1)
        init_at = text.index("::init(void)")
        chunks.append("\n/* ---- %s (%s) ---- */\nnamespace ng_%s {\n" % (group, fname, group))
        chunks += preamble(text, init_at)

        for m in re.finditer(r'ES2F_ADD_API_CASE\((\w+),', text[init_at:]):
            name = m.group(1)
            brace = body_brace(text, init_at + m.end())
            body = text[brace:match_brace(text, brace)]
            fn = "case_%s_%s" % (group, name)
            chunks.append("static void %s(void)\n%s\n" % (fn, body))
            table.append((group, name, "ng_%s::%s" % (group, fn)))
        chunks.append("} /* namespace ng_%s */\n" % group)

    chunks.append("\nstatic const struct DeqpCase g_deqp_cases[] = {\n")
    for group, name, fn in table:
        chunks.append('\t{ "%s", "%s", %s },\n' % (group, name, fn))
    chunks.append("};\n")

    open(out_path, "w").write("".join(chunks))
    sys.stderr.write("extract.py: %d cases\n" % len(table))


main()
