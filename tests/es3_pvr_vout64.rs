static LOCK: Mutex<()> = Mutex::new(());
static ONCE: Once = Once::new();
static mut CTX: *mut GlContext = core::ptr::null_mut();

fn logs() -> Vec<String> {
    with_platform(|p| p.log.clone())
}

fn shader(type_: GLenum, src: &CStr) -> GLuint {
    let p = src.as_ptr();
    // SAFETY: plain GL calls; `p` is a NUL-terminated string.
    unsafe {
        let s = glCreateShader(type_);
        glShaderSource(s, 1, &p, core::ptr::null());
        glCompileShader(s);
        let mut ok: GLint = 0;
        glGetShaderiv(s, GL_COMPILE_STATUS, &mut ok);
        assert_eq!(ok, 1, "shader compile failed: {:?}", logs());
        s
    }
}

/// The one context and backend of the file, set up once; the tests take turns.
/// Three draw buffers are on for the whole file.
fn rig() -> MutexGuard<'static, ()> {
    let g = LOCK.lock().unwrap_or_else(|e| e.into_inner());
    /* a refusal another test of the file logged first through glog_once!
     * logs again */
    yakogl::osal::new_log_epoch();
    ONCE.call_once(|| {
        // SAFETY: statics; the lock serialises every GL call of the file.
        unsafe {
            osal_set_ops(osal());
            yakogl::backend::g_backend = &yakogl_backend_pvr;
            yakogl::shaderc::g_shaderc = &yakogl::shaderc::online::SHC_ONLINE;
            backend::HOST_DRAW_TARGETS.store(3, Ordering::Relaxed);
            assert_eq!(yakogl::backend::init(), 0, "{:?}", logs());
            CTX = context::gl_context_create(CANVAS as u32, CANVAS as u32);
            assert!(!CTX.is_null(), "{:?}", logs());
        }
    });
    // SAFETY: plain GL calls.
    unsafe {
        glBindFramebuffer(GL_FRAMEBUFFER, 0);
        glDisable(GL_BLEND);
        glColorMask(1, 1, 1, 1);
        glFinish();
        while glGetError() != GL_NO_ERROR {}
    }
    g
}

static POS: [f32; 12] = [-1.0, -1.0, 0.0, 1.0, 3.0, -1.0, 0.0, 1.0, -1.0, 3.0, 0.0, 1.0];

/// A vertex shader with `n` vec4 outputs v0..: each is `pos * (k+1)` scaled
/// to stay small, and gl_Position the position.
fn vs_src(n: usize) -> String {
    let mut s = String::from("#version 300 es\nlayout(location = 0) in vec4 pos;\n");
    for k in 0..n {
        s += &format!("out vec4 v{k};\n");
    }
    s += "void main() {\n  gl_Position = pos;\n";
    for k in 0..n {
        s += &format!("  v{k} = pos * {}.0;\n", k + 1);
    }
    s + "}\n"
}

/// A fragment shader reading v0..v(n-1) and summing their red parts.
fn fs_src(n: usize) -> String {
    let mut s = String::from("#version 300 es\nprecision mediump float;\n");
    for k in 0..n {
        s += &format!("in vec4 v{k};\n");
    }
    s += "out vec4 c;\nvoid main() {\n  float r = 0.0;\n";
    for k in 0..n {
        s += &format!("  r += v{k}.x;\n");
    }
    s + "  c = vec4(r / 128.0, 0.0, 0.0, 1.0);\n}\n"
}

fn geti(pname: GLenum) -> GLint {
    let mut v = 0;
    // SAFETY: plain GL call into a local.
    unsafe { glGetIntegerv(pname, &mut v) };
    v
}

fn cstr(s: &str) -> std::ffi::CString {
    std::ffi::CString::new(s).unwrap()
}

