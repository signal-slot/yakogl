/// gl_MaxVertexOutputVectors is the query divided by four: a shader that
/// sizes an array with it gets sixteen elements (and gl_MaxFragmentInputVectors
/// stays fifteen).
#[test]
fn the_shader_constant_is_16() {
    let _g = rig();
    let vs = cstr(
        "#version 300 es\nlayout(location = 0) in vec4 pos;\nout float n;\n\
         void main() {\n  gl_Position = pos;\n  n = gl_MaxVertexOutputVectors == 16 ? 16.0 * pos.x : 0.0;\n}\n",
    );
    let fs = cstr(
        "#version 300 es\nprecision mediump float;\nin float n;\nout vec4 c;\n\
         void main() {\n  c = gl_MaxFragmentInputVectors == 15 ? vec4(n) : vec4(0.0);\n}\n",
    );
    // SAFETY: plain GL calls.
    unsafe {
        let p = glCreateProgram();
        glAttachShader(p, shader(GL_VERTEX_SHADER, &vs));
        glAttachShader(p, shader(GL_FRAGMENT_SHADER, &fs));
        glLinkProgram(p);
        let mut ok: GLint = 0;
        glGetProgramiv(p, GL_LINK_STATUS, &mut ok);
        assert_eq!(ok, 1, "link failed: {:?}", logs());
    }
}

/// Sixteen vec4 outputs, the fragment shader reads fifteen: it links, draws
/// and reaches the kick (the PowerVR host model has no rasteriser to read).
#[test]
fn sixteen_outputs_with_fifteen_read_draw() {
    let _g = rig();
    EMITS.lock().unwrap().clear();
    KICKS.lock().unwrap().clear();
    with_platform(|p| p.log.clear());
    let (vs, fs) = (cstr(&vs_src(16)), cstr(&fs_src(15)));
    // SAFETY: plain GL calls; POS is a static.
    unsafe {
        let p = glCreateProgram();
        glAttachShader(p, shader(GL_VERTEX_SHADER, &vs));
        glAttachShader(p, shader(GL_FRAGMENT_SHADER, &fs));
        glLinkProgram(p);
        let mut ok: GLint = 0;
        glGetProgramiv(p, GL_LINK_STATUS, &mut ok);
        assert_eq!(ok, 1, "link failed: {:?}", logs());
        glViewport(0, 0, SIZE, SIZE);
        glUseProgram(p);
        glVertexAttribPointer(0, 4, GL_FLOAT, 0, 0, POS.as_ptr() as *const c_void);
        glEnableVertexAttribArray(0);
        glDrawArrays(GL_TRIANGLES, 0, 3);
        assert_eq!(glGetError(), GL_NO_ERROR, "draw: {:?}", logs());
        glFinish();
    }
    assert_eq!(KICKS.lock().unwrap().len(), 1, "one kick: {:?}", logs());
    assert_eq!(EMITS.lock().unwrap().len(), 1, "one end-of-tile program: {:?}", logs());
    let l = logs();
    assert!(!l.iter().any(|s| s.contains("refused") || s.contains("no fragment shader variant")), "{l:?}");
}

/// Seventeen vec4 outputs are past the limit: the link fails.
#[test]
fn seventeen_outputs_do_not_link() {
    let _g = rig();
    let (vs, fs) = (cstr(&vs_src(17)), cstr(&fs_src(15)));
    // SAFETY: plain GL calls.
    unsafe {
        let p = glCreateProgram();
        let v = glCreateShader(GL_VERTEX_SHADER);
        let src = vs.as_ptr();
        glShaderSource(v, 1, &src, core::ptr::null());
        glCompileShader(v);
        glAttachShader(p, v);
        glAttachShader(p, shader(GL_FRAGMENT_SHADER, &fs));
        glLinkProgram(p);
        let (mut cs, mut ls): (GLint, GLint) = (0, 0);
        glGetShaderiv(v, GL_COMPILE_STATUS, &mut cs);
        glGetProgramiv(p, GL_LINK_STATUS, &mut ls);
        assert!(cs == 0 || ls == 0, "17 vec4 outputs must be refused");
    }
}
