fn logs() -> Vec<String> {
    with_platform(|p| p.log.clone())
}

fn shader(type_: GLenum, src: &CStr) -> GLuint {
    let p = src.as_ptr();
    // SAFETY: plain GL calls; `p` is a NUL-terminated string.
    unsafe {
        let s = glCreateShader(type_);
        glShaderSource(s, 1, &p, core::ptr::null());
        glCompileShader(s);
        let mut ok: GLint = 0;
        glGetShaderiv(s, GL_COMPILE_STATUS, &mut ok);
        assert_eq!(ok, 1, "shader compile failed: {:?}", logs());
        s
    }
}

fn program(vs: &CStr, fs: &CStr) -> GLuint {
    // SAFETY: plain GL calls.
    unsafe {
        let (v, f) = (shader(GL_VERTEX_SHADER, vs), shader(GL_FRAGMENT_SHADER, fs));
        let p = glCreateProgram();
        glAttachShader(p, v);
        glAttachShader(p, f);
        glLinkProgram(p);
        let mut ok: GLint = 0;
        glGetProgramiv(p, GL_LINK_STATUS, &mut ok);
        assert_eq!(ok, 1, "link failed: {:?}", logs());
        p
    }
}

/// The one context and backend of the file, set up once; the tests take turns.
fn rig() -> MutexGuard<'static, ()> {
    let g = LOCK.lock().unwrap_or_else(|e| e.into_inner());
    ONCE.call_once(|| {
        // SAFETY: statics; the lock serialises every GL call of the file.
        unsafe {
            osal_set_ops(osal());
            yakogl::backend::g_backend = &yakogl_backend_pvr;
            yakogl::shaderc::g_shaderc = &yakogl::shaderc::online::SHC_ONLINE;
            assert_eq!(yakogl::backend::init(), 0, "{:?}", logs());
            CTX = context::gl_context_create(CANVAS as u32, CANVAS as u32);
            assert!(!CTX.is_null(), "{:?}", logs());
            PLAIN = program(VS, FS_PLAIN);
            SAMPLER = program(VS, FS_CUBE);
        }
    });
    // SAFETY: plain GL calls.
    unsafe {
        glBindFramebuffer(GL_FRAMEBUFFER, 0);
        glFinish();
        while glGetError() != GL_NO_ERROR {}
    }
    g
}

static POS: [f32; 12] = [-1.0, -1.0, 0.0, 1.0, 3.0, -1.0, 0.0, 1.0, -1.0, 3.0, 0.0, 1.0];

fn draw(prog: GLuint) {
    // SAFETY: plain GL calls; POS is a static.
    unsafe {
        glViewport(0, 0, SIZE, SIZE);
        glUseProgram(prog);
        glVertexAttribPointer(0, 4, GL_FLOAT, 0, 0, POS.as_ptr() as *const c_void);
        glEnableVertexAttribArray(0);
        glDrawArrays(GL_TRIANGLES, 0, 3);
        assert_eq!(glGetError(), GL_NO_ERROR, "{:?}", logs());
    }
}

/// A SIZE-square one-level RGBA8 cube, bound to unit 0 and made complete.
fn cube() -> GLuint {
    let mut name = 0;
    let px = vec![0x40u8; (SIZE * SIZE * 4) as usize];
    // SAFETY: plain GL calls; `px` holds one face.
    unsafe {
        glGenTextures(1, &mut name);
        glActiveTexture(GL_TEXTURE0);
        glBindTexture(GL_TEXTURE_CUBE_MAP, name);
        for f in 0..6 {
            glTexImage2D(
                GL_TEXTURE_CUBE_MAP_POSITIVE_X + f,
                0,
                GL_RGBA as GLint,
                SIZE,
                SIZE,
                0,
                GL_RGBA,
                GL_UNSIGNED_BYTE,
                px.as_ptr() as *const c_void,
            );
        }
        glTexParameteri(GL_TEXTURE_CUBE_MAP, GL_TEXTURE_MIN_FILTER, GL_NEAREST as GLint);
        glTexParameteri(GL_TEXTURE_CUBE_MAP, GL_TEXTURE_MAG_FILTER, GL_NEAREST as GLint);
        glUseProgram(SAMPLER);
        glUniform1i(glGetUniformLocation(SAMPLER, c"tex".as_ptr()), 0);
    }
    name
}

/// A framebuffer with face +X of cube `name` as its colour image, bound.
fn face_fb(name: GLuint) -> GLuint {
    let mut fb = 0;
    // SAFETY: plain GL calls.
    unsafe {
        glGenFramebuffers(1, &mut fb);
        glBindFramebuffer(GL_FRAMEBUFFER, fb);
        glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_CUBE_MAP_POSITIVE_X, name, 0);
        assert_eq!(glCheckFramebufferStatus(GL_FRAMEBUFFER), GL_FRAMEBUFFER_COMPLETE, "{:?}", logs());
    }
    fb
}

#[test]
fn a_face_drawn_into_is_copied_for_the_next_draw_without_a_flush() {
    let _g = rig();
    let name = cube();
    let fb = face_fb(name);
    // SAFETY: statics set in `rig`; plain GL calls.
    unsafe {
        draw(PLAIN);
        glBindFramebuffer(GL_FRAMEBUFFER, 0);
    }
    let before = native_cube::copies();
    // SAFETY: as above.
    draw(unsafe { SAMPLER });
    assert_eq!(native_cube::copies(), before + 1, "the cube is sampled from a copy of what was drawn");
    // SAFETY: names made by the test.
    unsafe {
        glDeleteFramebuffers(1, &fb);
        glDeleteTextures(1, &name);
        glFinish();
    }
}

#[test]
fn a_cube_attached_to_the_drawn_framebuffer_keeps_the_stacked_image() {
    let _g = rig();
    let name = cube();
    let fb = face_fb(name);
    // SAFETY: statics set in `rig`.
    draw(unsafe { PLAIN });
    let before = native_cube::copies();
    /* the face is still the draw's target: a feedback loop, undefined in GL */
    // SAFETY: as above.
    draw(unsafe { SAMPLER });
    assert_eq!(native_cube::copies(), before, "no copy of a cube being drawn into");
    // SAFETY: names made by the test.
    unsafe {
        glBindFramebuffer(GL_FRAMEBUFFER, 0);
        glDeleteFramebuffers(1, &fb);
        glDeleteTextures(1, &name);
        glFinish();
    }
}
