//! PowerVR: a cube face rendered into in the open frame is sampled from the
//! twiddled copy of what was drawn, not from the stacked image (dEQP-GLES3
//! texture.specification, fbo and texture cube cases on the AM62P; plan #388
//! item fix-cube-rt, design report design-cube-rt).
//!
//! The draw binds a cube for a program that samples the TPU's own cube
//! (`native_cube` bit 0) through a twiddled copy (`gl::native_cube`), made
//! only when the kick that rendered into the cube is no longer being
//! recorded. A face drawn into and then sampled by the very next draw (no
//! `glFlush` between, a different framebuffer) leaves that kick open, so the
//! bind kept the stacked image -- which the program reads as a twiddled
//! cube: a stale or scrambled picture. The draw now submits the open frame
//! and waits for it, then copies, unless the cube is attached to the
//! framebuffer being drawn (a feedback loop, undefined in GL), which keeps
//! the stacked image. `native_cube::copies()` counts the copies made.
//!
//! The GL calls run against the real PowerVR back end on a host platform
//! (the platform of tests/es3_half_float_rt_pvr.rs).
//!
//! ```text
//! cargo test --no-default-features --features host-test,gpu-powervr,shaderc-online --test pvr_cube_rt
//! ```

