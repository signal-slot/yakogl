//! The ES 2.0 context against 654b0620 (GL_IMPLEMENTATION_COLOR_READ_FORMAT/
//! TYPE answer RGBA/UNSIGNED_INT_2_10_10_10_REV for an RGB10_A2 read buffer)
//! and 5e94999a (glLinkProgram captures the program binary,
//! GL_NUM_PROGRAM_BINARY_FORMATS 1), on V3D 4.2. The Pi 4 whole dEQP-GLES2
//! tree (46f93767) predates them; dEQP-GLES2 queries the implementation read
//! format/type (functional.read_pixels.*, state_query.*) and reads the
//! binary-format state next to GL_EXTENSIONS.
//!
//! Pinned in the ES 2.0 context (`report-es2`):
//! - the implementation read format/type of the default framebuffer and of an
//!   FBO with an RGBA8 (where GL_OES_rgb8_rgba8 is listed), RGBA4, RGB5_A1 and
//!   RGB565 colour renderbuffer, each RGBA/UNSIGNED_BYTE, and a pair
//!   glReadPixels accepts (ES 2.0 4.3.1); no RGB10_A2 pair, whose renderbuffer
//!   format ES 2.0 lacks (GL_INVALID_ENUM) and which `report-es2` never stores;
//! - GL_NUM_PROGRAM_BINARY_FORMATS and GL_PROGRAM_BINARY_FORMATS are ES 3.0
//!   pnames of glGetIntegerv/Floatv/Booleanv: GL_INVALID_ENUM, the output
//!   untouched; GL_PROGRAM_BINARY_LENGTH of glGetProgramiv likewise, a
//!   linked program included; GL_EXTENSIONS lists no program-binary
//!   extension, so the state and the string agree; the link itself and
//!   GL_LINK_STATUS are unchanged.
//!
//! The job builder is stood in for as in tests/v3d_es2ctx_drift_fbo_complete.rs.
//!
//! ```text
//! cargo test --no-default-features --features host-test,gpu-v3d,shaderc-online,no-shader-table,report-es2 --test v3d_es2ctx_drift_read_format
//! ```
