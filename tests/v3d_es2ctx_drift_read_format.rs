const W: GLsizei = 32;
const H: GLsizei = 32;

const VS: &str = "attribute vec4 p;\nvoid main() { gl_Position = p; }\n";
const FS: &str = "precision mediump float;\nvoid main() { gl_FragColor = vec4(0.25, 0.5, 0.75, 1.0); }\n";

/// The error flag, drained: the first error since the last call.
fn err() -> GLenum {
    // SAFETY: plain GL calls.
    unsafe {
        let e = glGetError();
        while glGetError() != GL_NO_ERROR {}
        e
    }
}

fn extension_listed(name: &str) -> bool {
    // SAFETY: GL_EXTENSIONS is a NUL-terminated string.
    let s = unsafe { CStr::from_ptr(glGetString(GL_EXTENSIONS) as *const c_char) };
    s.to_string_lossy().split(' ').any(|e| e == name)
}

fn bind_fbo() -> GLuint {
    let mut fb = 0;
    // SAFETY: plain GL calls with room for one name.
    unsafe {
        glGenFramebuffers(1, &mut fb);
        glBindFramebuffer(GL_FRAMEBUFFER, fb);
    }
    fb
}

fn renderbuffer(format: GLenum) -> GLuint {
    let mut rb = 0;
    // SAFETY: plain GL calls with room for one name.
    unsafe {
        glGenRenderbuffers(1, &mut rb);
        glBindRenderbuffer(GL_RENDERBUFFER, rb);
        glRenderbufferStorage(GL_RENDERBUFFER, format, W, H);
        glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_RENDERBUFFER, rb);
    }
    rb
}

fn geti(pname: GLenum) -> GLint {
    let mut v: GLint = -777;
    // SAFETY: a plain GL call with room for the one value.
    unsafe { glGetIntegerv(pname, &mut v) };
    v
}

/// What the implementation says glReadPixels takes for the bound read buffer.
fn read_pair() -> (GLenum, GLenum) {
    let (f, t) = (geti(GL_IMPLEMENTATION_COLOR_READ_FORMAT), geti(GL_IMPLEMENTATION_COLOR_READ_TYPE));
    assert_eq!(err(), GL_NO_ERROR, "the two queries");
    (f as GLenum, t as GLenum)
}

/// The pair is RGBA/UNSIGNED_BYTE, and glReadPixels accepts it.
fn pins(what: &str) {
    assert_eq!(read_pair(), (GL_RGBA, GL_UNSIGNED_BYTE), "{what}: implementation read format/type");
    let mut px = vec![0u8; (W * H * 4) as usize];
    for (f, t) in [(GL_RGBA, GL_UNSIGNED_BYTE), read_pair()] {
        // SAFETY: `px` holds W x H RGBA8 texels, the most any pair here reads.
        unsafe { glReadPixels(0, 0, W, H, f, t, px.as_mut_ptr() as *mut c_void) };
        assert_eq!(err(), GL_NO_ERROR, "{what}: glReadPixels({f:#x}, {t:#x})");
    }
}

fn link_program() -> GLuint {
    let mut ids = [0; 2];
    // SAFETY: plain GL calls; one NUL-terminated source each.
    unsafe {
        for (i, (ty, src)) in [(GL_VERTEX_SHADER, VS), (GL_FRAGMENT_SHADER, FS)].into_iter().enumerate() {
            let text = CString::new(src).unwrap();
            ids[i] = glCreateShader(ty);
            let p: [*const c_char; 1] = [text.as_ptr()];
            glShaderSource(ids[i], 1, p.as_ptr(), core::ptr::null());
            glCompileShader(ids[i]);
        }
        let p = glCreateProgram();
        glAttachShader(p, ids[0]);
        glAttachShader(p, ids[1]);
        glBindAttribLocation(p, 0, c"p".as_ptr());
        glLinkProgram(p);
        let mut ok: GLint = 0;
        glGetProgramiv(p, GL_LINK_STATUS, &mut ok);
        assert_eq!(ok, 1, "the program links; {:?}", log_lines());
        p
    }
}

