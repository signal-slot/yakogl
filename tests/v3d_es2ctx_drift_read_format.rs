#[test]
fn the_program_binary_state_is_es3_only_and_unwritten() {
    let _g = rig();
    for pname in [GL_NUM_PROGRAM_BINARY_FORMATS, GL_PROGRAM_BINARY_FORMATS] {
        let mut i = [-777 as GLint; 4];
        let mut f = [-777.0 as GLfloat; 4];
        let mut b = [0xEE as GLboolean; 4];
        // SAFETY: plain GL calls; four values of room for each.
        unsafe {
            glGetIntegerv(pname, i.as_mut_ptr());
            assert_eq!(err(), GL_INVALID_ENUM, "glGetIntegerv({pname:#x})");
            glGetFloatv(pname, f.as_mut_ptr());
            assert_eq!(err(), GL_INVALID_ENUM, "glGetFloatv({pname:#x})");
            glGetBooleanv(pname, b.as_mut_ptr());
            assert_eq!(err(), GL_INVALID_ENUM, "glGetBooleanv({pname:#x})");
        }
        assert_eq!((i, f, b), ([-777; 4], [-777.0; 4], [0xEE; 4]), "{pname:#x}: nothing written");
    }
    /* no extension string names a program binary either */
    for name in ["GL_OES_get_program_binary", "GL_ARB_get_program_binary"] {
        assert!(!extension_listed(name), "{name} is not listed");
    }
}

#[test]
fn a_linked_program_has_no_binary_length_in_es2() {
    let _g = rig();
    let p = link_program();
    for pname in [GL_PROGRAM_BINARY_LENGTH, GL_PROGRAM_BINARY_RETRIEVABLE_HINT] {
        let mut v: GLint = -777;
        // SAFETY: a plain GL call with room for one value.
        unsafe { glGetProgramiv(p, pname, &mut v) };
        assert_eq!((err(), v), (GL_INVALID_ENUM, -777), "glGetProgramiv({pname:#x})");
    }
    /* the ES 2.0 pnames are unchanged */
    let mut v: GLint = -777;
    // SAFETY: plain GL calls with room for one value.
    unsafe {
        glGetProgramiv(p, GL_LINK_STATUS, &mut v);
        assert_eq!((err(), v), (GL_NO_ERROR, GL_TRUE as GLint));
        glGetProgramiv(p, GL_ATTACHED_SHADERS, &mut v);
        assert_eq!((err(), v), (GL_NO_ERROR, 2));
        glUseProgram(p);
        assert_eq!(err(), GL_NO_ERROR);
        glUseProgram(0);
        glDeleteProgram(p);
    }
    assert_eq!(err(), GL_NO_ERROR);
}
