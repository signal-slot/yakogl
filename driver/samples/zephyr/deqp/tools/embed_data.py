"""embed_data.py <data root> <prefix> <out.c>: every file under <data root>
as a const array, and a sorted table {name, bytes, size} the memory archive
searches. Names are <prefix>/<path relative to the root>, the names dEQP's
test packages ask their archive for (gles2/data/brick.png, ...)."""
import os, sys

root, prefix, out = sys.argv[1], sys.argv[2].rstrip('/'), sys.argv[3]
files = []
for d, _, fs in os.walk(root):
    for f in fs:
        p = os.path.join(d, f)
        files.append((prefix + '/' + os.path.relpath(p, root).replace(os.sep, '/'), p))
files.sort()
with open(out, 'w') as o:
    o.write('/* GENERATED by embed_data.py from %s. DO NOT EDIT. */\n' % root)
    o.write('#include <stddef.h>\n#include <stdint.h>\n#include "deqp_data.h"\n\n')
    for i, (_, p) in enumerate(files):
        data = open(p, 'rb').read()
        o.write('static const uint8_t f%d[%d] = {' % (i, max(len(data), 1)))
        o.write(','.join(str(b) for b in data) or '0')
        o.write('};\n')
    o.write('\nconst struct deqp_file deqp_files[] = {\n')
    for i, (n, p) in enumerate(files):
        o.write('\t{ "%s", f%d, %d },\n' % (n, i, os.path.getsize(p)))
    o.write('};\nconst size_t deqp_num_files = %d;\n' % len(files))
print('%d files' % len(files))
