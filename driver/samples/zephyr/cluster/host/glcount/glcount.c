/* the Rust heap's bytes in use (malloc_usable_size: an upper bound per
 * block), for GLCOUNT_STRESS's growth check */
static size_t heap_in_use;

void *slint_heap_alloc(size_t alignment, size_t size)
{
	void *p = NULL;
	if (alignment < sizeof(void *))
		alignment = sizeof(void *);
	if (posix_memalign(&p, alignment, size ? size : 1) != 0)
		return NULL;
	heap_in_use += malloc_usable_size(p);
	return p;
}

void slint_heap_free(void *p)
{
	if (p)
		heap_in_use -= malloc_usable_size(p);
	free(p);
}

