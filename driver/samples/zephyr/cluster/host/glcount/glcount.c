/* Pixels a draw covers more than once, rasterised at pixel centres with the
 * top-left rule (as GL does), in a hit map over the window: a stencil stroke
 * (3 passes) and a single-pass stroke differ only on such pixels, since the
 * stencil's only job is to blend each pixel once. */
static uint8_t *hitmap;

static bool edge_in(double w, double ax, double ay)
{
	/* top-left rule: an edge is "top" (horizontal, pointing left in y-down
	 * screen space with CCW orientation normalised below) or "left" */
	if (w > 0)
		return true;
	if (w < 0)
		return false;
	return (ay == 0 && ax < 0) || ay > 0;
}

static unsigned overlap_of_draw(GLenum m, GLint first, GLsizei n, unsigned *covered)
{
	if (!hitmap && !(hitmap = calloc((size_t)W * H, 1)))
		return 0;
	memset(hitmap, 0, (size_t)W * H);
	unsigned twice = 0, once = 0;
	const GLsizei step = m == GL_TRIANGLES ? 3 : 1;
	for (GLsizei k = 0; k + 2 < n; k += step) {
		float x[3], y[3];
		bool ok = true;
		for (int v = 0; v < 3; v++)
			ok &= vertex(first + k + v, &x[v], &y[v]);
		if (!ok)
			continue;
		double area = ((double)x[1] - x[0]) * ((double)y[2] - y[0]) - ((double)x[2] - x[0]) * ((double)y[1] - y[0]);
		if (area == 0)
			continue;
		if (area < 0) { /* orient one way so the rule is consistent */
			float tx = x[1], ty = y[1];
			x[1] = x[2], y[1] = y[2], x[2] = tx, y[2] = ty;
		}
		int x0 = (int)floorf(fminf(x[0], fminf(x[1], x[2]))), x1 = (int)ceilf(fmaxf(x[0], fmaxf(x[1], x[2])));
		int y0 = (int)floorf(fminf(y[0], fminf(y[1], y[2]))), y1 = (int)ceilf(fmaxf(y[0], fmaxf(y[1], y[2])));
		x0 = x0 < 0 ? 0 : x0, y0 = y0 < 0 ? 0 : y0, x1 = x1 > W ? W : x1, y1 = y1 > H ? H : y1;
		for (int py = y0; py < y1; py++)
			for (int px = x0; px < x1; px++) {
				const double cx = px + 0.5, cy = py + 0.5;
				bool in = true;
				for (int e = 0; e < 3 && in; e++) {
					const int a = e, b = (e + 1) % 3;
					const double ex = (double)x[b] - x[a], ey = (double)y[b] - y[a];
					const double w = ex * (cy - y[a]) - ey * (cx - x[a]);
					in = edge_in(w, ex, ey);
				}
				if (!in)
					continue;
				uint8_t *h = &hitmap[(size_t)py * W + px];
				if (*h == 1)
					twice++;
				if (*h == 0)
					once++;
				if (*h < 255)
					(*h)++;
			}
	}
	*covered = once;
	return twice;
}

/* GLCOUNT_TRACE=<frame>: one line per draw of that demo frame */
static bool tracing;
static unsigned trace_frame; /* GLCOUNT_TRACE: the demo frame (1-based), 0 none */
static unsigned trace_draw;

static void trace(GLenum m, GLint first, GLsizei n)
{
	float x0 = W_PX, y0 = H_PX, x1 = 0, y1 = 0, x, y;
	for (GLsizei k = 0; k < n; k++)
		if (vertex(first + k, &x, &y)) {
			x0 = x < x0 ? x : x0, y0 = y < y0 ? y : y0;
			x1 = x > x1 ? x : x1, y1 = y > y1 ? y : y1;
		}
	const double a0 = c.area_colour + c.area_stencil;
	area_of_draw(m, first, n);
	const double a = c.area_colour + c.area_stencil - a0;
	c.area_colour -= colour_on ? a : 0; /* area_of_draw is also called by the draw; count once */
	c.area_stencil -= colour_on ? 0 : a;
	unsigned pi = 0;
	while (pi < nprogs && progs[pi].id != cur_prog)
		pi++;
	const struct tex_state *t0 = texs && bound[0] && bound[0] < MAX_TEX_ID ? &texs[bound[0]] : NULL;
	printf("glcount: trace draw %3u: %s %s%s%s%s %s %d verts, bbox %.0f,%.0f-%.0f,%.0f, %.0f px; colour %s; "
	       "blend %s", trace_draw++,
	       pi < nprogs && progs[pi].sel >= 0 && progs[pi].sel <= 9 ? sel_name[progs[pi].sel] : "?",
	       pi < nprogs && progs[pi].glyph ? "glyph " : "", pi < nprogs && progs[pi].nodiscard ? "nodiscard " : "",
	       pi < nprogs && progs[pi].aa ? "aa" : "", "", glname(m), (int)n, x0, y0, x1, y1, a,
	       colour_on ? "on" : "off", blend_on ? "on" : "off");
	if (blend_on)
		printf(" (%s,%s / %s,%s)", glname(blend_f[0]), glname(blend_f[1]), glname(blend_f[2]), glname(blend_f[3]));
	printf("; stencil %s", stencil_on ? "on" : "off");
	if (stencil_on)
		printf(" (%s ref %d mask 0x%x, ops %s,%s,%s)", glname(stencil_func), stencil_ref, stencil_fmask,
		       glname(stencil_ops[0]), glname(stencil_ops[1]), glname(stencil_ops[2]));
	printf("; scissor %s", scissor_on ? "on" : "off");
	if (t0 && t0->w)
		printf("; tex0 %ux%u %s min %s mag %s, border alpha max %d", t0->w, t0->h, glname(t0->fmt),
		       glname(t0->min), glname(t0->mag), t0->border_alpha);
	else
		printf("; tex0 none");
	if (pi < nprogs && progs[pi].frag_set) {
		const float *f = progs[pi].frag;
		printf("; texType %d, innerCol %.2f,%.2f,%.2f,%.2f, strokeThr %.2f, scissorRadius %.1f, "
		       "scissorExt %.0f,%.0f",
		       (int)f[42], f[24], f[25], f[26], f[27], f[41], f[51], f[32], f[33]);
	}
	if (colour_on) {
		unsigned covered = 0, twice = overlap_of_draw(m, first, n, &covered);
		printf("; pixels covered %u, of them more than once %u", covered, twice);
	}
	printf("\n");
}

