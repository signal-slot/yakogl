static GLuint next_id = 1;

/* What each draw samples, for the demo replay: FemtoVG binds the paint's
 * texture on unit 0 and the glyph texture on unit 1 before every draw
 * (femtovg renderer/opengl.rs set_uniforms), so a draw's pair of bound
 * textures is well defined. Each texture's content is a hash of what was
 * uploaded to it: a glTexSubImage2D that covers the whole texture replaces
 * the hash (so a refilled texture and a new texture with the same pixels
 * hash the same), a partial one chains onto it, and glTexImage2D without
 * pixels is "empty WxH". The signature folds, per draw, the mode, the count
 * and the two bound textures' contents; texture ids are not in it, so two
 * libraries that draw the same with differently managed textures (a refill
 * or a pooled table instead of a new texture) give the same signature. It
 * cannot see vertex data or uniforms. GLCOUNT_DROP_REFILL is its control. */
#define MAX_TEX_ID (1u << 22)
struct tex_state {
	uint64_t content;
	uint32_t w, h;
	GLenum fmt, min, mag; /* for GLCOUNT_TRACE */
	uint32_t last_drawn;  /* the replay frame (1-based) that last sampled it, 0 never */
	int border_alpha;     /* the largest alpha on the texture's outer ring of texels
			       * at its last whole upload (RGBA only); -1 unknown */
};

/* The largest alpha of the outer ring of a w x h RGBA8 image (the texels an
 * edge fringe or an inset would blend): 0 means the ring is transparent. */
static int ring_alpha(const uint8_t *px, uint32_t w, uint32_t h)
{
	int a = 0;
	for (uint32_t y = 0; y < h; y++)
		for (uint32_t x = 0; x < w; x += (y == 0 || y == h - 1) ? 1 : (w > 1 ? w - 1 : 1)) {
			const int v = px[((size_t)y * w + x) * 4 + 3];
			a = v > a ? v : a;
		}
	return a;
}
static struct tex_state *texs;
static GLuint bound[8];
static unsigned cur_unit;
static uint64_t signature = 0xcbf29ce484222325ull;
static int content_error; /* an id past MAX_TEX_ID or an unknown format: the signature is void */
/* GLCOUNT_DROP_REFILL=N, the signature's control: the Nth whole-texture
 * glTexSubImage2D into a 256x1 gradient table is not applied, as a pooled
 * table handed out without its refill would be; the signature must change. */
static unsigned drop_refill, gradient_refills;
static uint32_t replay_frame; /* the demo replay's frame, 1-based; 0 outside it */

static uint64_t fnv(uint64_t h, const void *p, size_t n)
{
	const uint8_t *b = p;
	for (size_t i = 0; i < n; i++) {
		h ^= b[i];
		h *= 0x100000001b3ull;
	}
	return h;
}
static uint64_t fnv_u64(uint64_t h, uint64_t v)
{
	return fnv(h, &v, sizeof(v));
}
static struct tex_state *bound_tex(void)
{
	GLuint id = cur_unit < 8 ? bound[cur_unit] : 0;
	if (!texs || id == 0)
		return NULL;
	if (id >= MAX_TEX_ID) {
		content_error = 1;
		return NULL;
	}
	return &texs[id];
}
static size_t bytes_per_pixel(GLenum f, GLenum ty)
{
	if (ty != GL_UNSIGNED_BYTE)
		return 0;
	switch (f) {
	case GL_ALPHA:
	case GL_LUMINANCE: return 1;
	case GL_LUMINANCE_ALPHA: return 2;
	case GL_RGB: return 3;
	case GL_RGBA: return 4;
	default: return 0;
	}
}

