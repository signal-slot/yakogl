/*
 * glcount: the image's Rust library (rust/, the cluster's UI through Slint's
 * no_std FemtoVG renderer) built for the host and driven with a stub GL that
 * draws nothing and counts the calls. It answers what the renderer asks of
 * GL per frame without a board: here, how many textures a frame creates
 * (glTexImage2D) and how many it only refills (glTexSubImage2D).
 *
 * The stub offers the GL functions YakoGL's eglGetProcAddress answers (its
 * PROCS table, src/gl/egl.rs; gl_names.h, generated by run.sh) and nothing
 * else: FemtoVG takes the paths it would take on the board (the OES vertex
 * arrays, for one).
 * The calls that return something get an answer a working context would give
 * (ids, a "OpenGL ES 2.0" version string, shaders that compile and programs
 * that link); every other call is a no-op returning 0. The no-op is called
 * through the caller's own signature, which the x86-64 System V ABI allows
 * for a function that reads no arguments (host test only).
 *
 * The sequence, printed one line per frame: the check's first two frames
 * (Slint clock 0 and 1000 ms, 400 telemetry ticks between them), then
 * GLCOUNT_FRAMES frames 200 ms apart (4 ticks each), as the demo draws.
 * Textures of 256x1 are FemtoVG's multi-stop gradient tables
 * (femtovg/src/gradient_store.rs: one per distinct set of stops, freed when
 * a frame does not use it), counted apart from the others, which are the
 * Text items' and the images'.
 *
 * The verdict (exit 1 on FAIL): after the warm-up, no steady frame creates
 * a texture, a gradient table included (the fork pools the tables). A frame is steady when it makes as
 * many draws as the frame before it: the same items are on screen, so every
 * Text item had a texture last frame. A frame whose draw count changed may
 * show a new item (an icon appearing makes its image's texture) and is left
 * out, and printed as left out. The pool's own counters
 * (slint_cluster_gradient_pool) must agree with the 256x1 textures the stub
 * saw created (a library without the pool is a FAIL: nothing to compare). And the run must show that it
 * measured something: the speed text changed and textures other than the
 * gradient tables were refilled (a run where neither happens cannot tell a
 * reused texture from an unused one).
 *
 * GLCOUNT_DEMO_S=N replays the demo's own sequence instead (src/main.c): the
 * check's three frames (Slint clock 0, 1000 and 3000 ms, FRAME_TICKS = 400
 * telemetry ticks before the second), then N seconds of demo frames
 * GLCOUNT_STEP_MS apart (default 63, the board's mean frame at 15.8 fps),
 * the ticks due at 50 ms each and the clock 3000 ms + t, as main.c's demo
 * loop sets them. Every GLCOUNT_REPORT_S (default 10) seconds of that time
 * it prints the per-frame means by main.c's definitions: "uploads"
 * (glTexImage2D calls with pixels and glTexSubImage2D calls) and "new
 * textures" (glTexImage2D calls). main.c's "tilings" count the V3D
 * backend's CPU tilings, which a stub GL cannot see; it prints none. No
 * verdict: the numbers are read against the board's report lines.
 */
