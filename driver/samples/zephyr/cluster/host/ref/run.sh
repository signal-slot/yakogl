# The host reference render of the cluster sample: builds host/ref against an
# unpatched Slint checkout and renders the cluster's frame at each size given.
#
#   SLINT_UPSTREAM_DIR=<slint at 1007c032> AGL_SLINT_CLUSTER_DIR=<clone> \
#       host/ref/run.sh <out-dir> [WxH ...]        (default: the three panels)
#
# Writes, per size, <out-dir>/ref-<W>x<H>.rgba (W*H*4 bytes, R G B 255, rows
# top down), ref-<W>x<H>.blind.txt (the gradient-stroked bands the reference
# cannot draw; compare.py reads it) and probes-<W>x<H>.txt; and
# <out-dir>/references.rs, the cluster sample's check/src/references.rs built
# from them (copy it there when the UI, the state or the fonts change). The font variables are the
# image's (CMakeLists.txt); NOTO_SANS_DIR defaults to /usr/share/fonts/noto.
set -eu

out=${1:?usage: run.sh <out-dir> [WxH ...]}
shift
[ $# -gt 0 ] || set -- 1024x600 1280x800 1920x720
# SLINT_UPSTREAM_DIR must be outside this repository: the reference depends
# on ../../check, a member of this repository's workspace, and with both under
# one root cargo took this repository's root for Slint's crates ("error
# inheriting `authors` from workspace root manifest").
: "${SLINT_UPSTREAM_DIR:?the unpatched Slint checkout (slint/nostd/README.md names the commit)}"
: "${AGL_SLINT_CLUSTER_DIR:?the agl-slint-cluster clone}"
noto=${NOTO_SANS_DIR:-/usr/share/fonts/noto}
here=$(cd "$(dirname "$0")" && pwd)
sample=$(cd "$here/../.." && pwd)

mkdir -p "$out/crate"
sed -e "s#@REF_SRC@#$here#g" -e "s#@SLINT_UPSTREAM_DIR@#$SLINT_UPSTREAM_DIR#g" \
	-e "s#@CHECK_DIR@#$sample/check#g" \
	"$here/Cargo.toml.in" > "$out/crate/Cargo.toml"

export SLINT_UI_FILE="$sample/ui/zephyr-cluster.slint"
export AGL_SLINT_CLUSTER_UI_DIR="$AGL_SLINT_CLUSTER_DIR/ui"
export SLINT_DEFAULT_FONT="$noto/NotoSans-Regular.ttf"
export SLINT_FONT_PATH="$noto/NotoSans-Light.ttf:$noto/NotoSans-ExtraLight.ttf"
sizes=$(cat "$sample/font-sizes.txt")
[ -n "$sizes" ] || { echo "run.sh: $sample/font-sizes.txt is empty or missing" >&2; exit 1; }
export SLINT_FONT_SIZES="$sizes"
export CARGO_TARGET_DIR="$out/target"
cargo build --release --manifest-path "$out/crate/Cargo.toml"

rs="$out/references.rs"
{
	echo "// SPDX-License-Identifier: Apache-2.0"
	echo "// Generated by host/ref/run.sh (Slint's software renderer from an unpatched"
	echo "// checkout at the no_std tree's base, the same UI, state and clock as the"
	echo "// image): the host reference's probe points, one table per window size."
	echo "// Regenerate when the UI, the state (FRAME_TICKS) or the fonts change. The"
	echo "// points avoid the reference's blind spot, the gradient-stroked dial arcs"
	echo "// (host/ref/src/main.rs gradient_strokes)."
	echo
	echo "use super::{Probe, Reference};"
	echo
	echo "/// Every window size the host reference was run at."
	echo "pub const REFERENCES: &[Reference] = &["
} > "$rs.body"
: > "$rs.tables"
for size in "$@"; do
	w=${size%x*}
	h=${size#*x}
	# not piped: a failing reference run must stop the script (sh has no pipefail)
	"$out/target/release/cluster_ref" "$w" "$h" "$out/ref-${w}x${h}.rgba" > "$out/probes-${w}x${h}.txt"
	cat "$out/probes-${w}x${h}.txt"
	n=$(grep -c '^	{' "$out/probes-${w}x${h}.txt")
	[ "$n" -gt 0 ] || { echo "run.sh: no probe point found at ${w}x${h}" >&2; exit 1; }
	echo "    Reference { w: $w, h: $h, probes: REF_${w}X${h} }," >> "$rs.body"
	{
		echo
		grep '^state:' "$out/probes-${w}x${h}.txt" | sed 's#^#// #'
		sed -n '/^\/\* host reference/,/\*\/$/p' "$out/probes-${w}x${h}.txt" |
			sed 's#^/\* #// #; s#^ \* #// #; s# \*/$##'
		echo "const REF_${w}X${h}: &[Probe] = &["
		grep '^	{' "$out/probes-${w}x${h}.txt" |
			sed 's#^	{ \([0-9]*\), \([0-9]*\), { \([0-9]*\), \([0-9]*\), \([0-9]*\) } },#    Probe { x: \1, y: \2, rgb: [\3, \4, \5] },#'
		echo "];"
	} >> "$rs.tables"
done
echo "];" >> "$rs.body"
cat "$rs.body" "$rs.tables" > "$rs"
rm -f "$rs.body" "$rs.tables"
echo "wrote $rs"
