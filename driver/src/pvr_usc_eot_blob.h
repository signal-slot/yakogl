/*
 * pvr_usc_eot_blob.h
 *
 * USC end-of-tile (EOT) programs for PowerVR BXS-4-64 (BVNC 36.53.104.796,
 * TI AM62P): pvr_usc_eot() (src/imagination/vulkan/pvr_usc.c) with the
 * transfer context's props (pvr_arch_job_context.c
 * pvr_transfer_eot_shaders_init): shared_words, state_regs[i] = 2i, so
 * emit i reads its PBE state from shared registers sh[2i], sh[2i+1]; one
 * 16-byte instruction group per emit, the last one ending
 * (`emitpix.freep`).
 *
 *   pvr_usc_eot_words          capture_usc eot 1
 *   pvr_usc_eot2_words         capture_usc eot 2
 *   pvr_usc_eot3_words         capture_usc eot 3
 *   pvr_usc_eot4_words         capture_usc eot 4
 *   pvr_usc_eot2_tb_words      capture_usc eot 3 1
 *   pvr_usc_eot3_tb_words      capture_usc eot 3 2
 *   pvr_usc_eot4_tb_words      capture_usc eot 4 3
 *   pvr_usc_eot4_tb2_words     capture_usc eot 4 2 3
 *   pvr_usc_eot4_tb3_words     capture_usc eot 4 1 2 3
 *
 * The _tb programs read emits from tile buffers (tile_buffer_addrs[i] set,
 * num_output_regs 4, msaa_samples 1): a pixel has four output registers
 * here, so three RGBA16F attachments do not fit, the shader stores the rest
 * to memory and the program loads each one back (flush_tile_buffer,
 * PVR_USC_EOT_TB_DWORDS dwords per spilled emit) before emitting it. A
 * tile buffer's address is two immediates in the program, a sentinel the
 * driver patches at upload: the k-th spilled emit (in emit order) reads
 * tile buffer k, its immediates at the byte offsets
 * pvr_usc_eot_*_addr_bytes[..][k] = { lo, hi } (a program with several
 * spilled emits has them at any byte, not on a dword). The first sentinel,
 * PVR_USC_EOT_TB_ADDR_LO/HI, is the one-spill programs'. As captured,
 * pvr_usc_eot2_tb_words and pvr_usc_eot3_tb_words are BOTH three-emit
 * programs: the tile buffer on emit 1 and on emit 2 (the arguments above; a
 * two-emit program with the tile buffer on its last emit, capture_usc eot 2
 * 1, is a different program).
 *
 * GENERATED by tools/pco_shc/gen_usc_blobs.py render. The VDM-sync, passthrough
 * and plain end-of-tile (eot1..3) programs are the words of src/pvr/internal.rs,
 * which yakogl-precompile --internal builds with our USC encoder; render refuses
 * them unless they equal Mesa 26.2.1's pco (tools/pco_shc/usc_blobs.txt, written
 * by gen_usc_blobs.py capture, tools/pco_shc/capture_usc.c, README.md).
 * eot4 and the tile-buffer programs stay pco's: our encoder has no list line
 * for four emits, and no builder for the loads from memory. Do not edit.
 */

