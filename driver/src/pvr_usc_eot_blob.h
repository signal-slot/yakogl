/*
 * pvr_usc_eot_blob.h
 *
 * USC end-of-tile (EOT) programs for PowerVR BXS-4-64 (BVNC 36.53.104.796,
 * TI AM62P): pvr_usc_eot() (src/imagination/vulkan/pvr_usc.c) with the
 * transfer context's props (pvr_arch_job_context.c
 * pvr_transfer_eot_shaders_init): shared_words, state_regs[i] = 2i, so
 * emit i reads its PBE state from shared registers sh[2i], sh[2i+1]; one
 * 16-byte instruction group per emit, the last one ending
 * (`emitpix.freep`).
 *
 *   pvr_usc_eot_words      capture_usc eot 1
 *   pvr_usc_eot2_words     capture_usc eot 2
 *   pvr_usc_eot3_words     capture_usc eot 3
 *   pvr_usc_eot2_tb_words  capture_usc eot 3 1
 *   pvr_usc_eot3_tb_words  capture_usc eot 3 2
 *
 * The _tb programs read one emit's data from a tile buffer
 * (tile_buffer_addrs[i] set, num_output_regs 4, msaa_samples 1): a pixel
 * has four output registers here, so three RGBA16F attachments do not fit,
 * the shader stores one to memory and the program loads it back
 * (flush_tile_buffer) before emitting it. The tile buffer's address is two
 * immediates in the program, the sentinel PVR_USC_EOT_TB_ADDR_LO/HI, which
 * the driver patches at upload. As captured, BOTH are three-emit programs:
 * pvr_usc_eot2_tb_words has the tile buffer on emit 1, pvr_usc_eot3_tb_words
 * on emit 2 (the arguments above; a two-emit program with the tile buffer
 * on its last emit, capture_usc eot 2 1, is a different program).
 *
 * GENERATED by tools/pco_shc/gen_usc_blobs.py render from
 * tools/pco_shc/usc_blobs.txt, which gen_usc_blobs.py capture writes from
 * Mesa 26.2.1's pco (tools/pco_shc/capture_usc.c, README.md). Do not edit.
 */

