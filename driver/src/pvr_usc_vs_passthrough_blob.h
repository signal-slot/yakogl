/*
 * pvr_usc_vs_passthrough_blob.h
 *
 * PowerVR BXS-4-64 (BVNC 36.53.104.796): Mesa's precompiled usclib
 * programs the driver binds itself (pco_usclib_common[], built by pco_clc
 * into pco_uscgen_programs.c).
 *
 *   pvr_usc_vs_passthrough  VS_PASSTHROUGH_COMMON (usclib common.cl
 *                           vs_passthrough_common(): gl_Position =
 *                           vec4(in.xyz, 1.0)), capture_usc precomp VS_PASSTHROUGH_COMMON
 *   pvr_usc_vs_nop_words    VS_NOP_COMMON, capture_usc precomp VS_NOP_COMMON
 *   pvr_usc_fs_nop_words    FS_NOP_COMMON (writes no colour), capture_usc precomp FS_NOP_COMMON
 *
 * Upload a program to the USC heap; its heap offset is the DOUTU execution
 * address of the PDS program that kicks it.
 *
 * GENERATED by tools/pco_shc/gen_usc_blobs.py render. The VDM-sync, passthrough
 * and plain end-of-tile (eot1..3) programs are the words of src/pvr/internal.rs,
 * which yakogl-precompile --internal builds with our USC encoder; render refuses
 * them unless they equal Mesa 26.2.1's pco (tools/pco_shc/usc_blobs.txt, written
 * by gen_usc_blobs.py capture, tools/pco_shc/capture_usc.c, README.md).
 * fs_nop stays pco's (nothing binds it). Do not edit.
 */
#ifndef PVR_USC_VS_PASSTHROUGH_BLOB_H
#define PVR_USC_VS_PASSTHROUGH_BLOB_H

#include <stdint.h>

/* USC binary, 8 dwords (32 bytes). temps = 0. */
static const uint32_t pvr_usc_vs_passthrough[8] = {
   0x0804a058u, 0x00048000u, 0xfff33000u, 0xffffffffu,
   0x0e80a058u, 0x00018003u, 0xfff33000u, 0xffffffffu,
};
#define PVR_USC_VS_PASSTHROUGH_SIZE_BYTES 32u
#define PVR_USC_VS_PASSTHROUGH_TEMPS      0u

/* temps = 0. */
static const uint32_t pvr_usc_vs_nop_words[2] = {
   0x0580a044u, 0xff000000u,
};
/* temps = 0. */
static const uint32_t pvr_usc_fs_nop_words[2] = {
   0x00ee8004u, 0xfffffff2u,
};

#endif /* PVR_USC_VS_PASSTHROUGH_BLOB_H */
