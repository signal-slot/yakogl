/*
 * pvr_usc_clear_fs_blob.h
 *
 * USC "clear-attach" fragment shader for PowerVR BXS-4-64 (BVNC
 * 36.53.104.796, TI AM62P), for a one-dword colour:
 * pvr_uscgen_clear_attach() (src/imagination/vulkan/pvr_usc.c) with
 * { dword_count 1, offset 0, uses_tile_buffer false }, entry 0 of the
 * clear-attach table pvr_device_init_clear_attachment_programs() builds
 * (capture_usc clear 1).
 *
 * The shader reads the colour from shared register 0 (sh0;
 * nir_load_preamble(base = PVR_CLEAR_ATTACH_DATA_DWORD0), pvr_iface.h) and
 * writes it to pixel output register 0 (`mbyp` with olchk, then end). So
 * the colour-upload PDS program DMAs the packed colour (one dword in the
 * target's pixel format) into sh0 before the USC runs.
 *
 * GENERATED by tools/pco_shc/gen_usc_blobs.py render from
 * tools/pco_shc/usc_blobs.txt, which gen_usc_blobs.py capture writes from
 * Mesa 26.2.1's pco (tools/pco_shc/capture_usc.c, README.md). Do not edit.
 */

#ifndef PVR_USC_CLEAR_FS_BLOB_H
#define PVR_USC_CLEAR_FS_BLOB_H

#include <stdint.h>

/* 16 bytes = 4 dwords, little-endian. */
static const uint32_t pvr_usc_clear_fs_words[] = {
   0x87808a38u, 0x00000880u, 0xfff32000u, 0xffffffffu,
};

/* Byte view (identical data), for DMA/upload paths that want bytes. */
static const uint8_t pvr_usc_clear_fs_bytes[] = {
   0x38, 0x8a, 0x80, 0x87,
   0x80, 0x08, 0x00, 0x00,
   0x00, 0x20, 0xf3, 0xff,
   0xff, 0xff, 0xff, 0xff,
};

#define PVR_USC_CLEAR_FS_SIZE_BYTES 16
#define PVR_USC_CLEAR_FS_TEMPS      0

/* The clear color is consumed from shared register 0 (sh0). */
#define PVR_USC_CLEAR_FS_COLOR_SHARED_REG 0

#endif /* PVR_USC_CLEAR_FS_BLOB_H */
