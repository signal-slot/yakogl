def cstr(path):
    data = open(path, 'rb').read()
    lines = data.split(b'\n')
    if data.endswith(b'\n'):
        lines = lines[:-1]
    return '\n'.join('\t"%s\\n"' % l.decode().replace('\\', '\\\\').replace('"', '\\"') for l in lines)
