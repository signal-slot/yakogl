# every case that mentions one of the fourteen ES 3.00 symbols, read out of
# gl_test.c's own text (case 54 is called es3chain and is absent from this list
# because it draws with the base pair, which does have ES 1.00 twins).
ES300_CASES = (41, 42, 43, 44, 45, 46, 47, 48, 49, 51, 52, 55, 57, 89, 98, 100, 104, 106, 114, 141, 163)


def es300_cases_used():
    """The cases whose functions use a `#version 300 es` source (by its first
    line, with no ES 1.00 twin), read from
    gl_test.c: the run_case switch names each case's function, and a function
    uses a source when its body names the symbol. 89 (flatlast) was missing
    from the list above, so the ES 1.00 set reported it FAIL at the version
    line rather than SKIP (usc-backend, 2026-09-24): the list is checked
    against this, and regeneration stops when they disagree."""
    import re
    c = open(os.path.join(HERE, 'gl_test.c')).read()
    def version300(f):
        with open(os.path.join(SH, f)) as fh:
            return next((l for l in fh if l.strip()), '').startswith('#version 300 es')
    # By the version line, not the directory: case 55's source is
    # qt3d/clear_mrt_300.*. A source the ES 1.00 set has a twin for is served.
    es300 = {e[0] for e in ENTRIES if e[1] not in ES100_TWINS and version300(e[1])}
    bodies = dict(re.findall(r'^static int (case_\w+)\(void\)\n\{(.*?)^\}', c, re.S | re.M))
    number = {fn: int(n) for n, fn in re.findall(r'case (\d+):\s*(?:rc = )?(case_\w+)\(', c)}
    used = set()
    for fn, body in bodies.items():
        if any(sym in body for sym in es300) and fn in number:
            used.add(number[fn])
    return used


CHECK = '--check' in sys.argv[1:]


def emit(path, sub, head):
    out = list(head)
    for entry in ENTRIES:
        name, f = entry[0], entry[1]
        note = entry[2] if len(entry) > 2 else None
        out.append('%sstatic const char %s[] =\n%s;\n'
                   % ('/* %s */\n' % note if note else '', name,
                      cstr(os.path.join(SH, sub.get(f, f)))))
    text = '\n'.join(out) + '\n'
    if not CHECK:
        open(os.path.join(HERE, path), 'w').write(text)
        return
    try:
        have = open(os.path.join(HERE, path)).read()
    except FileNotFoundError:
        raise SystemExit('gen_gl_test_shaders: %s is not there to check; run without --check to write it' % path)
    if have != text:
        hl, tl = have.split('\n'), text.split('\n')
        i = next((i for i, (a, b) in enumerate(zip(hl, tl)) if a != b), min(len(hl), len(tl)))
        raise SystemExit('gen_gl_test_shaders: %s is not what this generator makes from %s '
                         '(first difference at line %d):\n  committed: %s\n  generated: %s\n'
                         'Fix the source under tools/shaders/ and regenerate: '
                         'python3 driver/tools/pvrlab/gen_gl_test_shaders.py'
                         % (path, SH, i + 1,
                            hl[i] if i < len(hl) else '<no such line>',
                            tl[i] if i < len(tl) else '<no such line>'))
    print('gen_gl_test_shaders: %s is the generator\'s own output (%d sources)' % (path, len(ENTRIES)))


emit('gl_test_shaders.h', {}, out)

ES100_HEAD = [
    '/* SPDX-License-Identifier: Apache-2.0 */',
    '/* GENERATED by tools/pvrlab/gen_gl_test_shaders.py from yakogl/tools/shaders/. DO NOT EDIT.',
    ' *',
    ' * The GL ES 1.00 set: gl_test_shaders.h with its thirteen GLSL 450 sources',
    ' * replaced by the ES 1.00 twin of each. Every symbol has the same name as in',
    ' * that header, so gl_test.c selects a set with an include and nothing else.',
    ' *',
    ' * This is the set an ES 2.0 compiler can be asked to compile: a GLSL 450',
    ' * source with layout locations, a Vulkan push-constant block and a user',
    ' * fragment output is refused at the version line, which says nothing about',
    ' * the compiler under test.',
    ' *',
    ' * The twins are not a rewrite of the tests. Each keeps the names and the',
    ' * declaration order of its original, so the reflection of a twin equals the',
    ' * reflection of its original field by field (src/shaderc/es100_twins.rs),',
    ' * and either set must read back the same pixels from the same case.',
    ' *',
    ' * @N cases have no ES 1.00 form, because their GLSL is "#version 300 es":',
    ' * @LIST.',
    ' * GL_TEST_SHADERS_SKIP_REASON names them, so they are skipped with a reason',
    ' * printed rather than failing at the version line or passing silently. */',
    '',
    '#define GL_TEST_ES100_SET 1',
    '',
    '/* Non-NULL for a case this set cannot serve; the string is the reason. */',
    '#define GL_TEST_SHADERS_SKIP_REASON(c) \\',
    '\t(@COND \\',
    '\t ? "ES 3.00 source, outside the ES 2.0 compiler" : (const char *)0)',
    '',
]
_used = es300_cases_used()
if not _used:
    raise SystemExit('gen_gl_test_shaders: found no case using an es300/ source -- the check cannot see gl_test.c')
if _used != set(ES300_CASES):
    raise SystemExit('gen_gl_test_shaders: ES300_CASES disagrees with gl_test.c: missing %s, extra %s'
                     % (sorted(_used - set(ES300_CASES)), sorted(set(ES300_CASES) - _used)))
subst = (('@N', str(len(ES300_CASES))),
         ('@LIST', ', '.join(str(c) for c in ES300_CASES)),
         ('@COND', ' || '.join('(c) == %d' % c for c in ES300_CASES)))
head = []
for line in ES100_HEAD:
    for k, v in subst:
        line = line.replace(k, v)
    head.append(line)
emit('gl_test_shaders_es100.h', ES100_TWINS, head)
