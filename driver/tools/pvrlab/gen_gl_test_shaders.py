"""Regenerate the two gl_test shader headers: the GLSL sources gl_test.c feeds to
glShaderSource, as C strings byte-identical to yakogl/tools/shaders/* (the offline
shader table matches by SHA-256 of the text, so a stray byte here is a miss there).

  gl_test_shaders.h        the default set. Thirteen of its sources are #version 450
                           written for SPIR-V; the rest are ES 1.00 or ES 3.00.
  gl_test_shaders_es100.h  the same symbols, with those thirteen replaced by their
                           GLSL ES 1.00 twins from tools/shaders/gl_test_es100/.
                           Selected by GL_TEST_ES100 (default off). It is what an
                           ES 2.0 application would have written, and therefore the
                           only set an ES 2.0 compiler can be asked to compile.

The ES 1.00 header also names the cases it cannot serve: a case whose GLSL is
"#version 300 es" has no ES 1.00 form at all, so it is skipped BY NAME rather than
left to fail at the version line (a failure there would say the compiler is broken
when the truth is that the case is out of its scope).

  --check  write nothing: regenerate both headers and refuse a drift against the
           committed ones. tools/check.sh runs this. The headers hold the only
           copy of the GLSL gl_test.c compiles, while the source list, the offline
           table and the host tests all name tools/shaders/ instead -- so a header
           that is not that text is a suite drawing one program while everything
           else checks another."""
