#include <stdio.h>
#include <stddef.h>
#include "rgx_fwif_km.h"
#define O(s,f) printf("  %-40s off=%4zu\n", #f, offsetof(s,f))
int main(void){
  printf("sizeof(RGXFWIF_FWCOMMONCONTEXT)=%zu\n", sizeof(RGXFWIF_FWCOMMONCONTEXT));
  O(RGXFWIF_FWCOMMONCONTEXT,psCCBCtl);
  O(RGXFWIF_FWCOMMONCONTEXT,psCCB);
  O(RGXFWIF_FWCOMMONCONTEXT,psContextState);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32FWComCtxFlags);
  O(RGXFWIF_FWCOMMONCONTEXT,i32Priority);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32PrioritySeqNum);
  O(RGXFWIF_FWCOMMONCONTEXT,psRFCmd);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32CompatFlags);
  O(RGXFWIF_FWCOMMONCONTEXT,i32StatsNumStores);
  O(RGXFWIF_FWCOMMONCONTEXT,sBufStalledNode);
  O(RGXFWIF_FWCOMMONCONTEXT,ui64CBufQueueCtrlAddr);
  O(RGXFWIF_FWCOMMONCONTEXT,ui64RobustnessAddress);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32MaxDeadlineMS);
  O(RGXFWIF_FWCOMMONCONTEXT,bReadOffsetNeedsReset);
  O(RGXFWIF_FWCOMMONCONTEXT,sWaitingNode);
  O(RGXFWIF_FWCOMMONCONTEXT,sRunNode);
  O(RGXFWIF_FWCOMMONCONTEXT,sLastFailedUFO);
  O(RGXFWIF_FWCOMMONCONTEXT,psFWMemContext);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32ServerCommonContextID);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32PID);
  O(RGXFWIF_FWCOMMONCONTEXT,szProcName);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32DeferCount);
  O(RGXFWIF_FWCOMMONCONTEXT,bCancelRangesActive);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32UID);
  O(RGXFWIF_FWCOMMONCONTEXT,ui32WorkEstCCBSubmitted);
  O(RGXFWIF_FWCOMMONCONTEXT,sRangeCheckBeforeUse);
  O(RGXFWIF_FWCOMMONCONTEXT,uDMSpecific);
  printf("\nsizeof(RGXFWIF_FWRENDERCONTEXT)=%zu\n", sizeof(RGXFWIF_FWRENDERCONTEXT));
  O(RGXFWIF_FWRENDERCONTEXT,sTAContext);
  O(RGXFWIF_FWRENDERCONTEXT,s3DContext);
  printf("\nsizeof(RGXFWIF_KCCB_CMD)=%zu\n", sizeof(RGXFWIF_KCCB_CMD));
  O(RGXFWIF_KCCB_CMD,eCmdType);O(RGXFWIF_KCCB_CMD,ui32KCCBFlags);O(RGXFWIF_KCCB_CMD,uCmdData);
  printf("sizeof(RGXFWIF_KCCB_CMD_KICK_DATA)=%zu\n", sizeof(RGXFWIF_KCCB_CMD_KICK_DATA));
  O(RGXFWIF_KCCB_CMD_KICK_DATA,psContext);O(RGXFWIF_KCCB_CMD_KICK_DATA,ui32CWoffUpdate);
  O(RGXFWIF_KCCB_CMD_KICK_DATA,ui32CWrapMaskUpdate);O(RGXFWIF_KCCB_CMD_KICK_DATA,ui32NumCleanupCtl);
  O(RGXFWIF_KCCB_CMD_KICK_DATA,apsCleanupCtl);

  /* The CLEANUP command: a layout this driver had never posted until the HWRT
   * recycle handshake, so its offsets are checked rather than assumed. */
  printf("\nsizeof(RGXFWIF_CLEANUP_REQUEST)=%zu\n", sizeof(RGXFWIF_CLEANUP_REQUEST));
  O(RGXFWIF_CLEANUP_REQUEST,eCleanupType);O(RGXFWIF_CLEANUP_REQUEST,uCleanupData);
  printf("  RGXFWIF_CLEANUP_FWCOMMONCONTEXT=%d HWRTDATA=%d FREELIST=%d ZSBUFFER=%d\n",
         (int)RGXFWIF_CLEANUP_FWCOMMONCONTEXT, (int)RGXFWIF_CLEANUP_HWRTDATA,
         (int)RGXFWIF_CLEANUP_FREELIST, (int)RGXFWIF_CLEANUP_ZSBUFFER);
  printf("\nsizeof(RGXFWIF_HWRTDATA)=%zu\n", sizeof(RGXFWIF_HWRTDATA));
#if defined(PM_INTERACTIVE_MODE)
  printf("  PM_INTERACTIVE_MODE=1\n");
  O(RGXFWIF_HWRTDATA,psPMMListDevVAddr);
#else
  printf("  PM_INTERACTIVE_MODE=0 (the firmware uses sPMRenderStateDevVAddr at this offset)\n");
  O(RGXFWIF_HWRTDATA,sPMRenderStateDevVAddr);
#endif
  O(RGXFWIF_HWRTDATA,ui64VCECatBase);O(RGXFWIF_HWRTDATA,ui64VCELastCatBase);
  O(RGXFWIF_HWRTDATA,ui64TECatBase);O(RGXFWIF_HWRTDATA,ui64TELastCatBase);
  O(RGXFWIF_HWRTDATA,ui64AlistCatBase);O(RGXFWIF_HWRTDATA,ui64AlistLastCatBase);
  O(RGXFWIF_HWRTDATA,ui64PMAListStackPointer);O(RGXFWIF_HWRTDATA,ui32PMMListStackPointer);
  O(RGXFWIF_HWRTDATA,sHWRTDataCommonFwAddr);O(RGXFWIF_HWRTDATA,ui32HWRTDataFlags);
  O(RGXFWIF_HWRTDATA,eState);O(RGXFWIF_HWRTDATA,apsFreeLists);
  O(RGXFWIF_HWRTDATA,aui32FreeListHWRSnapshot);O(RGXFWIF_HWRTDATA,psVHeapTableDevVAddr);
  O(RGXFWIF_HWRTDATA,sTailPtrsDevVAddr);O(RGXFWIF_HWRTDATA,sMacrotileArrayDevVAddr);
  O(RGXFWIF_HWRTDATA,sRgnHeaderDevVAddr);O(RGXFWIF_HWRTDATA,sRTCDevVAddr);
  O(RGXFWIF_HWRTDATA,sCleanupState);

  /* The freelist grow handshake: FW -> host request, host -> FW answer. */
  printf("\nsizeof(RGXFWIF_FWCCB_CMD)=%zu\n", sizeof(RGXFWIF_FWCCB_CMD));
  O(RGXFWIF_FWCCB_CMD,eCmdType);O(RGXFWIF_FWCCB_CMD,uCmdData);
  printf("sizeof(RGXFWIF_FWCCB_CMD_FREELIST_GS_DATA)=%zu\n",
         sizeof(RGXFWIF_FWCCB_CMD_FREELIST_GS_DATA));
  O(RGXFWIF_FWCCB_CMD_FREELIST_GS_DATA,ui64FreelistID);
  printf("sizeof(RGXFWIF_FREELIST_GS_DATA)=%zu\n",
         sizeof(RGXFWIF_FREELIST_GS_DATA));
  O(RGXFWIF_FREELIST_GS_DATA,sFreeListFWDevVAddr);
  O(RGXFWIF_FREELIST_GS_DATA,ui32DeltaPages);
  O(RGXFWIF_FREELIST_GS_DATA,ui32NewPages);
  printf("sizeof(RGXFWIF_FREELIST)=%zu\n", sizeof(RGXFWIF_FREELIST));
  O(RGXFWIF_FREELIST,ui32MaxPages);O(RGXFWIF_FREELIST,ui32CurrentPages);
  O(RGXFWIF_FREELIST,ui32GrowPages);O(RGXFWIF_FREELIST,ui32ReadyPages);
  O(RGXFWIF_FREELIST,bGrowPending);O(RGXFWIF_FREELIST,ui32CurrentStackTop);
  O(RGXFWIF_FREELIST,ui64FreeListID);

  printf("  RTN_SLOT_CMD_EXECUTED=0x%x CLEANUP_BUSY=0x%x POLL_FAILURE=0x%x NO_RESPONSE=0x%x\n",
         RGXFWIF_KCCB_RTN_SLOT_CMD_EXECUTED, RGXFWIF_KCCB_RTN_SLOT_CLEANUP_BUSY,
         RGXFWIF_KCCB_RTN_SLOT_POLL_FAILURE, RGXFWIF_KCCB_RTN_SLOT_NO_RESPONSE);
  return 0;
}
